// Урок 21.5. Ограничение градиента.
//
// Что изучаем: Ограничение градиента.
// Зачем это нужно: Clipping не даёт слишком большому градиенту вызвать резкое изменение параметра.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `gradient` для следующих операций.
    let gradient = 12.0;
    // Сохраняем рассчитанное значение `limit` для следующих операций.
    let limit = 1.0;
    // Сохраняем рассчитанное значение `clipped` для следующих операций.
    let clipped = if gradient > limit {
        // Используем ранее рассчитанное значение `limit` в текущем выражении.
        limit
    } else if gradient < -limit {
        // Складываем или вычитаем величины согласно используемой формуле.
        -limit
    } else {
        // Используем ранее рассчитанное значение `gradient` в текущем выражении.
        gradient
    };
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("исходный градиент={gradient}, после clipping={clipped}");
}
