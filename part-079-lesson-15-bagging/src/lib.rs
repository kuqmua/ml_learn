//! Вычисления и примеры урока part-079-lesson-15-bagging.

// Урок 15.1. Bagging.
//
// Что изучаем: Bagging.
// Зачем это нужно: Обучаем несколько моделей на разных bootstrap-выборках, затем объединяем ответы,
// уменьшая зависимость от одной выборки.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Создаём набор значений `model_predictions` для следующего шага примера.
    let model_predictions = [true, false, true, true, false];
    // Преобразуем входные данные и сохраняем полученную коллекцию в `positive_votes`.
    let positive_votes = model_predictions.iter().filter(|&&vote| vote).count();
    // Считаем количество элементов и сохраняем его в `bagged_prediction`.
    let bagged_prediction = positive_votes * 2 > model_predictions.len();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("голосов за класс 1: {positive_votes}; ансамбль={bagged_prediction}");
}
