// Урок 42.4. Определение выводов, которые нельзя сделать по малому проверочному набору.
// Связь с принятой терминологией: Ограничения оценки модели по малой выборке.
// Зачем здесь эта тема: Небольшое число новых меток делает оценку качества нестабильной.
// Почему код устроен так: Показываем, как один исход меняет долю ошибок при малой выборке.
// Представь: Если проверили только четыре новых случая, одна ошибка меняет долю ошибок сразу на 25
//   пунктов.
//
// Что изучаем: Ограничения модели.
// Зачем это нужно: На маленькой выборке высокая метрика нестабильна; отчёт должен показывать размер набора
// вместе с результатом.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
use lesson_trace::{enable, trace_note, trace_step};

fn main() {
    enable();
    trace_note!("Сохраняем рассчитанное значение `correct` для следующих операций.");
    let correct: i32 = 2;
    trace_step!(correct);
    trace_note!("Сохраняем рассчитанное значение `total` для следующих операций.");
    let total: i32 = 2;
    trace_step!(total);
    trace_note!("Нормируем или усредняем величину делением и сохраняем её в `accuracy`.");
    let accuracy: f64 = correct as f64 / total as f64;
    trace_step!(accuracy);
    trace_note!("Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.");
    println!("accuracy={accuracy:.2} на {total} объектах: вывод ненадёжен");
}
