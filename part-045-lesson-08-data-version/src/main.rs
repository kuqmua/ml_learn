// Урок 08.5. Версия данных.
//
// Что изучаем: Версия данных.
// Зачем это нужно: Отпечаток входа помогает отличить два набора, даже когда имя файла одинаково.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `data` для следующих операций.
    let data = "1,0\n2,1\n";
    // Преобразуем входные данные и сохраняем полученную коллекцию в `hasher`.
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    // Описываем или заполняем поле `std` этого значения.
    std::hash::Hash::hash(data, &mut hasher);
    // Сохраняем рассчитанное значение `fingerprint` для следующих операций.
    let fingerprint = std::hash::Hasher::finish(&hasher);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("отпечаток данных = {fingerprint}");
}
