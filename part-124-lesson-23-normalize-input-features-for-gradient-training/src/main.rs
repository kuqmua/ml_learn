// Урок 23.4. Нормализация входных признаков для обучения по градиенту.
// Почему этот урок сейчас: Разные масштабы признаков делают градиентные шаги несоразмерными.
// Почему пример устроен так: Вычитаем среднее train из его значений, чтобы отдельно увидеть эффект центрирования.
//
// Что изучаем: Нормализация признаков.
// Зачем это нужно: Приведение признаков к сопоставимому масштабу помогает градиентным шагам работать с
// разными координатами.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Создаём набор значений `training_data` для следующего шага примера.
    let training_data: [f64; 3] = [10.0, 20.0, 30.0];
    lesson_trace::trace_step!(training_data);
    // Проверяем ожидаемое свойство учебного примера.
    assert!(
        !training_data.is_empty(),
        "обучающая выборка не должна быть пустой"
    );
    // Преобразуем входные данные и сохраняем полученную коллекцию в `mean`.
    let mean: f64 =
        part_029_lesson_06_arithmetic_mean_of_numeric_values::arithmetic_mean_of_numeric_values(
            &training_data,
        )
        .unwrap();
    lesson_trace::trace_step!(mean);
    // Преобразуем входные данные и сохраняем полученную коллекцию в `centered`.
    let centered: Vec<f64> = training_data.iter().map(|&value| value - mean).collect();
    lesson_trace::trace_step!(centered);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("среднее train={mean}, центрировано={centered:?}");

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_normalize_input_features_for_gradient_training(training_data, centered);
}

// Строим график по результатам урока.
fn visualize_normalize_input_features_for_gradient_training(
    training_data: [f64; 3],
    centered: std::vec::Vec<f64>,
) {
    // График величин и зависимостей, изученных в этом уроке.
    let original_points: Vec<(f64, f64)> = training_data
        // Просматриваем элементы коллекции по ссылке.
        .iter()
        // Добавляем порядковый номер к каждому элементу.
        .enumerate()
        // Преобразуем каждый элемент в новое значение.
        .map(|(item_index, &element_value)| (item_index as f64, element_value))
        // Собираем результаты в коллекцию.
        .collect();
    // Собираем значения для `normalized_points` в коллекцию.
    let normalized_points: Vec<(f64, f64)> = centered
        // Просматриваем элементы коллекции по ссылке.
        .iter()
        // Добавляем порядковый номер к каждому элементу.
        .enumerate()
        // Преобразуем каждый элемент в новое значение.
        .map(|(item_index, &element_value)| (item_index as f64, element_value))
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Центрирование признака",
        // Указываем подпись горизонтальной оси.
        "номер объекта",
        // Указываем подпись вертикальной оси.
        "значение",
        // Передаём ряды или значения для отрисовки графика.
        &[
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "до",
                // Передаём рассчитанные координаты точек.
                points: &original_points,
            },
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "после",
                // Передаём рассчитанные координаты точек.
                points: &normalized_points,
            },
        ],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
