// Урок 10.4. Преобразование прогнозной вероятности в класс по порогу.
// Почему этот урок сейчас: Вероятность ещё не является меткой класса; решение зависит от выбранного порога.
// Почему пример устроен так: Сравниваем одну вероятность с порогом, чтобы увидеть смену класса без переобучения модели.
//
// Что изучаем: Порог классификации.
// Зачем это нужно: Порог превращает вероятность в метку класса. Более низкий порог обычно даёт больше
// положительных прогнозов.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Создаём набор значений `probabilities` для следующего шага примера.
    let probabilities: [f64; 3] = [0.2, 0.55, 0.8];
    lesson_trace::trace_step!(probabilities);
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for threshold in [0.5, 0.7] {
        lesson_trace::trace_step!(threshold);
        // Преобразуем входные данные и сохраняем полученную коллекцию в `predictions`.
        let predictions: Vec<bool> = probabilities
            .iter()
            .map(|&probability| probability >= threshold)
            .collect();
        lesson_trace::trace_step!(predictions);
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("порог {threshold}: {predictions:?}");
    }

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_convert_predicted_probability_to_class_using_threshold();
}

// Строим график по результатам урока.
fn visualize_convert_predicted_probability_to_class_using_threshold() {
    // График величин и зависимостей, изученных в этом уроке.
    let threshold_points: Vec<(f64, f64)> = (0..=100)
        // Преобразуем каждый элемент в новое значение.
        .map(|plot_step_index| {
            // Сохраняем результат этого шага в `threshold_value`.
            let threshold_value: f64 = plot_step_index as f64 / 100.0;
            (
                // Используем подготовленное значение в следующем шаге примера.
                threshold_value,
                // Задаём значения следующей строки или последовательности.
                [0.2, 0.55, 0.8]
                    .iter()
                    .filter(|&&probability| probability >= threshold_value)
                    .count() as f64,
            )
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Число положительных прогнозов",
        // Указываем подпись горизонтальной оси.
        "порог",
        // Указываем подпись вертикальной оси.
        "количество",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "оценки 0.2, 0.55, 0.8",
            // Передаём рассчитанные координаты точек.
            points: &threshold_points,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
