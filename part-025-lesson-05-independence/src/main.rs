// Зачем это нужно: События независимы, когда совместная вероятность равна результату умножения отдельных
// вероятностей.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Для двух честных монет P(орёл)=1/2, P(оба орла)=1/4.
    let first_head = 0.5;
    // Инициализируем значение `second_head` начальным состоянием.
    let second_head = 0.5;
    // Инициализируем значение `both_heads` начальным состоянием.
    let both_heads = 0.25;
    // Умножаем значения и сохраняем результат в `independent`.
    let independent = both_heads == first_head * second_head;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("монеты независимы: {independent}");
}
