// Урок 32.2. Выход с остаточной связью: прибавление исходного входа к преобразованию.
// Связь с принятой терминологией: Добавление входа блока через остаточную связь.
// Зачем здесь эта тема: Сложный блок может потерять исходные признаки и затруднить передачу
//   градиента.
// Почему код устроен так: Прибавляем вход к преобразованному выходу, сохраняя прямой путь
//   информации.
// Представь: Если новое преобразование почти бесполезно, residual всё равно пропускает исходный
//   вход дальше.
//
// Что изучаем: Остаточная связь.
// Зачем это нужно: Residual добавляет вход блока к его преобразованию, сохраняя исходный сигнал для
// следующих слоёв.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.

fn main() {
    let input: [f64; 2] = [1.0, 2.0];
    let transformed: [f64; 2] = [0.2, -0.5];
    let output: [f64; 2] = [input[0] + transformed[0], input[1] + transformed[1]];

    plot_first_coordinate_before_and_after_adding_block_input(input, output);
}

// Строим график по результатам урока.
fn plot_first_coordinate_before_and_after_adding_block_input(input: [f64; 2], output: [f64; 2]) {
    let _chart: std::path::PathBuf = lesson_visualization::bar_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Остаточная связь",
        "первая компонента",
        &[("вход", input[0]), ("после", output[0])],
    )
    .expect("не удалось сохранить график");
}
