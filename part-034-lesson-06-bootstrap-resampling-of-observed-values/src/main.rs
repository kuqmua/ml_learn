// Урок 06.6. Повторные выборки с возвращением из наблюдений.
//
// Что изучаем: Bootstrap.
// Зачем это нужно: Повторная выборка с возвращением показывает, как меняется оценка при перестановке
// наблюдений.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `values` для следующего шага примера.
    let values: [f64; 3] = [2.0, 4.0, 6.0];
    // Создаём набор значений `resamples` для следующего шага примера.
    let resamples: [[usize; 3]; 4] = [[0, 1, 2], [0, 0, 2], [1, 2, 2], [0, 1, 1]];
    // Проверяем ожидаемое свойство учебного примера.
    assert!(!values.is_empty(), "исходная выборка не должна быть пустой");
    // Повторяем следующий блок для каждой повторной выборки.
    for indices in resamples {
        // Проверяем ожидаемое свойство учебного примера.
        assert!(
            // Используем подготовленное значение в следующем шаге примера.
            !indices.is_empty(),
            // Передаём подпись или текстовое значение для следующего шага.
            "повторная выборка не должна быть пустой"
        );
        // Проверяем ожидаемое свойство учебного примера.
        assert!(
            // Используем подготовленное значение в следующем шаге примера.
            indices.iter().all(|&index| index < values.len()),
            // Передаём подпись или текстовое значение для следующего шага.
            "индекс выходит за границы исходной выборки"
        );
        // Инициализируем изменяемый накопитель `sum` начальным состоянием.
        let mut sum: f64 = 0.0;
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for index in indices {
            // Прибавляем очередной вклад к ранее накопленному результату.
            sum += values[index];
        }
        // Считаем количество элементов и сохраняем его в `mean`.
        let mean: f64 = sum / indices.len() as f64;
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("индексы {indices:?} -> среднее {mean:.2}");
    }

    // Построение графика вынесено из основного кода урока.
    visualize_bootstrap_resampling_of_observed_values(values, resamples);
}

// Строим график по результатам урока.
fn visualize_bootstrap_resampling_of_observed_values(values: [f64; 3], resamples: [[usize; 3]; 4]) {
    // Показываем значения, рассчитанные по данным примера.
    // Повторную выборку с возвращением называют bootstrap sample.
    let resampled_mean_points: Vec<(f64, f64)> = resamples
        // Просматриваем элементы коллекции по ссылке.
        .iter()
        // Добавляем порядковый номер к каждому элементу.
        .enumerate()
        // Преобразуем каждый элемент в новое значение.
        .map(|(item_index, indices)| {
            (
                // Вычисляем значение по указанной формуле.
                (item_index + 1) as f64,
                // Вычисляем значение по указанной формуле.
                indices
                    .iter()
                    .map(|&sample_index| values[sample_index])
                    .sum::<f64>()
                    / indices.len() as f64,
            )
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Bootstrap: средние повторных выборок",
        // Указываем подпись горизонтальной оси.
        "номер выборки",
        // Указываем подпись вертикальной оси.
        "среднее",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "среднее",
            // Передаём рассчитанные координаты точек.
            points: &resampled_mean_points,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
