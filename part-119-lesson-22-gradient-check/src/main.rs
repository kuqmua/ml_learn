// Урок 22.4. Проверка градиента.
//
// Что изучаем: Проверка градиента.
// Зачем это нужно: Сравниваем аналитическую производную с центральной численной разностью на малом
// примере.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `x` для следующих операций.
    let x = 3.0;
    // Инициализируем значение `h` начальным состоянием.
    let h = 0.0001;
    // Умножаем значения и сохраняем результат в `analytical`.
    let analytical = 2.0 * x;
    // Умножаем значения и сохраняем результат в `right`.
    let right = (x + h) * (x + h);
    // Умножаем значения и сохраняем результат в `left`.
    let left = (x - h) * (x - h);
    // Нормируем или усредняем величину делением и сохраняем её в `numerical`.
    let numerical = (right - left) / (2.0 * h);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("аналитически={analytical}, численно={numerical}");
    // График величин и зависимостей, изученных в этом уроке.
    let chart_points_0: Vec<(f64, f64)> = (1..=100)
        .map(|i| {
            let h = i as f64 / 100.0;
            (h, (((3.0 + h) * (3.0 + h) - 9.0) / h - 6.0).abs())
        })
        .collect();
    let chart = lesson_visualization::line_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Проверка градиента",
        "шаг h",
        "разность",
        &[lesson_visualization::Series {
            name: "x² в x=3",
            points: &chart_points_0,
        }],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
