// Урок 02.1. Форма матрицы.
//
// Что изучаем: Форма матрицы.
// Зачем это нужно: Число строк и столбцов определяет, как линейный массив разбивается на ячейки. Проверка
// формы нужна до любого обращения к элементу.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `rows` для следующих операций.
    let rows = 2;
    // Сохраняем рассчитанное значение `columns` для следующих операций.
    let columns = 3;
    // Создаём набор значений `elements` для следующего шага примера.
    let elements = [1, 2, 3, 4, 5, 6];
    // Форма 2×3 требует ровно шесть элементов.
    assert_eq!(rows * columns, elements.len());
    // Сохраняем рассчитанное значение `row` для следующих операций.
    let row = 1;
    // Сохраняем рассчитанное значение `column` для следующих операций.
    let column = 2;
    // В построчной записи индекс ячейки равен row * columns + column.
    let value = elements[row * columns + column];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("форма {rows}×{columns}, элемент [{row}, {column}] = {value}");
}
