// Урок 01.2. Норма L1.
//
// Что изучаем: Норма L1.
// Зачем это нужно: Изучаем сумму модулей координат: она измеряет размер вектора без сокращения
// положительных и отрицательных частей друг другом. Для [3, −4] результат равен |3| + |−4| = 7. Поменяй
// знаки координат и проверь, что норма не изменится.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Отрицательная координата помогает увидеть, зачем нужен модуль.
    let vector = [3.0, -4.0];
    // Инициализируем изменяемый накопитель `l1_norm` начальным состоянием.
    let mut l1_norm = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for coordinate in vector {
        // Модуль возвращает неотрицательный вклад каждой координаты.
        let absolute_value = if coordinate < 0.0 {
            // Складываем или вычитаем величины согласно используемой формуле.
            -coordinate
        } else {
            // Используем ранее рассчитанное значение `coordinate` в текущем выражении.
            coordinate
        };
        // Прибавляем очередной вклад к ранее накопленному результату.
        l1_norm += absolute_value;
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("норма L1 = {l1_norm}");
}
