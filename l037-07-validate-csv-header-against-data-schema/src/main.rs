// Представь: Если код ждёт столбцы age и city, файл со столбцом price вместо age нужно отклонить до
//   расчётов.
//
// Что изучаем: Схема данных.
// Зачем это нужно: Схема задаёт имена колонок и ожидаемые типы. Проверка заголовка предотвращает
// незаметную перестановку признаков.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.

fn main() {
    let comma_separated_values_text: &str = "feature,target\n1.5,0\n2.5,1\n";
    let mut lines: std::str::Lines<'_> = comma_separated_values_text.lines();

    assert_eq!(
        lines
            .next()
            .expect("CSV пустой: ожидается строка заголовка"),
        "feature,target",
        "неверная схема CSV"
    );
    let _: usize = lines.count();
}

