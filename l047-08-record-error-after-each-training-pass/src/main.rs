// Урок 047. Записывать ошибку после последовательных шагов настоящего обновления параметра.
// По журналу проверяем, что обучение на этом примере приближает вес к нужному значению.

fn main() {
    let mut weight: f64 = 0.0;
    let mut history = Vec::new();
    for epoch in 0..5 {
        let loss = (weight - 3.0).powi(2);
        history.push(loss);
        println!("Проход {epoch}: вес={weight:.4}, ошибка={loss:.6}");
        weight -= 0.2 * 2.0 * (weight - 3.0);
    }
    assert!(history.windows(2).all(|pair| pair[1] < pair[0]));
    println!("Журнал позволяет проверить, что ошибка действительно уменьшается.");
}

