// Сводная практика 33. Инференс через CLI.
//
// Что повторяем вместе: контракт входа/выхода, пакетная обработка, ошибки, производительность.
// Зачем это нужно: Инференс через CLI принимает внешние данные, проверяет схему и выдаёт предсказания либо
//   понятную ошибку.
// Что показывает программа: Считываем CSV из стандартного ввода. При пустом stdin запускаем встроенный
//   демонстрационный набор. Печатаем прогнозы либо явную ошибку формата.
// Что проверить при изменении примера: Проверь пустой ввод, неверную схему, стабильность порядка строк и
//   время на крупном наборе.
// Дополнительная практика: Сделай CLI для пакетных прогнозов по CSV или JSONL с явным форматом результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Шаг: Считываем CSV из стандартного ввода.
    let mut input_csv = String::new();
    // Читаем весь CSV из стандартного ввода через трейт `Read`.
    std::io::Read::read_to_string(&mut std::io::stdin(), &mut input_csv)?;
    // Шаг: При пустом stdin запускаем встроенный демонстрационный набор.
    if input_csv.is_empty() {
        // Обновляем `input_csv` результатом текущего шага.
        input_csv = "feature\n1\n2\n3\n".into();
    }

    // Шаг: Печатаем прогнозы либо явную ошибку формата.
    match (|| -> Result<String, String> {
        // Используем подготовленное значение в следующем шаге примера.
        /* Проверяем схему CSV и обрабатываем строки в исходном порядке. */
        // Сохраняем результат этого шага в `input_csv`.
        let input_csv: &str = &input_csv;
        // Создаём изменяемое значение `lines` для следующих операций.
        let mut lines = input_csv.lines();
        // Разбираем наличие значения перед использованием результата.
        if lines.next() != Some("feature") {
            // Прерываем расчёт и явно сообщаем причину некорректного входа.
            return Err("ожидается заголовок feature".into());
        }
        // Создаём изменяемое значение `output_csv` для следующих операций.
        let mut output_csv = String::from("prediction\n");
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for (row_index, line) in lines.enumerate() {
            // Сохраняем рассчитанное значение `feature_value` для следующих операций.
            let feature_value: f64 = line
                // Преобразуем текстовое поле в требуемый числовой тип.
                .parse()
                // Складываем или вычитаем величины согласно используемой формуле.
                .map_err(|_| format!("строка {}: не число", row_index + 2))?;
            // Отсекаем бесконечные и неопределённые числовые значения.
            if !feature_value.is_finite() {
                // Прерываем расчёт и явно сообщаем причину некорректного входа.
                return Err(format!("строка {}: не конечное число", row_index + 2));
            }
            // Умножаем величины согласно используемой формуле.
            output_csv.push_str(&format!("{}\n", 2. * feature_value + 1.));
        }
        // Возвращаем успешное значение в типе `Result`.
        Ok(output_csv)
    })() {
        // Возвращаем успешное значение в типе `Result`.
        Ok(result) => print!("{result}"),
        // Возвращаем описание ошибки в типе `Result`.
        Err(error) => {
            // Выполняем очередное действие, после которого продолжаем следующий шаг.
            eprintln!("{error}");
            // При ошибке формата завершаем процесс с ненулевым кодом.
            std::process::exit(1)
        }
    }
    // Возвращаем успешное значение в типе `Result`.
    Ok(())
}
