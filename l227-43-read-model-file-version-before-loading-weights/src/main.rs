// Урок 43.2. Чтение версии файла модели перед загрузкой весов.
// Связь с принятой терминологией: Чтение версии формата модели перед загрузкой.
// Зачем здесь эта тема: Формат сохранения со временем меняется; загрузчик должен знать, как читать
//   старый файл.
// Почему код устроен так: Считываем версию до остальных полей и выбираем соответствующие правила
//   разбора.
// Представь: Файл версии 1 может иметь меньше полей, чем файл версии 2; читатель выбирает правила
//   по номеру версии.
//
// Загрузчик различает поддерживаемый формат, другую версию и отсутствие строки версии.

fn main() {
    for (_description, saved_model_text, expected) in [
        ("поддерживаемый формат", "model_v1\n2.0\n1.0\n", "model_v1"),
        (
            "другая версия",
            "model_v2\n2.0\n1.0\n",
            "неизвестный формат",
        ),
        ("пустой файл", "", "нет версии"),
    ] {
        let status: &str = match saved_model_text.lines().next() {
            Some("model_v1") => "model_v1",

            Some(_) => "неизвестный формат",

            None => "нет версии",
        };
        assert_eq!(status, expected);
    }
}
