// Урок 13.3. Сглаживание Лапласа.
//
// Что изучаем: Сглаживание Лапласа.
// Зачем это нужно: Прибавление единицы к частотам не даёт неизвестному слову обнулить вероятность всего
// текста.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Инициализируем значение `observed_count` начальным состоянием.
    let observed_count = 0.0;
    // Сохраняем рассчитанное значение `total_words_in_class` для следующих операций.
    let total_words_in_class = 8.0;
    // Сохраняем рассчитанное значение `vocabulary_size` для следующих операций.
    let vocabulary_size = 4.0;
    // Нормируем или усредняем величину делением и сохраняем её в `unsmoothed`.
    let unsmoothed = observed_count / total_words_in_class;
    // Нормируем или усредняем величину делением и сохраняем её в `smoothed`.
    let smoothed = (observed_count + 1.0) / (total_words_in_class + vocabulary_size);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("без сглаживания={unsmoothed}, со сглаживанием={smoothed}");
    // График величин и зависимостей, изученных в этом уроке.
    let chart_points_0: Vec<(f64, f64)> = (0..=8).map(|n| (n as f64, n as f64 / 10.0)).collect();
    let chart_points_1: Vec<(f64, f64)> = (0..=8)
        .map(|n| (n as f64, (n as f64 + 1.0) / 12.0))
        .collect();
    let chart = lesson_visualization::line_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Сглаживание Лапласа",
        "частота токена",
        "оценка вероятности",
        &[
            lesson_visualization::Series {
                name: "без сглаживания",
                points: &chart_points_0,
            },
            lesson_visualization::Series {
                name: "со сглаживанием",
                points: &chart_points_1,
            },
        ],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
