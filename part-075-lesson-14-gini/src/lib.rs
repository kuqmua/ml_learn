//! Вычисления и примеры урока part-075-lesson-14-gini.

// Урок 14.2. Нечистота Gini.
//
// Что изучаем: Нечистота Gini.
// Зачем это нужно: Gini равна единице минус сумма квадратов долей классов; чистому узлу соответствует
// ноль.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for positive_fraction in [0.0, 0.5, 1.0] {
        // Комбинируем исходные величины и сохраняем результат в `negative_fraction`.
        let negative_fraction = 1.0 - positive_fraction;
        // Сохраняем рассчитанное значение `gini` для следующих операций.
        let gini =
            // Умножаем величины согласно используемой формуле.
            1.0 - positive_fraction * positive_fraction - negative_fraction * negative_fraction;
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("доля положительных={positive_fraction}, Gini={gini}");
    }
}
