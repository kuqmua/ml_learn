// Урок 218. Выбирать действие по большей из готовых оценок будущей награды.
// Это правило использования уже известных оценок; сами оценки в примере не обучаются.

fn main() {
    for (left, right, expected) in [
        (0.2, 0.8, "вправо"),
        (0.9, 0.1, "влево"),
        (0.5, 0.5, "влево"),
    ] {
        let action = if right > left {
            "вправо"
        } else {
            "влево"
        };
        println!("Оценки: влево={left}, вправо={right}; выбор={action}");
        assert_eq!(action, expected);
    }
    println!("При равных оценках здесь явно выбрана левая ветвь.");
}

