//! Вычисления и примеры урока part-023-lesson-04-optimization.

// Сводная практика 04. Градиентный спуск.
//
// Что повторяем вместе: скорость обучения, сходимость, локальные минимумы, batch и stochastic updates.
// Зачем это нужно: Скорость обучения определяет, приблизится ли последовательность обновлений к минимуму
//   или начнёт расходиться.
// Что показывает программа: Запускаем спуск с тремя скоростями обучения. Сохраняем loss после каждого
//   обновления параметра. По первой и последней ошибке видим сходимость или расходимость.
// Что проверить при изменении примера: Покажи успешный, медленный и расходящийся запуск; критерий остановки
//   не должен зависеть только от числа шагов.
// Дополнительная практика: Минимизируй квадратичную функцию и запиши историю loss для нескольких learning
//   rate.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Учебные реализации математических операций для этого урока.

    // Объявляем повторно используемое вычисление `calculate_quadratic_loss`; параметры ниже задают его входы.
    fn calculate_quadratic_loss(parameter: f64) -> f64 {
        // Составляем результат из вычисленных значений в указанном порядке.
        (|| -> f64 {
            /* Возводим число в квадрат обычным умножением. */
            let value: f64 = parameter - 3.0;
            // Умножаем величины согласно используемой формуле.
            value * value
        })()
    }

    // Шаг: Запускаем спуск с тремя скоростями обучения.
    for learning_rate in [0.01, 0.2, 1.1] {
        // Шаг: Сохраняем loss после каждого обновления параметра.
        let history = (|| -> Vec<f64> {
            /* Обновляем параметр против градиента и сохраняем историю ошибки. */
            let learning_rate: f64 = learning_rate;
            // Сохраняем рассчитанное значение `steps` для следующих операций.
            let steps: usize = 30;
            // Инициализируем изменяемый накопитель `parameter` начальным состоянием.
            let mut parameter = 0.0;
            // Создаём набор значений `history` для следующего шага примера.
            let mut history = vec![calculate_quadratic_loss(parameter)];
            // Повторяем следующий блок для каждого элемента указанной последовательности.
            for _ in 0..steps {
                // Выполняем встроенный расчёт один раз и сохраняем результат в `gradient`.
                let gradient = (|| -> f64 {
                    /* Для квадратичной ошибки берём производную 2(x−3). */
                    let parameter: f64 = parameter;
                    // d/dx (x−3)² = 2(x−3).
                    2.0 * (parameter - 3.0)
                })();
                // Проверяем условие и выбираем соответствующую ветку алгоритма.
                if (|| -> f64 {
                    /* Модуль числа по определению: меняем знак только у отрицательного числа. */
                    let value: f64 = gradient;
                    // Проверяем условие и выбираем соответствующую ветку алгоритма.
                    if value < 0.0 { -value } else { value }
                })() < 1e-8
                {
                    // Останавливаем цикл после достижения условия завершения.
                    break;
                }
                // Шагаем против производной: большой learning_rate может вызвать расходимость.
                parameter -= learning_rate * gradient;
                // Сохраняем очередной рассчитанный элемент в коллекции.
                history.push(calculate_quadratic_loss(parameter));
                // Отсекаем бесконечные и неопределённые числовые значения.
                if !parameter.is_finite() {
                    // Останавливаем цикл после достижения условия завершения.
                    break;
                }
            }
            // Используем ранее рассчитанное значение `history` в текущем выражении.
            history
        })();
        // Шаг: По первой и последней ошибке видим сходимость или расходимость.
        println!(
            // Задаём шаблон строки: плейсхолдеры ниже заменятся рассчитанными значениями.
            "rate={learning_rate}, initial={:.4}, final={:.4}, steps={}",
            // Передаём ранее рассчитанное значение в текущую операцию.
            history[0],
            // Складываем или вычитаем величины согласно используемой формуле.
            history[history.len() - 1],
            // Складываем или вычитаем величины согласно используемой формуле.
            history.len() - 1
        );
    }
}
