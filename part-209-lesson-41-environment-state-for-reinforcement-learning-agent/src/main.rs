// Урок 41.1. Состояние среды для агента обучения с подкреплением.
// Зачем здесь эта тема: Обучение с подкреплением начинается с описания того, что агент может
//   наблюдать.
// Почему код устроен так: Задаём маленькое дискретное состояние, прежде чем вводить действия и
//   награды.
// Представь: В маленьком мире состояние может быть просто номером клетки, где сейчас стоит агент.
//
// Что изучаем: Состояние среды.
// Зачем это нужно: Состояние описывает информацию, от которой зависит выбор следующего действия агента.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Сохраняем рассчитанное значение `current_cell` для следующих операций.
    let current_cell: i32 = 2;
    lesson_trace::trace_step!(current_cell);
    // Сохраняем рассчитанное значение `goal_cell` для следующих операций.
    let goal_cell: i32 = 4;
    lesson_trace::trace_step!(goal_cell);
    // Комбинируем исходные величины и сохраняем результат в `distance_to_goal`.
    let distance_to_goal: i32 = goal_cell - current_cell;
    lesson_trace::trace_step!(distance_to_goal);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("состояние: клетка={current_cell}, до цели={distance_to_goal}");

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_environment_state_for_reinforcement_learning_agent();
}

// Строим график по результатам урока.
fn visualize_environment_state_for_reinforcement_learning_agent() {
    // Значения из этого урока на графике.
    let state_points: Vec<(f64, f64)> = (0..=5)
        .map(|plot_step_index| (plot_step_index as f64, (5 - plot_step_index) as f64))
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Расстояние до цели",
        // Указываем подпись горизонтальной оси.
        "позиция",
        // Указываем подпись вертикальной оси.
        "шагов осталось",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "линейная среда",
            // Передаём рассчитанные координаты точек.
            points: &state_points,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
