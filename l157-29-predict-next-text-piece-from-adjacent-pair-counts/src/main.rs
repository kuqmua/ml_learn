// Урок 157. Выбирать следующее слово по наибольшему счётчику пары с текущим словом.
// Так получаем простейшее продолжение текста, учитывающее только один предыдущий элемент.

fn main() {
    let transitions = [("я", "учу", 3), ("я", "пишу", 1), ("учу", "rust", 2)];
    for current in ["я", "учу", "неизвестно"] {
        let best = transitions
            .iter()
            .filter(|entry| entry.0 == current)
            .max_by_key(|entry| entry.2)
            .map(|entry| entry.1);
        println!("После {current:?}: {best:?}");
        if current == "я" {
            assert_eq!(best, Some("учу"));
        }
        if current == "неизвестно" {
            assert_eq!(best, None);
        }
    }
}

