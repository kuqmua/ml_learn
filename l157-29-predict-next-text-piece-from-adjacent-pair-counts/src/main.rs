// Урок 29.1. Прогноз следующей части текста по частотам соседних пар.
// Зачем здесь эта тема: Простейшая языковая модель показывает, что следующий токен зависит от
//   контекста, пока только от одного предыдущего.
// Почему код устроен так: Считаем частоты пар токенов и нормируем их в условные вероятности.
// Представь: После слова «добрый» чаще встречается «день», если эта пара часто была в обучающем
//   тексте.
//
// Что изучаем: Предсказание следующего токена.
// Зачем это нужно: По частотам переходов выбираем наиболее вероятное продолжение текущего слова.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.

fn main() {
    let mut best: (&str, i32) = ("", 0);
    let transitions: [(&str, &str, i32); 3] =
        [("я", "учу", 3), ("я", "пишу", 1), ("учу", "rust", 2)];
    let current: &str = "я";
    for (previous, next, count) in transitions {
        if previous == current && count > best.1 {
            best = (next, count);
        }
    }
    let _ = &(best.0);
}

