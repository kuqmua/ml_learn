// Урок 08.3. Конфигурация эксперимента из аргументов командной строки.
// Зачем здесь эта тема: Для воспроизводимости недостаточно seed: нужны все параметры запуска.
// Почему код устроен так: Читаем конфигурацию из аргументов и явно фиксируем использованные
//   значения.
// Представь: Если поменяли скорость обучения, запись этого параметра объяснит, почему два запуска
//   дали разные ошибки.
//
// Что изучаем: Конфигурация запуска.
// Зачем это нужно: Явные параметры запуска позволяют повторить вычисление. Пример читает seed из аргумента
// и показывает применённое значение.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Получаем значение `seed` из окружения текущего процесса.
    let seed: u64 = std::env::args()
        // Берём элемент с указанным порядковым номером.
        .nth(1)
        // Преобразуем каждый элемент последовательности.
        .map(|text| text.parse::<u64>().expect("seed должен быть числом"))
        // При отсутствии значения используем запасной вариант.
        .unwrap_or(42);
    lesson_trace::trace_step!(seed);
    // Сохраняем рассчитанное значение `iterations` для следующих операций.
    let iterations: i32 = 3;
    lesson_trace::trace_step!(iterations);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("конфигурация: seed={seed}, iterations={iterations}");
}
