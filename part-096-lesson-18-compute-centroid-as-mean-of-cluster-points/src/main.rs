// Урок 18.1. Вычисление центроида как среднего точек кластера.
//
// Что изучаем: Центроиды кластеров.
// Зачем это нужно: Центроид — покоординатное среднее точек одной группы. Он представляет центр кластера.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `cluster` для следующего шага примера.
    let cluster: [[f64; 2]; 2] = [[1.0, 2.0], [3.0, 4.0]];
    // Создаём набор значений `cluster_center` для следующего шага примера.
    // Среднее пустого кластера не определено.
    assert!(!cluster.is_empty(), "для центра нужна хотя бы одна точка");
    // Задаём учебные значения для `cluster_center`.
    // Центр группы точек называют centroid.
    let mut cluster_center: [f64; 2] = [0.0, 0.0];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for point in cluster {
        // Прибавляем очередной вклад к ранее накопленному результату.
        cluster_center[0] += point[0];
        // Прибавляем очередной вклад к ранее накопленному результату.
        cluster_center[1] += point[1];
    }
    // Масштабируем текущую величину делением.
    cluster_center[0] /= cluster.len() as f64;
    // Масштабируем текущую величину делением.
    cluster_center[1] /= cluster.len() as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("центроид = {cluster_center:?}");

    // Построение графика вынесено из основного кода урока.
    visualize_compute_centroid_as_mean_of_cluster_points(cluster, cluster_center);
}

// Строим график по результатам урока.
fn visualize_compute_centroid_as_mean_of_cluster_points(
    cluster: [[f64; 2]; 2],
    cluster_center: [f64; 2],
) {
    // Значения из этого урока на графике.
    let observation_points: Vec<(f64, f64)> = cluster
        .iter()
        .map(|data_point| (data_point[0], data_point[1]))
        .collect();
    // Собираем значения для `cluster_center_points` в коллекцию.
    let cluster_center_points: Vec<(f64, f64)> = vec![(cluster_center[0], cluster_center[1])];
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::scatter_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок диаграммы.
        "Точки кластера и центроид",
        // Указываем подпись горизонтальной оси.
        "x",
        // Указываем подпись вертикальной оси.
        "y",
        // Передаём ряды или значения для отрисовки графика.
        &[
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "точки",
                // Передаём рассчитанные координаты точек.
                points: &observation_points,
            },
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "центроид",
                // Передаём рассчитанные координаты точек.
                points: &cluster_center_points,
            },
        ],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
