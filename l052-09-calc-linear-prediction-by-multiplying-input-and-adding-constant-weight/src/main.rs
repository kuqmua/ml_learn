// Урок 052. Вычислять прогноз прямой через вход, умноженный на вес, и постоянную прибавку.
// Это основа простой модели зависимости одного числового ответа от одного признака.

fn main() {
    for (weight, bias) in [(2.0, 1.0), (3.0, 1.0), (2.0, 5.0)] {
        let predictions = [0.0, 1.0, 3.0].map(|x| weight * x + bias);
        println!("y={weight}*x+{bias}: {predictions:?}");
        assert_eq!(predictions[0], bias);
        assert_eq!(predictions[1] - predictions[0], weight);
    }
    println!("Вес меняет отклик на изменение входа, постоянная прибавка сдвигает все ответы.");
}

