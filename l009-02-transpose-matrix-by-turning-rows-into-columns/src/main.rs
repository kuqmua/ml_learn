// Урок 009. Меняем строки таблицы на столбцы, сохраняя сами числа.
// Из строк [1, 2, 3] и [4, 5, 6] получаем строки [1, 4], [2, 5] и [3, 6].
// Таблица 2×3 становится таблицей 3×2. Число из ячейки (строка, столбец)
// попадает в ячейку (столбец, строка). Если повторить операцию, вернётся исходная таблица.
// Это полезно, когда нужно работать с числами одного столбца как с отдельной строкой.
// В учебниках такую перестановку называют транспонированием.

fn main() {
    let matrix: [[i32; 3]; 2] = [[1, 2, 3], [4, 5, 6]];
    let mut transposed: [[i32; 2]; 3] = [[0; 2]; 3];
    for row in 0..2 {
        for column in 0..3 {
            transposed[column][row] = matrix[row][column];
        }
    }

    let mut restored: [[i32; 3]; 2] = [[0; 3]; 2];
    for row in 0..transposed.len() {
        for column in 0..transposed[row].len() {
            restored[column][row] = transposed[row][column];
        }
    }
    assert_eq!(restored, matrix);

    // Выполняем вычисления из примера.
    let _ = transposed;
}
