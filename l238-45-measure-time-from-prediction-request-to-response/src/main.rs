// Урок 238. Собирать серию замеров прогноза и выбирать медиану и верхний процентиль.
// Для очень короткой операции стоимость измерения существенна; пример не измеряет задержку
// сетевого сервиса.

fn main() {
    let mut durations = Vec::new();
    for _ in 0..100 {
        let start = std::time::Instant::now();
        let input = std::hint::black_box(3.0_f64);
        let prediction = std::hint::black_box(2.0 * input + 1.0);
        durations.push(start.elapsed());
        assert_eq!(prediction, 7.0);
    }
    durations.sort();
    println!(
        "100 вызовов: медиана={:?}, 95-й процентиль по индексу={:?}",
        durations[50], durations[94]
    );
    println!(
        "Для настолько короткой операции заметна стоимость самого измерения; это не замер сетевого сервиса."
    );
}

