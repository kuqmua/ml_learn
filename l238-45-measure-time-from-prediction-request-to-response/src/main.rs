// Урок 45.3. Измерение времени от запроса прогноза до ответа.
// Связь с принятой терминологией: Измерение задержки ответа инференса.
// Зачем здесь эта тема: Качество прогноза не описывает удобство сервиса; задержка тоже влияет на
//   использование.
// Почему код устроен так: Измеряем один учебный запрос от начала вычисления до готового прогноза;
//   для оценки хвостов нужны повторные замеры.
// Представь: Замер одного вызова показывает способ измерения, но для вывода о типичной задержке
//   нужны многие вызовы.
//
// Что изучаем: Задержка ответа.
// Зачем это нужно: Замеряем время обработки запроса, поскольку правильный, но слишком медленный прогноз
// может быть непригоден.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
use lesson_trace::{enable, trace_note, trace_step};

fn main() {
    enable();
    trace_note!("Сохраняем рассчитанное значение `start` для следующих операций.");
    let start: std::time::Instant = std::time::Instant::now();
    trace_step!(start);
    trace_note!("Сохраняем рассчитанное значение `feature` для следующих операций.");
    let feature: f64 = 3.0;
    trace_step!(feature);
    trace_note!("Умножаем значения и сохраняем результат в `prediction`.");
    let prediction: f64 = 2.0 * feature + 1.0;
    trace_step!(prediction);
    trace_note!("Сохраняем рассчитанное значение `response_delay` для следующих операций.");
    trace_note!("Время ожидания ответа после запроса называют latency.");
    let response_delay: std::time::Duration = start.elapsed();
    trace_step!(response_delay);
    trace_note!("Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.");
    println!("прогноз={prediction}, задержка={response_delay:?}");
}
