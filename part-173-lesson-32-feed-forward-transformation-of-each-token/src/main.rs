// Урок 32.4. Преобразование каждого токена полносвязным слоем.
//
// Что изучаем: Feed-forward слой.
// Зачем это нужно: После внимания каждый токен отдельно проходит через линейное преобразование и
// нелинейную активацию.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Создаём набор значений `text_unit` для следующего шага примера.
    // Единицу текста, которую модель обрабатывает как одно целое, называют token.
    let text_unit: [f64; 2] = [1.0, 2.0];
    lesson_trace::trace_step!(text_unit);
    // Создаём набор значений `linear` для следующего шага примера.
    let linear: [f64; 2] = [
        // Умножаем величины согласно используемой формуле.
        0.5 * text_unit[0] - 0.2 * text_unit[1],
        // Умножаем величины согласно используемой формуле.
        0.3 * text_unit[0] + 0.4 * text_unit[1],
    ];
    lesson_trace::trace_step!(linear);
    // Создаём набор значений `activated` для следующего шага примера.
    let activated: [f64; 2] = [
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if linear[0] > 0.0 { linear[0] } else { 0.0 },
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if linear[1] > 0.0 { linear[1] } else { 0.0 },
    ];
    lesson_trace::trace_step!(activated);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("после feed-forward = {activated:?}");

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_feed_forward_transformation_of_each_token(activated);
}

// Строим график по результатам урока.
fn visualize_feed_forward_transformation_of_each_token(activated: [f64; 2]) {
    // Сравнение величин из этого урока.
    let chart: std::path::PathBuf = lesson_visualization::bar_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок диаграммы.
        "Feed-forward",
        // Указываем подпись вертикальной оси.
        "активация",
        // Передаём ряды или значения для отрисовки графика.
        &[("нейрон 0", activated[0]), ("нейрон 1", activated[1])],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
