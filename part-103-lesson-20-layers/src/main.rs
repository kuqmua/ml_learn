// Урок 20.1. Слои нейронной сети.
//
// Что изучаем: Слои нейронной сети.
// Зачем это нужно: Слой преобразует входной вектор в выходной по весам и смещениям каждого нейрона.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `input` для следующего шага примера.
    let input = [1.0, 2.0];
    // Создаём набор значений `weights` для следующего шага примера.
    let weights = [[0.5, 0.2], [-0.3, 0.8]];
    // Создаём набор значений `biases` для следующего шага примера.
    let biases = [0.1, -0.2];
    // Создаём набор значений `output` для следующего шага примера.
    let mut output = [0.0; 2];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for neuron in 0..2 {
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        output[neuron] = biases[neuron];
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for feature in 0..2 {
            // Прибавляем очередной вклад к ранее накопленному результату.
            output[neuron] += weights[neuron][feature] * input[feature];
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("выход слоя = {output:?}");
    // Значения ячеек видны по цвету и подписи.
    let chart = lesson_visualization::heatmap(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Веса слоя",
        &weights.iter().map(|row| row.to_vec()).collect::<Vec<_>>(),
    )
    .expect("не удалось сохранить тепловую карту");
    println!("график: {}", chart.display());
}
