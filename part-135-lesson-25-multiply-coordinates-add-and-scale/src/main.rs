// Урок 25.4. Масштабирование Q·K.
//
// Что изучаем: Масштабирование Q·K.
// Зачем это нужно: Оценку внимания делим на корень из размерности ключа, чтобы крупные векторы не делали
// softmax слишком резким.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `query` для следующего шага примера.
    let query = [1.0, 1.0];
    // Создаём набор значений `key` для следующего шага примера.
    let key = [2.0, 2.0];
    // Умножаем соответствующие координаты запроса и ключа, затем складываем результаты.
    let sum_after_multiplying_coordinates =
        lesson_001::multiply_matching_coordinates_then_add(&query, &key)
            .expect("запрос и ключ имеют одинаковую размерность");
    // Сохраняем рассчитанное значение `dimension` для следующих операций.
    let dimension = 2.0;
    // Создаём изменяемое значение `scale` для следующих операций.
    let mut scale = dimension;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for _ in 0..80 {
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        scale = (scale + dimension / scale) / 2.0;
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        "Q·K={sum_after_multiplying_coordinates}, после масштабирования={}",
        sum_after_multiplying_coordinates / scale
    );
}
