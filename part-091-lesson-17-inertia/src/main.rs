// Урок 17.3. Инерция кластеризации.
//
// Что изучаем: Инерция кластеризации.
// Зачем это нужно: Инерция складывает квадраты расстояний точек до назначенных центров; меньшая означает
// более плотные группы.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `points` для следующего шага примера.
    let points = [[0.0, 0.0], [1.0, 0.0], [5.0, 0.0], [6.0, 0.0]];
    // Создаём набор значений `centers` для следующего шага примера.
    let centers = [[0.5, 0.0], [5.5, 0.0]];
    // Создаём набор значений `assignments` для следующего шага примера.
    let assignments = [0, 0, 1, 1];
    // Инициализируем изменяемый накопитель `inertia` начальным состоянием.
    // Каждой точке нужен индекс существующего центра.
    assert_eq!(
        points.len(),
        assignments.len(),
        "каждой точке нужен номер центра"
    );
    assert!(
        assignments.iter().all(|&index| index < centers.len()),
        "номер центра выходит за границы списка"
    );
    let mut inertia = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 0..points.len() {
        // Комбинируем исходные величины и сохраняем результат в `delta`.
        let delta = points[index][0] - centers[assignments[index]][0];
        // Прибавляем очередной вклад к ранее накопленному результату.
        inertia += delta * delta;
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("инерция = {inertia}");
    // График величин и зависимостей, изученных в этом уроке.
    let chart_points_0: Vec<(f64, f64)> = (0..=60)
        .map(|i| {
            let x = i as f64 / 10.0;
            (x, ((x - 0.5) * (x - 0.5)).min((x - 5.5) * (x - 5.5)))
        })
        .collect();
    let chart = lesson_visualization::line_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Инерция для двух центров",
        "точка x",
        "квадрат расстояния",
        &[lesson_visualization::Series {
            name: "ближайший из 0.5 и 5.5",
            points: &chart_points_0,
        }],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
