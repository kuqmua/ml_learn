// Урок 25.6. Причинная маска внимания.
//
// Что изучаем: Причинная маска внимания.
// Зачем это нужно: Маска зануляет веса будущих позиций и не позволяет текущему токену пользоваться ещё
// неизвестным текстом.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `current_position` для следующих операций.
    let current_position = 1;
    // Создаём набор значений `raw_weights` для следующего шага примера.
    let raw_weights = [0.2, 0.3, 0.5];
    // Создаём набор значений `masked` для следующего шага примера.
    let mut masked = [0.0; 3];
    // Инициализируем изменяемый накопитель `allowed_sum` начальным состоянием.
    let mut allowed_sum = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 0..=current_position {
        // Прибавляем очередной вклад к ранее накопленному результату.
        allowed_sum += raw_weights[index];
    }
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 0..=current_position {
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        masked[index] = raw_weights[index] / allowed_sum;
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("позиция {current_position}: веса после маски = {masked:?}");
}
