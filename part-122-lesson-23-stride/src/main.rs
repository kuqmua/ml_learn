// Урок 23.2. Шаг свёртки stride.
//
// Что изучаем: Шаг свёртки stride.
// Зачем это нужно: Stride определяет, на сколько пикселей сдвигается ядро после одного применения.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `image_width` для следующих операций.
    let image_width = 5;
    // Сохраняем рассчитанное значение `kernel_width` для следующих операций.
    let kernel_width = 2;
    // Сохраняем рассчитанное значение `stride` для следующих операций.
    let stride = 2;
    // Нормируем или усредняем величину делением и сохраняем её в `output_width`.
    let output_width = (image_width - kernel_width) / stride + 1;
    // Преобразуем входные данные и сохраняем полученную коллекцию в `positions`.
    let positions: Vec<_> = (0..output_width).map(|index| index * stride).collect();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("позиции ядра по ширине: {positions:?}");
    // Сравнение величин из этого урока.
    let chart = lesson_visualization::bars(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Stride и позиции ядра",
        "позиция",
        &[
            ("первая", positions[0] as f64),
            ("последняя", *positions.last().unwrap() as f64),
        ],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
