//! Вычисления и примеры урока part-149-lesson-28-lexical-search.

// Урок 28.1. Лексический поиск.
//
// Что изучаем: Лексический поиск.
// Зачем это нужно: Совпадение слов запроса с документом даёт простой поиск без обученной модели.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Создаём набор значений `documents` для следующего шага примера.
    let documents = [("rust cargo", "guide"), ("машинное обучение", "ml")];
    // Сохраняем рассчитанное значение `query` для следующих операций.
    let query = "cargo";
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for (text, id) in documents {
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if text.split_whitespace().any(|word| word == query) {
            // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
            println!("найден документ {id}");
        }
    }
}
