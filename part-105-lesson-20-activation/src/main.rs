// Урок 20.3. Функция активации.
//
// Что изучаем: Функция активации.
// Зачем это нужно: Нелинейная активация позволяет сети описывать зависимости, которые не выражаются одной
// прямой.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for logit in [-2.0, 0.0, 2.0] {
        // ReLU оставляет положительные значения и обнуляет отрицательные.
        let relu = if logit > 0.0 { logit } else { 0.0 };
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("logit={logit}, ReLU={relu}");
    }
}
