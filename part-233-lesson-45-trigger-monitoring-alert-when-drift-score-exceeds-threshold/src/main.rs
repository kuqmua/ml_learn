// Урок 45.4. Предупреждение при превышении порога оценкой дрейфа.
// Зачем здесь эта тема: Мониторинг полезен только тогда, когда изменение приводит к действию.
// Почему код устроен так: Сравниваем оценку дрейфа с заранее выбранным порогом и формируем
//   предупреждение.
// Представь: Если доля новых значений в корзине выросла выше порога, мониторинг выдаёт
//   предупреждение.
//
// Здесь предупреждаем, только когда оценка дрейфа строго выше порога.
// Значение точно на пороге ещё не вызывает предупреждение.

fn main() {
    lesson_trace::enable();
    // Сохраняем результат этого шага в `alert_threshold`.
    let alert_threshold: f64 = 0.2;
    lesson_trace::trace_step!(alert_threshold);
    // Повторяем расчёт для каждого элемента последовательности.
    for (description, drift_score, expected) in [
        // Добавляем пару значений для сравнения или построения графика.
        ("ниже порога", 0.1, false),
        // Добавляем пару значений для сравнения или построения графика.
        ("на пороге", 0.2, false),
        // Добавляем пару значений для сравнения или построения графика.
        ("выше порога", 0.35, true),
    ] {
        lesson_trace::trace_step!(description);
        lesson_trace::trace_step!(drift_score);
        lesson_trace::trace_step!(expected);
        // Проверяем ожидаемое свойство учебного примера.
        assert!(drift_score >= 0.0);
        // Сохраняем результат этого шага в `alert`.
        let alert: bool = drift_score > alert_threshold;
        lesson_trace::trace_step!(alert);
        // Проверяем ожидаемое свойство учебного примера.
        assert_eq!(alert, expected);
        // Печатаем рассчитанные значения для проверки примера.
        println!("{description}: дрейф={drift_score}, требуется проверка={alert}");
    }

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_trigger_monitoring_alert_when_drift_score_exceeds_threshold(alert_threshold);
}

