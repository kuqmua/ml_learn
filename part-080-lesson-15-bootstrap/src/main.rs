// Урок 15.2. Bootstrap-выборка.
//
// Что изучаем: Bootstrap-выборка.
// Зачем это нужно: Случайная выборка с возвращением может содержать один объект несколько раз и пропускать
// другой.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `data` для следующего шага примера.
    let data = ["A", "B", "C", "D"];
    // Создаём набор значений `sampled_indices` для следующего шага примера.
    let sampled_indices = [0, 2, 2, 3];
    // Преобразуем входные данные и сохраняем полученную коллекцию в `sample`.
    let sample: Vec<_> = sampled_indices.iter().map(|&index| data[index]).collect();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("исходные={data:?}, bootstrap={sample:?}");
}
