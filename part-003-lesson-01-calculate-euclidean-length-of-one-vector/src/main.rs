// Урок 01.3. Вычисление евклидовой длины одного вектора.
// Почему этот урок сейчас: Для расстояний нужна геометрическая длина; сумма квадратов из скалярного произведения даёт её квадрат.
// Почему пример устроен так: Берём корень из произведения вектора на самого себя; пары 3–4–5 позволяют проверить результат вручную.
//
// Что изучаем: длина вектора — корень из суммы квадратов координат.
// Смена знаков длину не меняет; длина нулевого вектора равна нулю.

fn main() {
    lesson_trace::enable();
    // Задаём учебные значения для `cases`.
    let cases: [(&str, [f64; 2], f64); 4] = [
        // Добавляем пару значений для сравнения или построения графика.
        ("обычный вектор", [3.0, 4.0], 5.0),
        // Добавляем пару значений для сравнения или построения графика.
        ("сменили знаки", [-3.0, -4.0], 5.0),
        // Добавляем пару значений для сравнения или построения графика.
        ("вдвое длиннее", [6.0, 8.0], 10.0),
        // Добавляем пару значений для сравнения или построения графика.
        ("нулевой вектор", [0.0, 0.0], 0.0),
    ];
    lesson_trace::trace_step!(cases);
    // Повторяем расчёт для каждого элемента последовательности.
    for (description, vector, expected) in cases {
        lesson_trace::trace_step!(description);
        lesson_trace::trace_step!(vector);
        lesson_trace::trace_step!(expected);
        // В библиотеке длина строится на вычислении из первого урока.
        let length: f64 =
            part_003_lesson_01_calculate_euclidean_length_of_one_vector::euclidean_norm_of_vector(
                &vector,
            );
        lesson_trace::trace_step!(length);
        // Проверяем ожидаемое свойство учебного примера.
        assert!((length - expected).abs() < 1e-10);
        // Печатаем рассчитанные значения для проверки примера.
        println!("{description}: {vector:?} → L2 = {length}");
    }

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_calculate_euclidean_length_of_one_vector();
}

// Строим график по результатам урока.
fn visualize_calculate_euclidean_length_of_one_vector() {
    // Наглядное представление величин из этого урока.
    let euclidean_norm_points: Vec<(f64, f64)> = (-50..=50)
        // Преобразуем каждый элемент в новое значение.
        .map(|plot_step_index| {
            // Сохраняем результат этого шага в `horizontal_value`.
            let horizontal_value: f64 = plot_step_index as f64 / 10.0;
            // Добавляем пару значений для сравнения или построения графика.
            (
                horizontal_value,
                part_003_lesson_01_calculate_euclidean_length_of_one_vector::euclidean_norm_of_vector(&[
                    horizontal_value,
                    4.0,
                ]),
            )
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Норма L2",
        // Указываем подпись горизонтальной оси.
        "первая координата",
        // Указываем подпись вертикальной оси.
        "L2",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "вектор [x, 4]",
            // Передаём рассчитанные координаты точек.
            points: &euclidean_norm_points,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
