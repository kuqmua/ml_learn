// Урок 234. Делать повторные замеры пакетного прогноза при разных размерах входа.
// Показываем медиану времени, защищаем вычисление от удаления оптимизатором и не требуем строгой
// пропорциональности шумных замеров.

fn main() {
    for size in [10, 1000, 100_000] {
        let features = vec![1.0_f64; size];
        let mut timings = Vec::new();
        for _ in 0..5 {
            let start = std::time::Instant::now();
            let predictions: Vec<_> = std::hint::black_box(&features)
                .iter()
                .map(|&x| 2.0 * x + 1.0)
                .collect();
            std::hint::black_box(&predictions);
            timings.push(start.elapsed());
            assert_eq!(predictions.len(), size);
        }
        timings.sort();
        println!("Строк={size}, медиана пяти замеров={:?}", timings[2]);
    }
    println!(
        "Замеры зависят от машины и нагрузки; строгую пропорциональность времени не предполагаем."
    );
}

