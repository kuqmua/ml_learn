// Урок 103. Вычислять компактность одного набора точек при разном числе центров.
// Сравниваем величину улучшения: минимум ошибки без учёта сложности предпочёл бы по центру на
// каждую точку.

fn main() {
    let points = [0.0_f64, 1.0, 9.0, 10.0];
    let center_sets = [
        vec![5.0],
        vec![0.5, 9.5],
        vec![0.0, 1.0, 9.5],
        vec![0.0, 1.0, 9.0, 10.0],
    ];
    let mut errors = Vec::new();
    for centers in center_sets {
        let error = points
            .iter()
            .map(|&p| {
                centers
                    .iter()
                    .map(|&c| (p - c).powi(2))
                    .fold(f64::INFINITY, f64::min)
            })
            .sum::<f64>();
        println!(
            "Центров={}, центры={centers:?}, сумма квадратов расстояний={error}",
            centers.len()
        );
        errors.push(error);
    }
    assert!(errors[0] - errors[1] > errors[1] - errors[2]);
    println!(
        "Здесь основной выигрыш даёт переход от одной группы к двум; минимум ошибки сам по себе выбрал бы по центру на точку."
    );
}

