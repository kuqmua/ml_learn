// Урок 074. Оценивать объём прямого поиска соседей как число примеров, умноженное на число признаков.
// Этот расчёт объясняет рост работы при увеличении обучающего набора; фактическое время здесь не
// измеряется.

fn main() {
    let features = 4;
    for count in [10, 100, 1000] {
        let mut comparisons = 0;
        for _ in 0..count {
            for _ in 0..features {
                comparisons += 1;
            }
        }
        println!("Точек={count}, признаков={features}, обработанных координат={comparisons}");
        assert_eq!(comparisons, count * features);
    }
    println!("Увеличение числа точек в 10 раз увеличивает число обработанных координат в 10 раз.");
}

