// Урок 25.5. Нормировка softmax.
//
// Что изучаем: Нормировка softmax.
// Зачем это нужно: Экспоненты оценок делим на их сумму, получая неотрицательные веса внимания с суммой
// единица.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `logits` для следующего шага примера.
    let logits = [0.0, 1.0];
    // Создаём набор значений `exponentials` для следующего шага примера.
    let mut exponentials = [0.0; 2];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 0..2 {
        // Создаём изменяемое значение `term` для следующих операций.
        let mut term = 1.0;
        // Создаём изменяемое значение `sum` для следующих операций.
        let mut sum = 1.0;
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for order in 1..=30 {
            // Умножаем накопленное значение на очередной множитель.
            term *= logits[index] / order as f64;
            // Прибавляем очередной вклад к ранее накопленному результату.
            sum += term;
        }
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        exponentials[index] = sum;
    }
    // Комбинируем исходные величины и сохраняем результат в `denominator`.
    let denominator = exponentials[0] + exponentials[1];
    // Создаём набор значений `weights` для следующего шага примера.
    let weights = [exponentials[0] / denominator, exponentials[1] / denominator];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("веса внимания = {weights:?}");
}
