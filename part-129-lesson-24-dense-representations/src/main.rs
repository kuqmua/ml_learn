// Урок 24.3. Плотные представления слов.
//
// Что изучаем: Плотные представления слов.
// Зачем это нужно: Вместо отдельного разреженного признака на слово используем короткий вектор числовых
// признаков.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `embedding_table` для следующего шага примера.
    let embedding_table = [[0.0, 0.0], [0.8, 0.2], [0.7, 0.3]];
    // Сохраняем рассчитанное значение `token_id` для следующих операций.
    let token_id = 2;
    // Сохраняем рассчитанное значение `embedding` для следующих операций.
    let embedding = embedding_table[token_id];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("токен={token_id}, плотный вектор={embedding:?}");
}
