// Урок 116. Применять ReLU: сохранять положительное число и заменять остальные нулём.
// Такое нелинейное преобразование позволяет слоям сети делать больше, чем последовательность одних
// линейных операций.

fn main() {
    for (input, expected) in [(-2.0_f64, 0.0), (0.0, 0.0), (2.0, 2.0)] {
        let output = if input > 0.0 { input } else { 0.0 };
        println!("ReLU({input})={output}");
        assert_eq!(output, expected);
    }
    let relu = |x: f64| x.max(0.0);
    assert_ne!(relu(-2.0) + relu(2.0), relu(-2.0 + 2.0));
    println!("ReLU меняет правило обработки по знаку: её нельзя заменить одним общим множителем.");
}

