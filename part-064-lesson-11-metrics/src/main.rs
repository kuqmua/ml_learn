// Сводная практика 11. Метрики и дисбаланс классов.
//
// Что повторяем вместе: confusion matrix, precision, recall, F1, ROC-AUC, PR-AUC.
// Зачем это нужно: При редком положительном классе общей доли правильных ответов недостаточно; важны
//   precision и recall.
// Что показывает программа: Создаём несбалансированные истинные метки. Превращаем оценки в классы по
//   заданному порогу и считаем матрицу ошибок. Показываем, почему accuracy вводит в заблуждение при редком
//   положительном классе.
// Что проверить при изменении примера: Покажи набор, где accuracy высока у бесполезного классификатора; не
//   подбирай порог на test.
// Дополнительная практика: Рассчитай метрики из меток и оценок; добавь подбор порога по validation.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Шаг: Создаём несбалансированные истинные метки.
    let labels = [
        // Возвращаем булев результат для этого случая.
        false, false, false, false, false, false, false, false, false, true,
    ];
    // Создаём набор значений `scores` для следующего шага примера.
    let scores = [0.1, 0.2, 0.3, 0.1, 0.2, 0.4, 0.1, 0.3, 0.2, 0.8];

    // Автоматически получаем стандартные реализации перечисленных трейтов для этого типа.
    #[derive(Debug)]
    // Описываем тип `Counts`, чтобы явно хранить состояние и допустимые варианты.
    struct Counts {
        // Возвращаем булев результат для этого случая.
        true_positives: usize,
        // Возвращаем булев результат для этого случая.
        false_positives: usize,
        // Возвращаем булев результат для этого случая.
        true_negatives: usize,
        // Возвращаем булев результат для этого случая.
        false_negatives: usize,
    }
    // Разносим каждый прогноз по четырём ячейкам матрицы ошибок.
    fn count_binary_classification_outcomes(
        // `labels` задаёт соответствующее входное значение или поле структуры.
        labels: &[bool],
        // `scores` задаёт соответствующее входное значение или поле структуры.
        scores: &[f64],
        // Параметр `threshold` передаёт порог решения.
        threshold: f64,
    ) -> Counts {
        // Проверяем, что сравниваемые размерности или значения действительно совпадают.
        assert_eq!(labels.len(), scores.len());
        // Создаём изменяемое значение `confusion` для следующих операций.
        let mut confusion = Counts {
            // Возвращаем булев результат для этого случая.
            true_positives: 0,
            // Возвращаем булев результат для этого случая.
            false_positives: 0,
            // Возвращаем булев результат для этого случая.
            true_negatives: 0,
            // Возвращаем булев результат для этого случая.
            false_negatives: 0,
        };
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for (&actual_label, &prediction_score) in labels.iter().zip(scores) {
            // Разбираем каждый возможный вариант значения отдельно.
            match (actual_label, prediction_score >= threshold) {
                // Прибавляем очередной вклад к ранее накопленному результату.
                (true, true) => confusion.true_positives += 1,
                // Прибавляем очередной вклад к ранее накопленному результату.
                (false, true) => confusion.false_positives += 1,
                // Прибавляем очередной вклад к ранее накопленному результату.
                (false, false) => confusion.true_negatives += 1,
                // Прибавляем очередной вклад к ранее накопленному результату.
                (true, false) => confusion.false_negatives += 1,
            }
        }
        // Используем ранее рассчитанное значение `confusion` в текущем выражении.
        confusion
    }

    // Шаг: Превращаем оценки в классы по заданному порогу и считаем матрицу ошибок.
    let confusion = count_binary_classification_outcomes(&labels, &scores, 0.5);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Задаём шаблон строки: плейсхолдеры ниже заменятся рассчитанными значениями.
        "{confusion:?}, precision={:.2}, recall={:.2}, accuracy={:.2}",
        // Составляем результат из вычисленных значений в указанном порядке.
        (|| -> f64 {
            /* Делим верные положительные прогнозы на все положительные прогнозы. */
            let confusion: &Counts = &confusion;
            // Комбинируем исходные величины и сохраняем результат в `predicted_positives`.
            let predicted_positives = confusion.true_positives + confusion.false_positives;
            // Проверяем условие и выбираем соответствующую ветку алгоритма.
            if predicted_positives == 0 {
                // Используем фиксированное значение для этого варианта примера.
                0.0
            } else {
                // Делим значения, получая нормированную величину или среднее.
                confusion.true_positives as f64 / predicted_positives as f64
            }
        })(),
        // Составляем результат из вычисленных значений в указанном порядке.
        (|| -> f64 {
            /* Делим верные положительные прогнозы на все реальные положительные объекты. */
            let confusion: &Counts = &confusion;
            // Комбинируем исходные величины и сохраняем результат в `actual_positives`.
            let actual_positives = confusion.true_positives + confusion.false_negatives;
            // Проверяем условие и выбираем соответствующую ветку алгоритма.
            if actual_positives == 0 {
                // Используем фиксированное значение для этого варианта примера.
                0.0
            } else {
                // Делим значения, получая нормированную величину или среднее.
                confusion.true_positives as f64 / actual_positives as f64
            }
        })(),
        // Составляем результат из вычисленных значений в указанном порядке.
        (confusion.true_positives + confusion.true_negatives) as f64 / labels.len() as f64
    );
    // Шаг: Показываем, почему accuracy вводит в заблуждение при редком положительном классе.
    let useless = count_binary_classification_outcomes(&labels, &[0.; 10], 0.5);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Задаём шаблон строки: плейсхолдеры ниже заменятся рассчитанными значениями.
        "all-negative accuracy={:.2}",
        // Составляем результат из вычисленных значений в указанном порядке.
        (useless.true_positives + useless.true_negatives) as f64 / 10.
    );
}
