// Урок 32.3. Проверка загружаемой модели.
//
// Что изучаем: Проверка загружаемой модели.
// Зачем это нужно: После чтения проверяем числа и число полей до использования модели для прогноза.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `serialized` для следующих операций.
    let serialized = "2.0\n1.0\n";
    // Преобразуем входные данные и сохраняем полученную коллекцию в `values`.
    let values: Vec<_> = serialized.lines().collect();
    // Проверяем, что сравниваемые размерности или значения действительно совпадают.
    assert_eq!(values.len(), 2, "нужно ровно два параметра");
    // Читаем или разбираем входные данные в значение `weight`.
    let weight: f64 = values[0].parse().expect("вес должен быть числом");
    // Читаем или разбираем входные данные в значение `bias`.
    let bias: f64 = values[1].parse().expect("смещение должно быть числом");
    // Проверяем обязательное условие до дальнейшего вычисления.
    assert!(weight.is_finite() && bias.is_finite());
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("параметры допустимы: {weight}, {bias}");
}
