// Урок 30.5. Exploration и exploitation.
//
// Что изучаем: Exploration и exploitation.
// Зачем это нужно: Исследование пробует неизвестные действия, использование выбирает лучшее известное.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Инициализируем значение `random_fraction` начальным состоянием.
    let random_fraction = 0.05;
    // Инициализируем значение `exploration_probability` начальным состоянием.
    let exploration_probability = 0.1;
    // Сохраняем рассчитанное значение `best_known_action` для следующих операций.
    let best_known_action = "вправо";
    // Сохраняем рассчитанное значение `action` для следующих операций.
    let action = if random_fraction < exploration_probability {
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "влево"
    } else {
        // Используем ранее рассчитанное значение `best_known_action` в текущем выражении.
        best_known_action
    };
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("выбрано действие: {action}");
}
