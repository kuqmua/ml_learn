// Урок 31.2. Калибровка вероятностей.
//
// Что изучаем: Калибровка вероятностей.
// Зачем это нужно: Среди объектов с прогнозом около 0.8 событие должно происходить примерно в 80% случаев.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Инициализируем значение `predicted_probability` начальным состоянием.
    let predicted_probability = 0.8;
    // Создаём набор значений `observed_labels` для следующего шага примера.
    let observed_labels = [true, true, true, false, true];
    assert!(
        (0.0..=1.0).contains(&predicted_probability),
        "прогнозная вероятность должна быть от 0 до 1"
    );
    assert!(
        !observed_labels.is_empty(),
        "для частоты нужна хотя бы одна метка"
    );
    // Преобразуем входные данные и сохраняем полученную коллекцию в `observed_frequency`.
    let observed_frequency = observed_labels.iter().filter(|&&label| label).count() as f64
        // Делим значения, получая нормированную величину или среднее.
        / observed_labels.len() as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("прогноз={predicted_probability}, наблюдаемая частота={observed_frequency}");
}
