// Ссылка помогает найти подтверждение, но сама по себе ещё не доказывает истинность утверждения.

fn main() {
    let source = "docs/rust/cargo";
    let statement = "Cargo собирает проект";
    let answer = format!("{statement} [источник: {source}]");
    println!("{answer}");
    assert!(answer.contains(source));
    assert!(answer.contains(statement));
    println!(
        "Идентификатор позволяет найти документ и проверить утверждение; сам по себе он не доказывает его истинность."
    );
}

