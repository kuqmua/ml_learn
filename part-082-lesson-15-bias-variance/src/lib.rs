//! Вычисления и примеры урока part-082-lesson-15-bias-variance.

// Урок 15.4. Смещение и разброс.
//
// Что изучаем: Смещение и разброс.
// Зачем это нужно: Ошибка может происходить из систематического смещения модели или высокой изменчивости
// при разных обучающих наборах.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Создаём набор значений `predictions` для следующего шага примера.
    let predictions = [2.0, 4.0, 6.0];
    assert!(
        !predictions.is_empty(),
        "для оценки разброса нужен хотя бы один прогноз"
    );
    // Сохраняем рассчитанное значение `target` для следующих операций.
    let target = 5.0;
    // Преобразуем входные данные и сохраняем полученную коллекцию в `mean`.
    let mean = predictions.iter().sum::<f64>() / predictions.len() as f64;
    // Комбинируем исходные величины и сохраняем результат в `bias`.
    let bias = mean - target;
    // Сохраняем рассчитанное значение `variance` для следующих операций.
    let variance = predictions
        // Перебираем элементы по ссылке, не копируя исходную коллекцию.
        .iter()
        // Преобразуем каждый элемент последовательности.
        .map(|&x| (x - mean) * (x - mean))
        // Складываем результаты для всех элементов последовательности.
        .sum::<f64>()
        // Делим значения, получая нормированную величину или среднее.
        / predictions.len() as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("смещение={bias}, разброс={variance:.2}");
}
