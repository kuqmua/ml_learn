// Урок 162. Находить документы с точным словом запроса и сохранять их идентификаторы.
// Проверяем успешный поиск и пустой ответ, когда слово не встретилось ни в одном документе.

fn main() {
    let documents = [("guide", "rust cargo"), ("ml", "машинное обучение")];
    for query in ["cargo", "обучение", "пирог"] {
        let found: Vec<_> = documents
            .iter()
            .filter(|(_, text)| text.split_whitespace().any(|word| word == query))
            .map(|(id, _)| *id)
            .collect();
        println!("Запрос={query:?}, найдено={found:?}");
        if query == "cargo" {
            assert_eq!(found, vec!["guide"]);
        }
        if query == "пирог" {
            assert!(found.is_empty());
        }
    }
}

