// Урок 23.1. Ядро свёртки.
//
// Что изучаем: Ядро свёртки.
// Зачем это нужно: Малое ядро умножает локальный участок изображения на веса и суммирует отклики.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `patch` для следующего шага примера.
    let patch = [[1.0, 2.0], [3.0, 4.0]];
    // Создаём набор значений `kernel` для следующего шага примера.
    let kernel = [[1.0, 0.0], [0.0, -1.0]];
    // Инициализируем изменяемый накопитель `response` начальным состоянием.
    let mut response = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for row in 0..2 {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for column in 0..2 {
            // Прибавляем очередной вклад к ранее накопленному результату.
            response += patch[row][column] * kernel[row][column];
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("отклик ядра = {response}");
}
