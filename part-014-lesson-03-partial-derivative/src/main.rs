// Урок 03.2. Частная производная.
//
// Что изучаем: Частная производная.
// Зачем это нужно: Для функции двух переменных меняем одну переменную, оставляя другую постоянной. Это
// даёт отдельную производную по каждой оси.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // f(x,y)=x²+3y².
    let (x, y) = (2.0, -1.0);
    // Умножаем значения и сохраняем результат в `derivative_by_x`.
    let derivative_by_x = 2.0 * x;
    // Умножаем значения и сохраняем результат в `derivative_by_y`.
    let derivative_by_y = 6.0 * y;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("∂f/∂x={derivative_by_x}, ∂f/∂y={derivative_by_y}");
    // Наглядное представление величин из этого урока.
    let chart_points_0: Vec<(f64, f64)> = (-40..=40)
        .map(|i| {
            let x = i as f64 / 10.0;
            (x, x * x + 4.0)
        })
        .collect();
    let chart_points_1: Vec<(f64, f64)> = (-40..=40)
        .map(|i| {
            let y = i as f64 / 10.0;
            (y, 4.0 + y * y)
        })
        .collect();
    let chart = lesson_visualization::line_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Сечения функции x² + 3y²",
        "координата",
        "значение",
        &[
            lesson_visualization::Series {
                name: "y=-1",
                points: &chart_points_0,
            },
            lesson_visualization::Series {
                name: "x=2",
                points: &chart_points_1,
            },
        ],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
