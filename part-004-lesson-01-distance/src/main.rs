// Урок 01.4. Евклидово расстояние между точками.
//
// Что изучаем: Евклидово расстояние между точками.
// Зачем это нужно: Изучаем расстояние как длину вектора покоординатных разностей. Разность по каждой оси
// возводим в квадрат, складываем и извлекаем корень. Для (0, 0) и (3, 4) расстояние равно 5; при
// перестановке точек оно не меняется.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `first_point` для следующего шага примера.
    let first_point = [0.0, 0.0];
    // Создаём набор значений `second_point` для следующего шага примера.
    let second_point = [3.0, 4.0];
    // Расстояние определено только для точек одной размерности.
    assert_eq!(
        first_point.len(),
        second_point.len(),
        "точки должны иметь одинаковое число координат"
    );
    // Инициализируем изменяемый накопитель `squared_distance` начальным состоянием.
    let mut squared_distance = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 0..first_point.len() {
        // Квадрат убирает знак разности и сохраняет вклад каждой оси.
        let difference = first_point[index] - second_point[index];
        // Прибавляем очередной вклад к ранее накопленному результату.
        squared_distance += difference * difference;
    }
    // Создаём изменяемое значение `distance` для следующих операций.
    let mut distance = if squared_distance == 0.0 {
        // Используем фиксированное значение для этого варианта примера.
        0.0
    } else {
        // Используем ранее рассчитанное значение `squared_distance` в текущем выражении.
        squared_distance
    };
    // Проверяем условие и выбираем соответствующую ветку алгоритма.
    if squared_distance > 0.0 {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for _ in 0..80 {
            // Итерация Ньютона вычисляет корень без готового метода библиотеки.
            distance = (distance + squared_distance / distance) / 2.0;
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("расстояние = {distance}");
}
