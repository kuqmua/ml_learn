//! Вычисления и примеры урока part-078-lesson-14-decision-tree.

// Сводная практика 14. Дерево решений.
//
// Что повторяем вместе: энтропия, Gini, жадное разбиение, переобучение.
// Зачем это нужно: Дерево последовательно делит пространство признаков на области и хранит решение в
//   листьях.
// Что показывает программа: Создаём одномерную задачу с явной границей классов. Обучаем дерево, выбирая
//   порог по уменьшению неоднородности. Проверяем прогноз на новой точке и печатаем структуру дерева.
// Что проверить при изменении примера: Проверь чистый лист, константный признак и изменение train/test
//   метрик с глубиной.
// Дополнительная практика: Реализуй дерево для числовых признаков: выбор порога, max_depth, min_samples_leaf.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Шаг: Создаём одномерную задачу с явной границей классов.
    let data = [(1., false), (2., false), (3., true), (4., true)];

    // Автоматически получаем стандартные реализации перечисленных трейтов для этого типа.
    #[derive(Debug)]
    // Описываем тип `Tree`, чтобы явно хранить состояние и допустимые варианты.
    enum Tree {
        // Лист хранит итоговую метку класса.
        Leaf(bool),
        // Разветвление хранит порог и два дочерних поддерева.
        Split {
            // Поле `threshold` соответствующее значение в составе структуры.
            threshold: f64,
            // Поле `left` соответствующее значение в составе структуры.
            left: Box<Tree>,
            // Поле `right` соответствующее значение в составе структуры.
            right: Box<Tree>,
        },
    }

    // Объявляем повторно используемое вычисление `calculate_gini_impurity_of_labels`; параметры ниже задают его входы.
    fn calculate_gini_impurity_of_labels(data: &[(f64, bool)]) -> f64 {
        // Отдельно обрабатываем пустой набор, чтобы избежать неверного расчёта.
        if data.is_empty() {
            // Завершаем текущий расчёт и возвращаем найденное значение.
            return 0.;
        }
        // Сохраняем рассчитанное значение `positive_fraction` для следующих операций.
        let positive_fraction =
            // Делим значения, получая нормированную величину или среднее.
            data.iter().filter(|(_, label)| *label).count() as f64 / data.len() as f64;
        // Умножаем величины согласно используемой формуле.
        2. * positive_fraction * (1. - positive_fraction)
    }
    // Ищем порог с минимальной взвешенной нечистотой и строим дочерние узлы.
    fn build_numeric_decision_tree(data: &[(f64, bool)], remaining_depth: usize) -> Tree {
        // Считаем число положительных меток, чтобы проверить чистоту узла.
        let positive_count = data.iter().filter(|(_, label)| *label).count();
        // Чистый узел или достигнутый предел глубины превращаем в лист.
        if remaining_depth == 0 || positive_count == 0 || positive_count == data.len() {
            // Завершаем текущий расчёт и возвращаем найденное значение.
            return Tree::Leaf(positive_count * 2 >= data.len());
        }
        // Извлекаем значения признака и сортируем их для поиска возможных порогов.
        let mut sorted_feature_values: Vec<_> = data.iter().map(|sample| sample.0).collect();
        // Сортируем значения в порядке, заданном функцией сравнения.
        sorted_feature_values.sort_by(f64::total_cmp);
        // Инициализируем изменяемый накопитель `best_split` начальным состоянием.
        let mut best_split = None;
        // Кандидатами служат середины между соседними значениями признака.
        for pair in sorted_feature_values.windows(2) {
            // Проверяем условие и выбираем соответствующую ветку алгоритма.
            if pair[0] == pair[1] {
                // Пропускаем текущий элемент и переходим к следующему.
                continue;
            }
            // Нормируем или усредняем величину делением и сохраняем её в `candidate_threshold`.
            let candidate_threshold = (pair[0] + pair[1]) / 2.;
            // Сохраняем рассчитанное значение `left_samples` для следующих операций.
            let left_samples: Vec<_> = data
                // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                .iter()
                // Копируем значения из ссылок, чтобы получить самостоятельные элементы.
                .copied()
                // Оставляем только элементы, прошедшие указанную проверку.
                .filter(|sample| sample.0 < candidate_threshold)
                // Собираем элементы итератора в итоговую коллекцию.
                .collect();
            // Сохраняем рассчитанное значение `right_samples` для следующих операций.
            let right_samples: Vec<_> = data
                // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                .iter()
                // Копируем значения из ссылок, чтобы получить самостоятельные элементы.
                .copied()
                // Оставляем только элементы, прошедшие указанную проверку.
                .filter(|sample| sample.0 >= candidate_threshold)
                // Собираем элементы итератора в итоговую коллекцию.
                .collect();
            // Считаем количество элементов и сохраняем его в `score`.
            let score = (left_samples.len() as f64
                // Добавляем этот член в составное арифметическое выражение.
                * calculate_gini_impurity_of_labels(&left_samples)
                // Умножаем величины согласно используемой формуле.
                + right_samples.len() as f64 * calculate_gini_impurity_of_labels(&right_samples))
                // Делим значения, получая нормированную величину или среднее.
                / data.len() as f64;
            // Проверяем условие и выбираем соответствующую ветку алгоритма.
            if best_split.is_none_or(|(previous_score, _)| score < previous_score) {
                // Обновляем `best_split` результатом текущего шага.
                best_split = Some((score, candidate_threshold));
            }
        }
        // По лучшему порогу рекурсивно строим два дочерних поддерева.
        if let Some((_, threshold)) = best_split {
            // Сохраняем рассчитанное значение `left_samples` для следующих операций.
            let left_samples: Vec<_> = data
                // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                .iter()
                // Копируем значения из ссылок, чтобы получить самостоятельные элементы.
                .copied()
                // Оставляем только элементы, прошедшие указанную проверку.
                .filter(|sample| sample.0 < threshold)
                // Собираем элементы итератора в итоговую коллекцию.
                .collect();
            // Сохраняем рассчитанное значение `right_samples` для следующих операций.
            let right_samples: Vec<_> = data
                // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                .iter()
                // Копируем значения из ссылок, чтобы получить самостоятельные элементы.
                .copied()
                // Оставляем только элементы, прошедшие указанную проверку.
                .filter(|sample| sample.0 >= threshold)
                // Собираем элементы итератора в итоговую коллекцию.
                .collect();
            // Обрабатываем этот вариант структуры данных отдельным правилом.
            Tree::Split {
                // Используем ранее рассчитанное значение `threshold` в текущем выражении.
                threshold,
                // Заполняем поле `left` соответствующим рассчитанным значением.
                left: Box::new(build_numeric_decision_tree(
                    // Передаём данные по ссылке или разыменовываем их для следующей операции.
                    &left_samples,
                    // Складываем или вычитаем величины согласно используемой формуле.
                    remaining_depth - 1,
                )),
                // Заполняем поле `right` соответствующим рассчитанным значением.
                right: Box::new(build_numeric_decision_tree(
                    // Передаём данные по ссылке или разыменовываем их для следующей операции.
                    &right_samples,
                    // Складываем или вычитаем величины согласно используемой формуле.
                    remaining_depth - 1,
                )),
            }
        } else {
            // Обрабатываем этот вариант структуры данных отдельным правилом.
            Tree::Leaf(positive_count * 2 >= data.len())
        }
    }

    // Шаг: Обучаем дерево, выбирая порог по уменьшению неоднородности.
    let tree = build_numeric_decision_tree(&data, 2);
    // Объявляем повторно используемое вычисление `classify_feature_with_decision_tree`; параметры ниже задают его входы.
    fn classify_feature_with_decision_tree(tree: &Tree, feature_value: f64) -> bool {
        // Разбираем каждый возможный вариант значения отдельно.
        match tree {
            // Обрабатываем этот вариант структуры данных отдельным правилом.
            Tree::Leaf(label) => *label,
            // Обрабатываем этот вариант структуры данных отдельным правилом.
            Tree::Split {
                // Используем ранее рассчитанное значение `threshold` в текущем выражении.
                threshold,
                // Используем ранее рассчитанное значение `left` в текущем выражении.
                left,
                // Используем ранее рассчитанное значение `right` в текущем выражении.
                right,
            } => classify_feature_with_decision_tree(
                // Проверяем условие и выбираем соответствующую ветку алгоритма.
                if feature_value < *threshold {
                    // Используем ранее рассчитанное значение `left` в текущем выражении.
                    left
                } else {
                    // Используем ранее рассчитанное значение `right` в текущем выражении.
                    right
                },
                // Используем ранее рассчитанное значение `feature_value` в текущем выражении.
                feature_value,
            ),
        }
    }

    // Шаг: Проверяем прогноз на новой точке и печатаем структуру дерева.
    println!(
        // Задаём шаблон строки: плейсхолдеры ниже заменятся рассчитанными значениями.
        "{tree:?}; x=3.5 -> {}",
        // Вызываем нужное вычисление с подготовленными аргументами.
        classify_feature_with_decision_tree(&tree, 3.5)
    );
}
