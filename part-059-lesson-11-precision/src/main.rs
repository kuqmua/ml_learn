// Урок 11.2. Точность положительных прогнозов.
//
// Что изучаем: Точность положительных прогнозов.
// Зачем это нужно: Precision показывает долю действительно положительных объектов среди всех положительных
// прогнозов.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `true_positive` для следующих операций.
    let true_positive = 8.0;
    // Сохраняем рассчитанное значение `false_positive` для следующих операций.
    let false_positive = 2.0;
    // Нормируем или усредняем величину делением и сохраняем её в `precision`.
    let precision = true_positive / (true_positive + false_positive);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("precision = {precision:.2}");
}
