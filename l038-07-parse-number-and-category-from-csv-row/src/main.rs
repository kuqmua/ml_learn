// Урок 07.2. Чтение числа и категории из строки CSV.
// Связь с принятой терминологией: Разбор числового и категориального признаков из строки CSV.
// Зачем здесь эта тема: Строки CSV приходят текстом, а модель ждёт числа и категории определённых
//   типов.
// Почему код устроен так: Разбираем поля по схеме и сообщаем ошибку поля до вычисления признаков.
// Представь: Строка CSV «25,Москва» содержит и число, и категорию; обращаться с ними одинаково
//   нельзя.
//
// Что изучаем: Типы признаков.
// Зачем это нужно: Числовой признак участвует в арифметике, категориальный кодирует метку. Разбор должен
// сохранить это различие.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
use lesson_trace::{enable_tracing, trace_note, trace_step};

fn main() {
    enable_tracing();
    trace_note!("Сохраняем рассчитанное значение `row` для следующих операций.");
    let row: &str = "3.5,red";
    trace_step!(row);
    trace_note!(
        "Сохраняем рассчитанное значение `(number_text, category)` для следующих операций."
    );
    let (number_text, category): (&str, &str) = row.split_once(',').expect("две колонки");
    trace_step!(number_text);
    trace_step!(category);
    trace_note!("Читаем или разбираем входные данные в значение `numeric_feature`.");
    let numeric_feature: f64 = number_text.parse().expect("число");
    trace_step!(numeric_feature);
    trace_note!("Сохраняем рассчитанное значение `categorical_feature` для следующих операций.");
    let categorical_feature: &str = category;
    trace_step!(categorical_feature);
    trace_note!("Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.");
    println!("число={numeric_feature}, категория={categorical_feature}");
}
