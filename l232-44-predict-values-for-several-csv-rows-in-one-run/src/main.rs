// Урок 232. Получаем прогнозы для нескольких строк данных за один запуск программы.
// Для каждой строки читаем входное число, умножаем его на вес и добавляем постоянную прибавку.
// Порядок прогнозов совпадает с порядком входных строк: так понятно, к чему относится каждый ответ.

fn main() {
    let features: [f64; 3] = [1.0, 2.0, 3.0];
    let weight: f64 = 2.0;
    let constant_input_weight: f64 = 1.0;
    for feature in features {
        let _ = &(weight * feature + constant_input_weight);
    }
}

