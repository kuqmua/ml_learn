// Урок 03.3. Правило цепочки для производной композиции функций.
//
// Что изучаем: Правило цепочки.
// Зачем это нужно: Производную композиции получаем умножением производной внешней функции на производную
// внутренней.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // f(x)=(2x+1)²: внутренняя функция u=2x+1, внешняя u².
    let input_value: f64 = 3.0;
    // Умножаем значения и сохраняем результат в `inner`.
    let inner: f64 = 2.0 * input_value + 1.0;
    // Умножаем значения и сохраняем результат в `outer_derivative`.
    let outer_derivative: f64 = 2.0 * inner;
    // Сохраняем рассчитанное значение `inner_derivative` для следующих операций.
    let inner_derivative: f64 = 2.0;
    // Умножаем значения и сохраняем результат в `derivative`.
    let derivative: f64 = outer_derivative * inner_derivative;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("f'(3)={derivative}");

    // Построение графика вынесено из основного кода урока.
    visualize_chain_rule_for_derivative_of_composed_functions();
}

// Строим график по результатам урока.
fn visualize_chain_rule_for_derivative_of_composed_functions() {
    // Наглядное представление величин из этого урока.
    let composed_function_points: Vec<(f64, f64)> = (-20..=20)
        // Преобразуем каждый элемент в новое значение.
        .map(|plot_step_index| {
            // Сохраняем результат этого шага в `horizontal_value`.
            let horizontal_value: f64 = plot_step_index as f64 / 10.0;
            // Добавляем пару значений для сравнения или построения графика.
            (
                horizontal_value,
                horizontal_value * horizontal_value * horizontal_value * horizontal_value,
            )
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Собираем значения для `derivative_points` в коллекцию.
    let derivative_points: Vec<(f64, f64)> = (-20..=20)
        // Преобразуем каждый элемент в новое значение.
        .map(|plot_step_index| {
            // Сохраняем результат этого шага в `horizontal_value`.
            let horizontal_value: f64 = plot_step_index as f64 / 10.0;
            // Добавляем пару значений для сравнения или построения графика.
            (
                horizontal_value,
                4.0 * horizontal_value * horizontal_value * horizontal_value,
            )
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Правило цепочки: (2x+1)²",
        // Указываем подпись горизонтальной оси.
        "x",
        // Указываем подпись вертикальной оси.
        "значение",
        // Передаём ряды или значения для отрисовки графика.
        &[
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "(2x+1)²",
                // Передаём рассчитанные координаты точек.
                points: &composed_function_points,
            },
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "производная",
                // Передаём рассчитанные координаты точек.
                points: &derivative_points,
            },
        ],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
