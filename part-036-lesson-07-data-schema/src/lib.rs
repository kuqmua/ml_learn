//! Вычисления и примеры урока part-036-lesson-07-data-schema.

// Урок 07.1. Схема данных.
//
// Что изучаем: Схема данных.
// Зачем это нужно: Схема задаёт имена колонок и ожидаемые типы. Проверка заголовка предотвращает
// незаметную перестановку признаков.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Сохраняем рассчитанное значение `csv` для следующих операций.
    let csv = "feature,target\n1.5,0\n2.5,1\n";
    // Создаём изменяемое значение `lines` для следующих операций.
    let mut lines = csv.lines();
    // Сохраняем рассчитанное значение `header` для следующих операций.
    let header = lines.next().expect("CSV не пустой");
    // Проверяем, что сравниваемые размерности или значения действительно совпадают.
    assert_eq!(header, "feature,target", "неверная схема CSV");
    // Считаем количество элементов и сохраняем его в `row_count`.
    let row_count = lines.count();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("схема верна, строк данных = {row_count}");
}
