// Урок 32.1. Self-attention.
//
// Что изучаем: Self-attention.
// Зачем это нужно: Токены одной последовательности сравниваются друг с другом, чтобы каждый выход учёл
// подходящий контекст.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `text_units` для следующего шага примера.
    // Единицу текста, которую модель обрабатывает как одно целое, называют token.
    let text_units = [1.0, 3.0];
    // Создаём набор значений `weights` для следующего шага примера.
    let weights = [[0.8, 0.2], [0.4, 0.6]];
    // Создаём набор значений `context` для следующего шага примера.
    let context = [
        // Умножаем величины согласно используемой формуле.
        weights[0][0] * text_units[0] + weights[0][1] * text_units[1],
        // Умножаем величины согласно используемой формуле.
        weights[1][0] * text_units[0] + weights[1][1] * text_units[1],
    ];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("контекст для двух позиций = {context:?}");

    // Построение графика вынесено из основного кода урока.
    visualize(context);
}

// Строим график по результатам урока.
fn visualize(context: [f64; 2]) {
    // Сравнение величин из этого урока.
    let chart = lesson_visualization::bar_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок диаграммы.
        "Self-attention: контекст",
        // Указываем подпись вертикальной оси.
        "компонента",
        // Передаём ряды или значения для отрисовки графика.
        &[("позиция 0", context[0]), ("позиция 1", context[1])],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
