// Урок 01.1. Умножение координат попарно и сложение результатов.
//
// Что изучаем: Умножение координат попарно и сложение результатов.
// Зачем это нужно: Умножаем соответствующие координаты двух векторов и складываем полученные числа. Результат
// показывает, насколько два вектора направлены в одну сторону: для перпендикулярных векторов он равен
// нулю. Сначала вычисли ответ для двух коротких векторов вручную, затем сравни с выводом.
// Что делает пример: проверяет равенство длин, затем вычисляет сумму на небольших данных и печатает её.
// Как проверить понимание: предскажи вывод до запуска, затем добавь координату только одному вектору
// и посмотри на сообщение об ошибке.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Для каждой координаты левого вектора нужна координата правого с тем же индексом.
    let left = [1.0, 2.0];
    // Измени число элементов здесь, чтобы увидеть срабатывание проверки ниже.
    let right = [3.0, 4.0];
    // Иначе лишняя координата одного вектора потеряется или обращение по индексу вызовет панику.
    assert_eq!(
        left.len(),
        right.len(),
        "векторы должны быть одинаковой длины"
    );
    // Начинаем сумму с нуля; каждая итерация добавляет результат умножения одной пары.
    let mut sum_after_multiplying_coordinates = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 0..left.len() {
        // Для примера ответ равен 1·3 + 2·4 = 11.
        sum_after_multiplying_coordinates += left[index] * right[index];
    }
    // Нулевая сумма для [1, 2] и [−2, 1] показала бы перпендикулярность.
    println!("сумма после попарного умножения координат = {sum_after_multiplying_coordinates}");
}
