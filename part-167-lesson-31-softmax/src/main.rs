// Урок 31.5. Нормировка softmax.
//
// Большая оценка получает больший вес. Равные оценки дают равные веса.
// Прибавление одной константы к обеим оценкам не меняет веса, а сумма весов равна 1.

fn main() {
    // Задаём учебные значения для `cases`.
    let cases = [
        // Добавляем пару значений для сравнения или построения графика.
        ("равные оценки", [0.0, 0.0]),
        // Добавляем пару значений для сравнения или построения графика.
        ("вторая оценка выше", [0.0, 1.0]),
        // Добавляем пару значений для сравнения или построения графика.
        ("первая оценка выше", [1.0, 0.0]),
        // Добавляем пару значений для сравнения или построения графика.
        ("к обеим прибавили 1", [1.0, 2.0]),
    ];
    // Задаём учебные значения для `reference_weights`.
    let mut reference_weights = [0.0; 2];
    // Повторяем расчёт для каждого элемента последовательности.
    // Оценку модели до преобразования в вероятность называют logit.
    for (description, raw_model_scores) in cases {
        // Задаём учебные значения для `exponentials`.
        let mut exponentials = [0.0; 2];
        // Повторяем расчёт для каждого элемента последовательности.
        for index in 0..2 {
            // Считаем exp(x) первыми 30 членами ряда Тейлора для малых учебных оценок.
            let mut term = 1.0;
            // Сохраняем результат этого шага в `sum`.
            let mut sum = 1.0;
            // Повторяем расчёт для каждого элемента последовательности.
            for order in 1..=30 {
                // Обновляем значение результатом текущего вычисления.
                term *= raw_model_scores[index] / order as f64;
                // Обновляем значение результатом текущего вычисления.
                sum += term;
            }
            // Обновляем значение результатом текущего вычисления.
            exponentials[index] = sum;
        }
        // Сохраняем результат этого шага в `denominator`.
        let denominator = exponentials[0] + exponentials[1];
        // Проверяем ожидаемое свойство учебного примера.
        assert!(
            // Используем подготовленное значение в следующем шаге примера.
            denominator > 0.0,
            // Передаём подпись или текстовое значение для следующего шага.
            "сумма экспонент должна быть положительной"
        );
        // Задаём учебные значения для `weights`.
        let weights = [exponentials[0] / denominator, exponentials[1] / denominator];
        // Проверяем ожидаемое свойство учебного примера.
        assert!((weights[0] + weights[1] - 1.0).abs() < 1e-10);
        // Проверяем ожидаемое свойство учебного примера.
        assert!(weights.iter().all(|&weight| (0.0..=1.0).contains(&weight)));
        // Разбираем результат по его возможным вариантам.
        match description {
            // Передаём подпись или текстовое значение для следующего шага.
            "равные оценки" => assert!((weights[0] - weights[1]).abs() < 1e-10),
            // Передаём подпись или текстовое значение для следующего шага.
            "вторая оценка выше" => {
                // Проверяем ожидаемое свойство учебного примера.
                assert!(weights[1] > weights[0]);
                // Обновляем значение результатом текущего вычисления.
                reference_weights = weights;
            }
            // Передаём подпись или текстовое значение для следующего шага.
            "первая оценка выше" => assert!(weights[0] > weights[1]),
            // Передаём подпись или текстовое значение для следующего шага.
            "к обеим прибавили 1" => {
                // Проверяем ожидаемое свойство учебного примера.
                assert!((weights[0] - reference_weights[0]).abs() < 1e-10);
                // Проверяем ожидаемое свойство учебного примера.
                assert!((weights[1] - reference_weights[1]).abs() < 1e-10);
            }
            // Выполняем действие для этого варианта данных.
            _ => unreachable!(),
        }
        // Печатаем рассчитанные значения для проверки примера.
        println!("{description}: {raw_model_scores:?} → {weights:?}");
    }

    // Построение графика вынесено из основного кода урока.
    visualize();
}

// Строим график по результатам урока.
fn visualize() {
    // График величин и зависимостей, изученных в этом уроке.
    // Преобразование оценок в вероятности с суммой 1 называют softmax.
    let normalized_probability_points: Vec<(f64, f64)> = (-60..=60)
        // Преобразуем каждый элемент в новое значение.
        .map(|plot_step_index| {
            // Сохраняем результат этого шага в `distance_value`.
            let distance_value = plot_step_index as f64 / 10.0;
            // Добавляем пару значений для сравнения или построения графика.
            (distance_value, 1.0 / (1.0 + (-distance_value).exp()))
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Softmax двух логитов",
        // Указываем подпись горизонтальной оси.
        "разность второго и первого",
        // Указываем подпись вертикальной оси.
        "вес второго",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "softmax",
            // Передаём рассчитанные координаты точек.
            points: &normalized_probability_points,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
