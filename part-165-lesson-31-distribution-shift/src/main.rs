// Урок 31.1. Сдвиг распределения.
//
// Что изучаем: Сдвиг распределения.
// Зачем это нужно: Новые данные могут отличаться от обучающих; сравнение средних даёт первый сигнал о
// таком изменении.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `reference` для следующего шага примера.
    let reference = [1.0, 2.0, 3.0];
    // Создаём набор значений `current` для следующего шага примера.
    let current = [5.0, 6.0, 7.0];
    assert!(
        !reference.is_empty() && !current.is_empty(),
        "обе выборки должны содержать значения"
    );
    // Преобразуем входные данные и сохраняем полученную коллекцию в `reference_mean`.
    let reference_mean = reference.iter().sum::<f64>() / reference.len() as f64;
    // Преобразуем входные данные и сохраняем полученную коллекцию в `current_mean`.
    let current_mean = current.iter().sum::<f64>() / current.len() as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("эталон={reference_mean}, новые данные={current_mean}");
}
