// Урок 43.4. Загрузка поддерживаемых старой и новой версий файла модели.
// Связь с принятой терминологией: Загрузка поддерживаемых старой и новой версий формата модели.
// Зачем здесь эта тема: Выпущенная модель должна пережить обновление формата без сломанного
//   инференса.
// Почему код устроен так: Разбираем старую и новую версии разными путями и приводим к одной
//   внутренней структуре.
// Представь: Старый сохранённый файл должен по-прежнему загружаться после обновления программы.
//
// Старая и новая версии разбираются разными правилами; неизвестную версию отвергаем.

fn main() {
    for (_description, saved_model_text, expected) in [
        ("старый формат", "model_v1\n2.0\n1.0\n", "вес и смещение"),
        (
            "новый формат",
            "model_v2\n2.0\n1.0\nmetadata\n",
            "параметры и метаданные",
        ),
        (
            "неизвестная версия",
            "model_v3\n2.0\n1.0\n",
            "формат не поддерживается",
        ),
    ] {
        let explanation: &str = match saved_model_text.lines().next() {
            Some("model_v1") => "вес и смещение",

            Some("model_v2") => "параметры и метаданные",

            _ => "формат не поддерживается",
        };
        assert_eq!(explanation, expected);
    }
}
