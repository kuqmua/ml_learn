//! Вычисления и примеры урока part-013-lesson-03-derivative.

// Урок 03.1. Производная одной переменной.
//
// Что изучаем: Производная одной переменной.
// Зачем это нужно: Производная показывает мгновенную скорость изменения функции. Для f(x)=x² аналитическая
// производная равна 2x.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Сохраняем рассчитанное значение `x` для следующих операций.
    let x = 3.0;
    // Умножаем значения и сохраняем результат в `derivative`.
    let derivative = 2.0 * x;
    // При x=3 малое увеличение аргумента меняет x² примерно в шесть раз быстрее.
    println!("f(x)=x²; f'(3)={derivative}");
}
