// Урок 217. Задавать награду за переход в новое состояние.
// Достижение цели получает положительную награду, остальные шаги — небольшую отрицательную,
// задавая предпочтение короткому пути.

fn main() {
    let goal = 4;
    let reward = |next| if next == goal { 1.0 } else { -0.01 };
    let short_path = [1, 2, 3, 4];
    let long_path = [1, 0, 1, 2, 3, 4];
    let short_reward = short_path.map(reward).iter().sum::<f64>();
    let long_reward = long_path.map(reward).iter().sum::<f64>();
    println!(
        "Короткий путь={short_path:?}, награда={short_reward}; путь с возвратом={long_path:?}, награда={long_reward}"
    );
    assert!(short_reward > long_reward);
}

