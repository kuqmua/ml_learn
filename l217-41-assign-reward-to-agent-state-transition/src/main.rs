// Урок 41.3. Назначение награды за переход агента между состояниями.
// Связь с принятой терминологией: Награда за переход агента между состояниями.
// Зачем здесь эта тема: Агенту нужна оценка последствий перехода, чтобы различать полезные
//   действия.
// Почему код устроен так: Назначаем награду переходу и отдельно показываем новое состояние.
// Представь: Шаг к цели приносит награду; тот же шаг в другой ситуации может не принести её.
//
// Что изучаем: Награда.
// Зачем это нужно: Награда сообщает агенту, насколько полезным оказался переход, и формирует цель
// обучения.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
use lesson_trace::{enable, trace_note, trace_step};

fn main() {
    enable();
    trace_note!("Сохраняем рассчитанное значение `next_state` для следующих операций.");
    let next_state: i32 = 4;
    trace_step!(next_state);
    trace_note!("Сохраняем рассчитанное значение `goal` для следующих операций.");
    let goal: i32 = 4;
    trace_step!(goal);
    trace_note!("Комбинируем исходные величины и сохраняем результат в `reward`.");
    let reward: f64 = if next_state == goal { 1.0 } else { -0.01 };
    trace_step!(reward);
    trace_note!("Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.");
    println!("после перехода награда={reward}");
}
