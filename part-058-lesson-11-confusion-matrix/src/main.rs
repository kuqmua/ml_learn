// Урок 11.1. Матрица ошибок классификации.
//
// Что изучаем: Матрица ошибок классификации.
// Зачем это нужно: Четыре счётчика отделяют верные положительные и отрицательные ответы от двух видов
// ошибок.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `truth` для следующего шага примера.
    let truth = [true, false, true, false];
    // Создаём набор значений `predicted` для следующего шага примера.
    let predicted = [true, true, false, false];
    // Для каждого правильного ответа нужен ровно один прогноз.
    assert_eq!(
        truth.len(),
        predicted.len(),
        "число прогнозов должно совпадать с числом ответов"
    );
    // Сохраняем рассчитанное значение `(mut tp, mut fp, mut fn_count, mut tn)` для следующих операций.
    let (mut tp, mut fp, mut fn_count, mut tn) = (0, 0, 0, 0);
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 0..truth.len() {
        // Разбираем каждый возможный вариант значения отдельно.
        match (truth[index], predicted[index]) {
            // Прибавляем очередной вклад к ранее накопленному результату.
            (true, true) => {
                tp += 1;
                println!("истина=true, прогноз=true → TP: верно найден положительный класс");
            }
            // Прибавляем очередной вклад к ранее накопленному результату.
            (false, true) => {
                fp += 1;
                println!("истина=false, прогноз=true → FP: ложная тревога");
            }
            // Прибавляем очередной вклад к ранее накопленному результату.
            (true, false) => {
                fn_count += 1;
                println!("истина=true, прогноз=false → FN: положительный класс пропущен");
            }
            // Прибавляем очередной вклад к ранее накопленному результату.
            (false, false) => {
                tn += 1;
                println!("истина=false, прогноз=false → TN: верно найден отрицательный класс");
            }
        }
    }
    assert_eq!((tp, fp, fn_count, tn), (1, 1, 1, 1));
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("TP={tp}, FP={fp}, FN={fn_count}, TN={tn}");
}
