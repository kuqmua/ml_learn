// Урок 17.1. Центроиды кластеров.
//
// Что изучаем: Центроиды кластеров.
// Зачем это нужно: Центроид — покоординатное среднее точек одной группы. Он представляет центр кластера.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `cluster` для следующего шага примера.
    let cluster = [[1.0, 2.0], [3.0, 4.0]];
    // Создаём набор значений `centroid` для следующего шага примера.
    // Среднее пустого кластера не определено.
    assert!(!cluster.is_empty(), "для центра нужна хотя бы одна точка");
    let mut centroid = [0.0, 0.0];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for point in cluster {
        // Прибавляем очередной вклад к ранее накопленному результату.
        centroid[0] += point[0];
        // Прибавляем очередной вклад к ранее накопленному результату.
        centroid[1] += point[1];
    }
    // Масштабируем текущую величину делением.
    centroid[0] /= cluster.len() as f64;
    // Масштабируем текущую величину делением.
    centroid[1] /= cluster.len() as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("центроид = {centroid:?}");
    // Значения из этого урока на графике.
    let chart_points_0: Vec<(f64, f64)> = cluster.iter().map(|p| (p[0], p[1])).collect();
    let chart_points_1: Vec<(f64, f64)> = vec![(centroid[0], centroid[1])];
    let chart = lesson_visualization::scatter_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Точки кластера и центроид",
        "x",
        "y",
        &[
            lesson_visualization::Series {
                name: "точки",
                points: &chart_points_0,
            },
            lesson_visualization::Series {
                name: "центроид",
                points: &chart_points_1,
            },
        ],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
