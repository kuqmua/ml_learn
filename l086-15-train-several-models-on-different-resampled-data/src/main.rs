// Урок 086. Получать простые модели из разных повторных выборок и объединять их голоса.
// Проверяем разные выученные постоянные классы; голосование само по себе не гарантирует улучшение
// качества.

fn main() {
    let training = [false, false, true, true, true];
    let samples = [[0, 0, 1, 2, 3], [1, 2, 2, 3, 4], [0, 2, 3, 4, 4]];
    let models = samples.map(|indices| {
        let sample = indices.map(|i| training[i]);
        let majority = sample.iter().filter(|&&v| v).count() * 2 > sample.len();
        println!("Обучающая выборка={sample:?}, выученный постоянный класс={majority}");
        majority
    });
    let ensemble = models.iter().filter(|&&v| v).count() * 2 > models.len();
    println!("Ответы простых моделей={models:?}, большинство={ensemble}");
    assert_eq!(models, [false, true, true]);
    assert!(ensemble);
    println!(
        "Разный состав выборок дал разные модели. Голосование не гарантирует улучшения на любых данных."
    );
}

