// Урок 34.4. Алерты мониторинга.
//
// Что изучаем: Алерты мониторинга.
// Зачем это нужно: Порог превращает непрерывную метрику дрейфа в понятный сигнал для проверки системы.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Инициализируем значение `drift_score` начальным состоянием.
    let drift_score = 0.35;
    // Инициализируем значение `alert_threshold` начальным состоянием.
    let alert_threshold = 0.2;
    // Сохраняем рассчитанное значение `alert` для следующих операций.
    let alert = drift_score > alert_threshold;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("дрейф={drift_score}, требуется проверка={alert}");
}
