// Урок 09.2. Средняя абсолютная ошибка.
//
// Что изучаем: Средняя абсолютная ошибка.
// Зачем это нужно: MAE усредняет модули ошибок и показывает среднюю величину промаха в единицах целевой
// переменной.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `targets` для следующего шага примера.
    let targets = [2.0, 4.0, 6.0];
    // Создаём набор значений `predictions` для следующего шага примера.
    let predictions = [2.0, 5.0, 4.0];
    // Ошибку можно посчитать только для пары: истинное значение и прогноз.
    assert_eq!(
        targets.len(),
        predictions.len(),
        "число прогнозов должно совпадать с числом ответов"
    );
    assert!(
        !targets.is_empty(),
        "для MAE нужна хотя бы одна пара значений"
    );
    // Инициализируем изменяемый накопитель `absolute_error_sum` начальным состоянием.
    let mut absolute_error_sum = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 0..targets.len() {
        // Комбинируем исходные величины и сохраняем результат в `error`.
        let error = predictions[index] - targets[index];
        // Прибавляем очередной вклад к ранее накопленному результату.
        absolute_error_sum += if error < 0.0 { -error } else { error };
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("MAE = {}", absolute_error_sum / targets.len() as f64);
}
