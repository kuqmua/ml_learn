// Урок 215. Представлять положение агента и цель номерами ячеек.
// Разница номеров показывает смещение до цели в простом одномерном мире.

fn main() {
    let cells = 0..=4;
    let goal = 4;
    for position in cells {
        let offset = goal - position;
        println!("Положение={position}, цель={goal}, смещение={offset}");
        assert!(offset >= 0);
        if position == goal {
            assert_eq!(offset, 0);
        }
    }
}

