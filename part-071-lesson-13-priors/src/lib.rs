//! Вычисления и примеры урока part-071-lesson-13-priors.

// Урок 13.2. Априорные вероятности классов.
//
// Что изучаем: Априорные вероятности классов.
// Зачем это нужно: До чтения признаков модель учитывает, как часто встречается каждый класс в обучающем
// наборе.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Создаём набор значений `labels` для следующего шага примера.
    let labels = ["code", "code", "code", "ml"];
    assert!(
        !labels.is_empty(),
        "для частоты класса нужна хотя бы одна метка"
    );
    // Преобразуем входные данные и сохраняем полученную коллекцию в `code_count`.
    let code_count = labels.iter().filter(|&&label| label == "code").count();
    // Считаем количество элементов и сохраняем его в `code_prior`.
    let code_prior = code_count as f64 / labels.len() as f64;
    // Комбинируем исходные величины и сохраняем результат в `ml_prior`.
    let ml_prior = 1.0 - code_prior;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("P(code)={code_prior}, P(ml)={ml_prior}");
}
