// Урок 15.1. Выборка с возвращением для обучения ансамбля.
//
// Что изучаем: Bootstrap-выборка.
// Зачем это нужно: Случайная выборка с возвращением может содержать один объект несколько раз и пропускать
// другой.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `data` для следующего шага примера.
    let data: [&str; 4] = ["A", "B", "C", "D"];
    // Создаём набор значений `sampled_indices` для следующего шага примера.
    let sampled_indices: [usize; 4] = [0, 2, 2, 3];
    // Преобразуем входные данные и сохраняем полученную коллекцию в `sample`.
    let sample: Vec<&str> = sampled_indices.iter().map(|&index| data[index]).collect();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("исходные={data:?}, bootstrap={sample:?}");

    // Построение графика вынесено из основного кода урока.
    visualize_bootstrap_sample_with_replacement_for_ensemble(sample);
}

// Строим график по результатам урока.
fn visualize_bootstrap_sample_with_replacement_for_ensemble(sample: std::vec::Vec<&str>) {
    // Сравниваем величины, вычисленные в примере.
    let chart: std::path::PathBuf = lesson_visualization::bar_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок диаграммы.
        "Повторы в bootstrap-выборке",
        // Указываем подпись вертикальной оси.
        "число появлений",
        // Передаём ряды или значения для отрисовки графика.
        &[
            // Добавляем пару значений для сравнения или построения графика.
            (
                "A",
                sample
                    .iter()
                    .filter(|&&horizontal_value| horizontal_value == "A")
                    .count() as f64,
            ),
            // Добавляем пару значений для сравнения или построения графика.
            (
                "B",
                sample
                    .iter()
                    .filter(|&&horizontal_value| horizontal_value == "B")
                    .count() as f64,
            ),
            // Добавляем пару значений для сравнения или построения графика.
            (
                "C",
                sample
                    .iter()
                    .filter(|&&horizontal_value| horizontal_value == "C")
                    .count() as f64,
            ),
            // Добавляем пару значений для сравнения или построения графика.
            (
                "D",
                sample
                    .iter()
                    .filter(|&&horizontal_value| horizontal_value == "D")
                    .count() as f64,
            ),
        ],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
