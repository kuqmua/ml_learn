// Урок 081. Считать смешанность классов как единицу минус сумму квадратов их долей.
// Такая оценка, называемая критерием Джини, позволяет судить об однородности группы без
// логарифмов.

fn main() {
    let mut values = Vec::new();
    for share in [0.0_f64, 0.25, 0.5, 1.0] {
        let mixing = 1.0 - share * share - (1.0 - share) * (1.0 - share);
        println!("Доля класса={share}, смешанность={mixing}");
        values.push(mixing);
    }
    assert_eq!(values[0], 0.0);
    assert_eq!(values[3], 0.0);
    assert!(values[2] > values[1]);
}

