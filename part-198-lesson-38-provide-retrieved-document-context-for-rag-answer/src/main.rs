// Урок 38.1. Передача найденного фрагмента документа как контекста ответа RAG.
//
// Что изучаем: Контекст для ответа.
// Зачем это нужно: В RAG найденный фрагмент передаёт факты, на которые должен опираться ответ.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `context` для следующих операций.
    let context: &str = "Rust использует Cargo для сборки проектов.";
    // Сохраняем рассчитанное значение `question` для следующих операций.
    let question: &str = "Чем собирают проект Rust?";
    // Сохраняем рассчитанное значение `answer` для следующих операций.
    let answer: &str = if context.contains("Cargo") {
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "Cargo"
    // Обрабатываем случай, когда предыдущее условие не выполнено.
    } else {
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "не знаю"
    };
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("вопрос: {question}; контекст: {context}; ответ: {answer}");
}
