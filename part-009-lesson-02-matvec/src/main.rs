// Урок 02.3. Умножение матрицы на вектор.
//
// Что изучаем: Умножение матрицы на вектор.
// Зачем это нужно: Каждая выходная координата равна сумме после попарного умножения координат строки матрицы и входного
// вектора.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `matrix` для следующего шага примера.
    let matrix = [[1.0, 2.0], [3.0, 4.0]];
    // Создаём набор значений `vector` для следующего шага примера.
    let vector = [5.0, 6.0];
    // Создаём набор значений `result` для следующего шага примера.
    let mut result = [0.0; 2];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for row in 0..2 {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for column in 0..2 {
            // Умножаем пару соответствующих координат и добавляем вклад в строку.
            result[row] += matrix[row][column] * vector[column];
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("A·x = {result:?}");
}
