// Урок 24.3. Дополнение изображения нулями перед свёрткой.
//
// Что изучаем: Дополнение изображения padding.
// Зачем это нужно: Нулевые значения вокруг изображения позволяют ядру обработать крайние пиксели.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `image` для следующего шага примера.
    let image: [[i32; 2]; 2] = [[1, 2], [3, 4]];
    // Создаём набор значений `image_with_zero_border` для следующего шага примера.
    // Добавление нулевой рамки к изображению называют padding.
    let mut image_with_zero_border: [[i32; 4]; 4] = [[0; 4]; 4];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for row in 0..2 {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for column in 0..2 {
            // Присваиваем вычисленное значение соответствующей переменной или полю.
            image_with_zero_border[row + 1][column + 1] = image[row][column];
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("после padding: {image_with_zero_border:?}");

    // Построение графика вынесено из основного кода урока.
    visualize_pad_image_with_zeros_before_convolution(image_with_zero_border);
}

// Строим график по результатам урока.
fn visualize_pad_image_with_zeros_before_convolution(image_with_zero_border: [[i32; 4]; 4]) {
    // Значения ячеек видны по цвету и подписи.
    let chart: std::path::PathBuf = lesson_visualization::heatmap(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок тепловой карты.
        "Padding: дополненное изображение",
        // Используем подготовленное значение в следующем шаге примера.
        &image_with_zero_border
            // Просматриваем элементы коллекции по ссылке.
            .iter()
            // Преобразуем каждый элемент в новое значение.
            .map(|row| {
                row.iter()
                    .map(|&element_value| element_value as f64)
                    .collect::<Vec<_>>()
            })
            // Настраиваем или преобразуем результат предыдущего шага.
            .collect::<Vec<_>>(),
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить тепловую карту");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
