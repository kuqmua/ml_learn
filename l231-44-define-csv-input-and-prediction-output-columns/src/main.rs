// Урок 231. Задаём, какие столбцы должен содержать входной файл с данными
// и какие столбцы программа выдаст в файле с прогнозами.
// CSV — это текстовая таблица: одна строка файла соответствует одной строке данных,
// а значения столбцов разделены запятыми. Заголовок объясняет назначение каждого столбца.

fn main() {
    let input: &str = "feature\n1\n2\n";
    let mut lines: std::str::Lines<'_> = input.lines();
    assert_eq!(lines.next(), Some("feature"));

    for line in lines {
        let _ = line.parse::<f64>().unwrap() * 2.0 + 1.0;
    }
}
