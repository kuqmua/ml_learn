// Урок 44.1. Определение столбцов входного CSV и выходных прогнозов.
// Связь с принятой терминологией: Контракт CSV ввода и вывода для консольного инференса.
// Зачем здесь эта тема: Консольный инференс должен иметь однозначный контракт между файлом
//   пользователя и моделью.
// Почему код устроен так: Явно фиксируем заголовки и типы CSV на входе и выходе.
// Представь: Если вход ждёт столбец feature, файл с другим заголовком должен получить понятную
//   ошибку.
//
// Что изучаем: Контракт ввода и вывода CLI.
// Зачем это нужно: Программа принимает CSV с определённым заголовком и возвращает предсказания в известной
// схеме.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    lesson_trace::trace_note!("Сохраняем рассчитанное значение `input` для следующих операций.");
    let input: &str = "feature\n1\n2\n";
    lesson_trace::trace_step!(input);
    lesson_trace::trace_note!("Создаём изменяемое значение `lines` для следующих операций.");
    let mut lines: std::str::Lines<'_> = input.lines();
    lesson_trace::trace_step!(lines);
    lesson_trace::trace_note!(
        "Проверяем, что сравниваемые размерности или значения действительно совпадают."
    );
    assert_eq!(lines.next(), Some("feature"));
    lesson_trace::trace_note!(
        "Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением."
    );
    println!("prediction");
    lesson_trace::trace_note!(
        "Повторяем следующий блок для каждого элемента указанной последовательности."
    );
    for line in lines {
        lesson_trace::trace_step!(line);
        lesson_trace::trace_note!("Читаем или разбираем входные данные в значение `feature`.");
        let feature: f64 = line.parse().unwrap();
        lesson_trace::trace_step!(feature);
        lesson_trace::trace_note!(
            "Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением."
        );
        println!("{}", feature * 2.0 + 1.0);
    }
}
