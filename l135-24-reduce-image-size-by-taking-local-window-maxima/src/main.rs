// Урок 135. Заменять участок изображения одним максимальным значением.
// Так уменьшаем число значений, сохраняя самый сильный отклик в выбранном участке.

fn main() {
    let feature_map: [[f64; 2]; 2] = [[1.0, 4.0], [3.0, 2.0]];
    assert!(
        !feature_map.is_empty() && !feature_map[0].is_empty(),
        "карта признаков не должна быть пустой"
    );
    let mut maximum: f64 = feature_map[0][0];
    for row in feature_map {
        for value in row {
            if value > maximum {
                maximum = value;
            }
        }
    }

    // Выполняем вычисления из примера.
    let _ = (&feature_map, &maximum);

    println!("Участок={feature_map:?}; один сохранённый максимум={maximum}");
    assert_eq!(maximum, 4.0);
    println!(
        "Четыре числа заменили одним: самый сильный отклик сохранился, его точное положение потерялось."
    );
}

