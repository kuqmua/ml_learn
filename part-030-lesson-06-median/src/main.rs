// Урок 06.2. Медиана.
//
// Что изучаем: Медиана.
// Зачем это нужно: Медиана делит упорядоченный набор пополам и меньше среднего реагирует на выбросы.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `values` для следующего шага примера.
    let mut values = [2.0, 100.0, 4.0, 6.0];
    // Сортируем значения в порядке, заданном функцией сравнения.
    values.sort_by(f64::total_cmp);
    // Считаем количество элементов и сохраняем его в `middle`.
    let middle = values.len() / 2;
    // Нормируем или усредняем величину делением и сохраняем её в `median`.
    let median = (values[middle - 1] + values[middle]) / 2.0;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("медиана = {median}, отсортировано: {values:?}");
}
