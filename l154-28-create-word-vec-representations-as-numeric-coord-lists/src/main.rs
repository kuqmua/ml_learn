// Урок 154. Находить вектор слова в таблице по его идентификатору.
// Различаем номер слова и список его числовых признаков; таблица в этом примере задана заранее.

fn main() {
    let table = [[0.0, 0.0], [0.8, 0.2], [0.7, 0.3]];
    let identifiers = [1, 2, 1];
    let vectors = identifiers.map(|id| table[id]);
    println!("Идентификаторы={identifiers:?}; найденные векторы={vectors:?}");
    assert_eq!(vectors[0], vectors[2]);
    assert_ne!(vectors[0], vectors[1]);
    println!("Номер выбирает строку таблицы, но сам не является мерой сходства слов.");
}

