// Урок 11.4. Мера F1.
//
// Что изучаем: Мера F1.
// Зачем это нужно: F1 — гармоническое среднее precision и recall; она падает, если одна из этих величин
// мала.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Инициализируем значение `precision` начальным состоянием.
    let precision = 0.8;
    // Инициализируем значение `recall` начальным состоянием.
    let recall = 0.5;
    // Нормируем или усредняем величину делением и сохраняем её в `f1`.
    let f1 = 2.0 * precision * recall / (precision + recall);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("F1 = {f1:.3}");
}
