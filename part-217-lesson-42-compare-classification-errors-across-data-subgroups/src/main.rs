// Урок 42.3. Сравнение ошибок классификации по подгруппам данных.
// Почему этот урок сейчас: Общая метрика может скрывать ухудшение для отдельной группы пользователей или данных.
// Почему пример устроен так: Считаем одну и ту же ошибку отдельно по подгруппам и сравниваем размеры групп.
//
// Что изучаем: Ошибки по подгруппам.
// Зачем это нужно: Общая accuracy скрывает различия качества между группами; считаем ошибку отдельно.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Создаём набор значений `groups` для следующего шага примера.
    let groups: [(&str, bool, bool); 4] = [
        // Составляем результат из вычисленных значений в указанном порядке.
        ("A", true, true),
        // Составляем результат из вычисленных значений в указанном порядке.
        ("A", false, false),
        // Составляем результат из вычисленных значений в указанном порядке.
        ("B", true, false),
        // Составляем результат из вычисленных значений в указанном порядке.
        ("B", false, false),
    ];
    lesson_trace::trace_step!(groups);
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for group_name in ["A", "B"] {
        lesson_trace::trace_step!(group_name);
        // Сохраняем рассчитанное значение `matching` для следующих операций.
        let matching: Vec<&(&str, bool, bool)> = groups
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Оставляем только элементы, прошедшие указанную проверку.
            .filter(|&&(name, _, _)| name == group_name)
            // Собираем элементы итератора в итоговую коллекцию.
            .collect();
        lesson_trace::trace_step!(matching);
        // Проверяем ожидаемое свойство учебного примера.
        assert!(
            // Используем подготовленное значение в следующем шаге примера.
            !matching.is_empty(),
            // Передаём подпись или текстовое значение для следующего шага.
            "для оценки группы нужен хотя бы один пример"
        );
        // Сохраняем рассчитанное значение `correct` для следующих операций.
        let correct: usize = matching
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Оставляем только элементы, прошедшие указанную проверку.
            .filter(|sample| sample.1 == sample.2)
            // Подсчитываем число элементов после отбора.
            .count();
        lesson_trace::trace_step!(correct);
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!(
            // Присваиваем вычисленное значение соответствующей переменной или полю.
            "группа {group_name}: accuracy={:.2}",
            // Делим значения, получая нормированную величину или среднее.
            correct as f64 / matching.len() as f64
        );
    }

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_compare_classification_errors_across_data_subgroups(groups);
}

// Строим график по результатам урока.
fn visualize_compare_classification_errors_across_data_subgroups(groups: [(&str, bool, bool); 4]) {
    // Сохраняем результат этого шага в `group_accuracy`.
    let group_accuracy: &dyn Fn(&str) -> f64 = &|name: &str| {
        // Собираем значения для `examples` в коллекцию.
        let examples: Vec<&(&str, bool, bool)> = groups
            // Просматриваем элементы коллекции по ссылке.
            .iter()
            // Оставляем элементы, отвечающие условию.
            .filter(|(group, _, _)| *group == name)
            // Собираем результаты в коллекцию.
            .collect();
        // Используем подготовленное значение в следующем шаге примера.
        examples
            // Просматриваем элементы коллекции по ссылке.
            .iter()
            // Оставляем элементы, отвечающие условию.
            .filter(|(_, truth, predicted)| truth == predicted)
            // Подсчитываем число подходящих элементов.
            .count() as f64
            // Используем подготовленное значение в следующем шаге примера.
            / examples.len() as f64
    };
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::bar_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок диаграммы.
        "Точность по подгруппам",
        // Указываем подпись вертикальной оси.
        "accuracy",
        // Передаём ряды или значения для отрисовки графика.
        &[("A", group_accuracy("A")), ("B", group_accuracy("B"))],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
