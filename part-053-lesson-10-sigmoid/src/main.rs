// Урок 10.1. Сигмоидная функция.
//
// Что изучаем: Сигмоидная функция.
// Зачем это нужно: Сигмоида переводит произвольный logit в число между нулём и единицей. Экспоненту
// приближаем рядом Тейлора.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `logit` для следующих операций.
    let logit = 1.0;
    // Создаём изменяемое значение `term` для следующих операций.
    let mut term = 1.0;
    // Создаём изменяемое значение `exponential` для следующих операций.
    let mut exponential = 1.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for index in 1..=30 {
        // Умножаем накопленное значение на очередной множитель.
        term *= -logit / index as f64;
        // Прибавляем очередной вклад к ранее накопленному результату.
        exponential += term;
    }
    // Нормируем или усредняем величину делением и сохраняем её в `probability`.
    let probability = 1.0 / (1.0 + exponential);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("sigmoid({logit}) = {probability:.4}");
}
