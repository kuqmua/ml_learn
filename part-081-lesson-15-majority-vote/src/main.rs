// Урок 15.3. Голосование большинства.
//
// Что изучаем: Голосование большинства.
// Зачем это нужно: Каждая базовая модель отдаёт один голос; итоговый класс определяется числом голосов.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `votes` для следующего шага примера.
    let votes = [true, true, false];
    // Преобразуем входные данные и сохраняем полученную коллекцию в `positives`.
    let positives = votes.iter().filter(|&&vote| vote).count();
    // Считаем количество элементов и сохраняем его в `result`.
    let result = positives * 2 > votes.len();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("голоса={votes:?}, итог={result}");
}
