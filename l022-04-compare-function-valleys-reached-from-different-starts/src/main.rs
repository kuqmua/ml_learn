// Урок 022. Запускать уменьшение ошибки из разных начальных точек.
// На функции с двумя впадинами видим, что итоговый параметр зависит от старта.

fn main() {
    let loss = |x: f64| x.powi(4) - 2.0 * x * x;
    let mut results = Vec::new();
    for start in [-0.5_f64, 0.5] {
        let mut x = start;
        for _ in 0..100 {
            x -= 0.1 * (4.0 * x * x * x - 4.0 * x);
        }
        println!(
            "Начали с {start}, пришли к {x}; ошибка {} -> {}",
            loss(start),
            loss(x)
        );
        assert!(loss(x) < loss(start));
        results.push(x);
    }
    assert!(results[0] < 0.0 && results[1] > 0.0);
    println!(
        "Получили разные параметры. В этой симметричной функции обе впадины одинаково глубоки."
    );
}

