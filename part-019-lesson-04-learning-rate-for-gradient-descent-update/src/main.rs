// Урок 04.1. Скорость обучения в шаге градиентного спуска.
// Почему этот урок сейчас: Градиент показывает направление, но не размер шага; его задаёт скорость обучения.
// Почему пример устроен так: Сравниваем обновления одного параметра при разных коэффициентах, чтобы увидеть перескок и медленное движение.
//
// Что изучаем: Скорость обучения.
// Зачем это нужно: Один и тот же градиент даёт разные шаги при разных learning rate. Слишком большой шаг
// может перескочить минимум.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Инициализируем значение `parameter` начальным состоянием.
    let parameter: f64 = 0.0;
    lesson_trace::trace_step!(parameter);
    // Умножаем значения и сохраняем результат в `rate_of_change`.
    // Производную функции по параметру или вектор таких производных называют gradient.
    let rate_of_change: f64 = 2.0 * (parameter - 3.0);
    lesson_trace::trace_step!(rate_of_change);
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for rate in [0.1, 1.0, 2.0] {
        lesson_trace::trace_step!(rate);
        // Делаем ровно одно обновление, чтобы изолировать влияние скорости.
        let updated: f64 = parameter - rate * rate_of_change;
        lesson_trace::trace_step!(updated);
        // Умножаем значения и сохраняем результат в `error`.
        let error: f64 = (updated - 3.0) * (updated - 3.0);
        lesson_trace::trace_step!(error);
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("rate={rate}: параметр={updated}, ошибка={error}");
    }

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_learning_rate_for_gradient_descent_update(parameter, rate_of_change);
}

// Строим график по результатам урока.
fn visualize_learning_rate_for_gradient_descent_update(parameter: f64, rate_of_change: f64) {
    // Задаём учебные значения для `learning_rates`.
    let learning_rates: [f64; 3] = [0.1, 1.0, 2.0];
    // Собираем значения для `errors` в коллекцию.
    let errors: Vec<(f64, f64)> = learning_rates
        // Передаём элементы коллекции в итератор.
        .into_iter()
        // Преобразуем каждый элемент в новое значение.
        .map(|rate| {
            // Сохраняем результат этого шага в `updated`.
            let updated: f64 = parameter - rate * rate_of_change;
            // Добавляем пару значений для сравнения или построения графика.
            (rate, (updated - 3.0) * (updated - 3.0))
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "learning-rate",
        // Указываем заголовок графика.
        "Ошибка после одного шага",
        // Указываем подпись горизонтальной оси.
        "Скорость обучения",
        // Указываем подпись вертикальной оси.
        "Квадратичная ошибка",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "Ошибка",
            // Передаём рассчитанные координаты точек.
            points: &errors,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
