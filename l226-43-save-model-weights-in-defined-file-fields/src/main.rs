// Урок 226. Преобразовывать параметры модели в текст и читать их обратно в заданном порядке.
// В этом примере формат хранится в строке; запись на диск появится в следующей практике.

fn main() {
    let (weight, bias) = (2.0_f64, 1.0_f64);
    let saved = format!("{weight}\n{bias}\n");
    let values: Vec<f64> = saved.lines().map(|line| line.parse().unwrap()).collect();
    let before = weight * 3.0 + bias;
    let after = values[0] * 3.0 + values[1];
    println!("Сохранённый текст={saved:?}; прогноз до={before}, после чтения={after}");
    assert_eq!(before, after);
}

