// Урок 02.2. Транспонирование матрицы.
//
// Что изучаем: Транспонирование матрицы.
// Зачем это нужно: Строки исходной матрицы становятся столбцами результата. Значение не меняется, меняются
// только его координаты.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `matrix` для следующего шага примера.
    let matrix = [[1, 2, 3], [4, 5, 6]];
    // Создаём набор значений `transposed` для следующего шага примера.
    let mut transposed = [[0; 2]; 3];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for row in 0..2 {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for column in 0..3 {
            // Элемент [row, column] переносим в [column, row].
            transposed[column][row] = matrix[row][column];
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("исходная: {matrix:?}; транспонированная: {transposed:?}");

    // Повторное транспонирование возвращает каждое число на исходное место.
    let mut restored = [[0; 3]; 2];
    for row in 0..transposed.len() {
        for column in 0..transposed[row].len() {
            restored[column][row] = transposed[row][column];
        }
    }
    assert_eq!(restored, matrix);
    println!("после второго транспонирования: {restored:?}");
}
