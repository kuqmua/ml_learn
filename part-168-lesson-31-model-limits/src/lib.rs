//! Вычисления и примеры урока part-168-lesson-31-model-limits.

// Урок 31.4. Ограничения модели.
//
// Что изучаем: Ограничения модели.
// Зачем это нужно: На маленькой выборке высокая метрика нестабильна; отчёт должен показывать размер набора
// вместе с результатом.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Сохраняем рассчитанное значение `correct` для следующих операций.
    let correct = 2;
    // Сохраняем рассчитанное значение `total` для следующих операций.
    let total = 2;
    // Нормируем или усредняем величину делением и сохраняем её в `accuracy`.
    let accuracy = correct as f64 / total as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("accuracy={accuracy:.2} на {total} объектах: вывод ненадёжен");
}
