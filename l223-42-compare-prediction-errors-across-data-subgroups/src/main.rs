// Урок 42.3. Сравнение ошибок прогноза в разных подгруппах данных.
// Зачем здесь эта тема: Общая метрика может скрывать ухудшение для отдельной группы пользователей
//   или данных.
// Почему код устроен так: Считаем одну и ту же ошибку отдельно по подгруппам и сравниваем размеры
//   групп.
// Представь: Общая accuracy 90% может скрыть 50% accuracy для маленькой важной группы.
//
// Что изучаем: Ошибки по подгруппам.
// Зачем это нужно: Общая accuracy скрывает различия качества между группами; считаем ошибку отдельно.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.

fn main() {
    let groups: [(&str, bool, bool); 4] = [
        ("A", true, true),
        ("A", false, false),
        ("B", true, false),
        ("B", false, false),
    ];
    for group_name in ["A", "B"] {
        let matching: Vec<&(&str, bool, bool)> = groups
            .iter()
            .filter(|&&(name, _, _)| name == group_name)
            .collect();
        assert!(
            !matching.is_empty(),
            "для оценки группы нужен хотя бы один пример"
        );

        let _ = &(matching
            .iter()
            .filter(|sample| sample.1 == sample.2)
            .count() as f64
            / matching.len() as f64);
    }

    // Выполняем вычисления из примера.
    let _ = groups;
}

// Чему учит этот урок:
// Учимся считать качество отдельно по подгруппам данных.
// Так можно заметить, что общая оценка скрывает разное число ошибок в разных группах.
