// Урок 042. Замечать утечку проверочных данных в подготовку модели.
// Сравниваем среднее обучения со средним после добавления тестового значения: статистика уже
// изменилась из-за теста.

fn main() {
    let training_data: [f64; 3] = [1.0, 2.0, 3.0];
    assert!(
        !training_data.is_empty(),
        "обучающая выборка не должна быть пустой"
    );
    let training_mean: f64 = training_data.iter().sum::<f64>() / training_data.len() as f64;
    let test: [f64; 1] = [100.0];
    let contaminated_mean: f64 = (training_data.iter().sum::<f64>() + test.iter().sum::<f64>())
        / (training_data.len() + test.len()) as f64;

    // Выполняем вычисления из примера.
    let _ = (&training_mean, &contaminated_mean);

    println!(
        "Среднее только обучения={training_mean}; после подмешивания теста={contaminated_mean}"
    );
    assert_eq!(training_mean, 2.0);
    assert_eq!(contaminated_mean, 26.5);
    println!("Тестовое значение 100 изменило подготовку данных: независимость проверки потеряна.");
}

