// Урок 153. Выделять отдельные идентификаторы для неизвестного слова, начала и конца
// последовательности.
// Так структура текста и незнакомые слова получают явное представление в списке чисел.

fn main() {
    let (unknown, begin, end, known) = (0, 1, 2, 3);
    let vocabulary = std::collections::BTreeMap::from([("кот", known)]);
    let mut sequence = vec![begin];
    for word in ["кот", "незнакомое"] {
        sequence.push(*vocabulary.get(word).unwrap_or(&unknown));
    }
    sequence.push(end);
    println!("Начало + слова + конец: {sequence:?}");
    assert_eq!(sequence, vec![1, 3, 0, 2]);
}

