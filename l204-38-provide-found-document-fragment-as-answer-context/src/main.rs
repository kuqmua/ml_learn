fn main() {
    let answer = |context: &str| {
        if context.contains("Cargo") {
            Some("Cargo")
        } else {
            None
        }
    };
    for context in [
        "Rust использует Cargo для сборки проектов.",
        "Rust управляет памятью.",
    ] {
        println!(
            "Контекст={context:?}; ответ на вопрос о сборке={:?}",
            answer(context)
        );
    }
    assert_eq!(answer("Нет сведений о сборке"), None);
    assert_eq!(answer("Сборщик Cargo"), Some("Cargo"));
}

