// Урок 08.1. Повторение случайной последовательности из одного начального числа.
// Связь с принятой терминологией: Начальное число для воспроизводимой псевдослучайной последовательности.
// Зачем здесь эта тема: Случайное разбиение или обучение нельзя сравнить повторно без
//   воспроизводимого источника случайности.
// Почему код устроен так: Одинаковый seed должен давать одинаковую последовательность, а другой
//   seed — другую.
// Представь: Два запуска с одним seed выбирают строки в одном порядке; без этого трудно понять
//   причину разницы результатов.
//
// Что изучаем: Случайный seed.
// Зачем это нужно: Начальное состояние генератора делает псевдослучайную последовательность
// воспроизводимой.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.

fn main() {
    let seed: u64 = 42_u64;
    let mut state: u64 = seed;
    for _ in 0..3 {
        state = state.wrapping_mul(6364136223846793005).wrapping_add(1);
    }
}
