// Урок 26.3. Layer normalization.
//
// Что изучаем: Layer normalization.
// Зачем это нужно: Нормализуем координаты одного токена по его среднему и дисперсии, затем добавляем малое
// epsilon для устойчивости.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `token` для следующего шага примера.
    let token = [1.0, 3.0];
    // Нормируем или усредняем величину делением и сохраняем её в `mean`.
    let mean = (token[0] + token[1]) / 2.0;
    // Сохраняем рассчитанное значение `variance` для следующих операций.
    let variance =
        // Составляем результат из вычисленных значений в указанном порядке.
        ((token[0] - mean) * (token[0] - mean) + (token[1] - mean) * (token[1] - mean)) / 2.0;
    // Комбинируем исходные величины и сохраняем результат в `squared_scale`.
    let squared_scale = variance + 0.00001;
    // Создаём изменяемое значение `scale` для следующих операций.
    let mut scale = squared_scale;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for _ in 0..80 {
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        scale = (scale + squared_scale / scale) / 2.0;
    }
    // Создаём набор значений `normalized` для следующего шага примера.
    let normalized = [(token[0] - mean) / scale, (token[1] - mean) / scale];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("нормализованный токен = {normalized:?}");
}
