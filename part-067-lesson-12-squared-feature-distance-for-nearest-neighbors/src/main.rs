// Урок 12.1. Квадрат расстояния по признакам для поиска ближайших соседей.
//
// Что изучаем: Расстояния для ближайших соседей.
// Зачем это нужно: Сравниваем объекты по сумме квадратов разностей признаков; корень не нужен, если
// требуется только порядок соседей.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `query` для следующего шага примера.
    let query: [f64; 2] = [1.0, 2.0];
    // Создаём набор значений `candidates` для следующего шага примера.
    let candidates: [[f64; 2]; 2] = [[2.0, 2.0], [4.0, 6.0]];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for candidate in candidates {
        // Для поиска ближайшего кандидата нужен квадрат расстояния из урока 01.4.
        let squared_distance: f64 =
            part_004_lesson_01_euclidean_distance_between_two_points::squared_euclidean_distance_between_two_points(
                &query, &candidate,
            )
            // Используем результат, ожидая успешного выполнения шага.
            .expect("запрос и кандидат имеют одинаковое число координат");
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("кандидат {candidate:?}: квадрат расстояния={squared_distance}");
    }

    // Построение графика вынесено из основного кода урока.
    visualize_squared_feature_distance_for_nearest_neighbors();
}

// Строим график по результатам урока.
fn visualize_squared_feature_distance_for_nearest_neighbors() {
    // Значения из этого урока на графике.
    let distances_points: Vec<(f64, f64)> = (-50..=50)
        // Преобразуем каждый элемент в новое значение.
        .map(|plot_step_index| {
            // Сохраняем результат этого шага в `horizontal_value`.
            let horizontal_value: f64 = plot_step_index as f64 / 10.0;
            // Добавляем пару значений для сравнения или построения графика.
            (
                horizontal_value,
                (horizontal_value * horizontal_value + 1.0).sqrt(),
            )
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Расстояние до запроса",
        // Указываем подпись горизонтальной оси.
        "первая координата",
        // Указываем подпись вертикальной оси.
        "евклидово расстояние",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "запрос [0,0]",
            // Передаём рассчитанные координаты точек.
            points: &distances_points,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
