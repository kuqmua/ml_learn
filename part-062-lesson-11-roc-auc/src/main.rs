// Урок 11.5. Площадь под ROC-кривой.
//
// Что изучаем: Площадь под ROC-кривой.
// Зачем это нужно: ROC-AUC можно понимать как долю пар, где положительный объект получает оценку выше
// отрицательного.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `positive_scores` для следующего шага примера.
    let positive_scores = [0.9, 0.7];
    // Создаём набор значений `negative_scores` для следующего шага примера.
    let negative_scores = [0.6, 0.2];
    // Инициализируем изменяемый накопитель `ordered_pairs` начальным состоянием.
    let mut ordered_pairs = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for positive in positive_scores {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for negative in negative_scores {
            // Проверяем условие и выбираем соответствующую ветку алгоритма.
            if positive > negative {
                // Прибавляем очередной вклад к ранее накопленному результату.
                ordered_pairs += 1.0;
            }
        }
    }
    // Считаем количество элементов и сохраняем его в `pair_count`.
    let pair_count = (positive_scores.len() * negative_scores.len()) as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("ROC-AUC = {}", ordered_pairs / pair_count);
}
