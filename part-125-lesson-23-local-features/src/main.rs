// Урок 23.5. Локальные признаки.
//
// Что изучаем: Локальные признаки.
// Зачем это нужно: Один и тот же фильтр применяется в разных областях изображения и ищет одинаковый шаблон
// независимо от позиции.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `image` для следующего шага примера.
    let image = [1.0, 3.0, 2.0, 5.0];
    // Создаём набор значений `kernel` для следующего шага примера.
    let kernel = [-1.0, 1.0];
    // Формула ниже использует ровно два коэффициента ядра и два соседних пикселя.
    assert_eq!(
        kernel.len(),
        2,
        "этот пример рассчитан на ядро из двух значений"
    );
    // Ядро должно помещаться в изображение, иначе окно считать нельзя.
    assert!(
        !kernel.is_empty() && image.len() >= kernel.len(),
        "ядро должно быть непустым и не длиннее изображения"
    );
    // Повторяем следующий блок для каждого положения окна.
    for start in 0..=image.len() - kernel.len() {
        // Умножаем значения и сохраняем результат в `response`.
        let response = image[start] * kernel[0] + image[start + 1] * kernel[1];
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("позиция={start}, отклик на границу={response}");
    }
    // Значения из этого урока на графике.
    let chart_points_0: Vec<(f64, f64)> = (0..=image.len() - kernel.len())
        .map(|i| (i as f64, image[i] * kernel[0] + image[i + 1] * kernel[1]))
        .collect();
    let chart = lesson_visualization::line_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Отклик ядра на локальные границы",
        "позиция",
        "отклик",
        &[lesson_visualization::Series {
            name: "свёртка",
            points: &chart_points_0,
        }],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
