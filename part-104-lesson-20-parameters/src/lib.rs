//! Вычисления и примеры урока part-104-lesson-20-parameters.

// Урок 20.2. Параметры сети.
//
// Что изучаем: Параметры сети.
// Зачем это нужно: Веса масштабируют входы, смещение сдвигает результат; обучение меняет именно эти числа.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Сохраняем рассчитанное значение `input` для следующих операций.
    let input = 2.0;
    // Инициализируем изменяемый накопитель `weight` начальным состоянием.
    let mut weight = 0.5;
    // Инициализируем изменяемый накопитель `bias` начальным состоянием.
    let mut bias = 0.1;
    // Умножаем значения и сохраняем результат в `before`.
    let before = weight * input + bias;
    // Прибавляем очередной вклад к ранее накопленному результату.
    weight += 0.2;
    // Вычитаем очередной вклад из текущего значения параметра.
    bias -= 0.1;
    // Умножаем значения и сохраняем результат в `after`.
    let after = weight * input + bias;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("до={before}, после обновления={after}");
}
