// Урок 44.4. Измерение времени инференса при росте числа строк.
// Почему этот урок сейчас: Модель может быть точной, но слишком медленной при большом пакете.
// Почему пример устроен так: Замеряем один пакет из 1000 строк; график зависимости от размера здесь схематический, не серия измерений.
//
// Что изучаем: Производительность инференса.
// Зачем это нужно: Стоимость обработки растёт с числом строк; измеряем время пакетного прохода отдельно от
// загрузки входа.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Создаём набор значений `features` для следующего шага примера.
    let features: Vec<f64> = vec![1.0; 1000];
    lesson_trace::trace_step!(features);
    // Сохраняем рассчитанное значение `start` для следующих операций.
    let start: std::time::Instant = std::time::Instant::now();
    lesson_trace::trace_step!(start);
    // Сохраняем рассчитанное значение `predictions` для следующих операций.
    let predictions: Vec<f64> = features
        // Перебираем элементы по ссылке, не копируя исходную коллекцию.
        .iter()
        // Преобразуем каждый элемент последовательности.
        .map(|&feature| 2.0 * feature + 1.0)
        // Собираем элементы итератора в итоговую коллекцию.
        .collect();
    lesson_trace::trace_step!(predictions);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        "объектов={}, время={:?}",
        // Передаём очередное значение в составе результата или вызова.
        predictions.len(),
        // Замер завершается после обработки всей партии объектов.
        start.elapsed()
    );

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_measure_inference_time_as_batch_size_grows();
}

// Строим график по результатам урока.
fn visualize_measure_inference_time_as_batch_size_grows() {
    // График величин и зависимостей, изученных в этом уроке.
    let performance_points: Vec<(f64, f64)> = (0..=100)
        // Преобразуем каждый элемент в новое значение.
        .map(|plot_step_index| {
            // Сохраняем результат этого шага в `sample_count`.
            let sample_count: f64 = (plot_step_index * 10) as f64;
            // Добавляем пару значений для сравнения или построения графика.
            (sample_count, 2.0 * sample_count)
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart: std::path::PathBuf = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Стоимость пакетного инференса",
        // Указываем подпись горизонтальной оси.
        "число строк",
        // Указываем подпись вертикальной оси.
        "условное число операций",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "линейный проход",
            // Передаём рассчитанные координаты точек.
            points: &performance_points,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
