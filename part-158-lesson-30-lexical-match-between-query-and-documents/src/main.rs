// Урок 30.1. Совпадение слов запроса и документов при лексическом поиске.
// Зачем здесь эта тема: Перед сложным поиском полезно увидеть, что даёт точное совпадение слов
//   запроса и документа.
// Почему код устроен так: Считаем общие слова на малых текстах и видим ограничение буквального
//   поиска.
// Представь: Запрос «рыжий кот» найдёт документ с теми же словами, но может пропустить текст с
//   синонимом.
//
// Что изучаем: Лексический поиск.
// Зачем это нужно: Совпадение слов запроса с документом даёт простой поиск без обученной модели.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Создаём набор значений `documents` для следующего шага примера.
    let documents: [(&str, &str); 2] = [("rust cargo", "guide"), ("машинное обучение", "ml")];
    lesson_trace::trace_step!(documents);
    // Сохраняем рассчитанное значение `query` для следующих операций.
    let query: &str = "cargo";
    lesson_trace::trace_step!(query);
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for (text, document_identifier) in documents {
        lesson_trace::trace_step!(text);
        lesson_trace::trace_step!(document_identifier);
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if text.split_whitespace().any(|word| word == query) {
            // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
            println!("найден документ {document_identifier}");
        }
    }

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_lexical_match_between_query_and_documents(documents, query);
}

// Строим график по результатам урока.
fn visualize_lexical_match_between_query_and_documents(documents: [(&str, &str); 2], query: &str) {
    // Сравниваем величины, вычисленные в примере.
    let chart: std::path::PathBuf = lesson_visualization::bar_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок диаграммы.
        "Лексический поиск",
        // Указываем подпись вертикальной оси.
        "документов",
        // Передаём ряды или значения для отрисовки графика.
        &[
            (
                // Передаём подпись или текстовое значение для следующего шага.
                "найдены",
                // Используем подготовленное значение в следующем шаге примера.
                documents
                    // Просматриваем элементы коллекции по ссылке.
                    .iter()
                    // Оставляем элементы, отвечающие условию.
                    .filter(|(text, _)| text.contains(query))
                    // Подсчитываем число подходящих элементов.
                    .count() as f64,
            ),
            (
                // Передаём подпись или текстовое значение для следующего шага.
                "не найдены",
                // Используем подготовленное значение в следующем шаге примера.
                documents
                    // Просматриваем элементы коллекции по ссылке.
                    .iter()
                    // Оставляем элементы, отвечающие условию.
                    .filter(|(text, _)| !text.contains(query))
                    // Подсчитываем число подходящих элементов.
                    .count() as f64,
            ),
        ],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
