// Урок 053. Сравнивать кандидатов по ошибке с добавленным штрафом за большой вес.
// На двух вариантах видим, как сила штрафа меняет выбор, даже если точность одного варианта выше.

fn main() {
    let candidates = [(1.0_f64, 1.5_f64), (3.0, 1.0)];
    for strength in [0.0, 0.2] {
        let totals = candidates.map(|(weight, error)| error + strength * weight * weight);
        let best = if totals[0] < totals[1] { 0 } else { 1 };
        println!(
            "Сила штрафа={strength}: суммарные ошибки={totals:?}, выбран вес={}",
            candidates[best].0
        );
        assert_eq!(best, if strength == 0.0 { 1 } else { 0 });
    }
    println!("Без штрафа выигрывает точность; со штрафом большой вес может стать менее выгодным.");
}

