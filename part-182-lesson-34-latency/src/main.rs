// Урок 34.3. Задержка ответа.
//
// Что изучаем: Задержка ответа.
// Зачем это нужно: Замеряем время обработки запроса, поскольку правильный, но слишком медленный прогноз
// может быть непригоден.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `start` для следующих операций.
    let start = std::time::Instant::now();
    // Сохраняем рассчитанное значение `feature` для следующих операций.
    let feature = 3.0;
    // Умножаем значения и сохраняем результат в `prediction`.
    let prediction = 2.0 * feature + 1.0;
    // Сохраняем рассчитанное значение `latency` для следующих операций.
    let latency = start.elapsed();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("прогноз={prediction}, задержка={latency:?}");
}
