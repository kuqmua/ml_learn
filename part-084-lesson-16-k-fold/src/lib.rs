//! Вычисления и примеры урока part-084-lesson-16-k-fold.

// Урок 16.1. K-fold кросс-валидация.
//
// Что изучаем: K-fold кросс-валидация.
// Зачем это нужно: Каждый блок данных один раз становится проверочным, пока остальные используются для
// обучения.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Создаём набор значений `rows` для следующего шага примера.
    let rows = [0, 1, 2, 3, 4, 5];
    // Сохраняем рассчитанное значение `folds` для следующих операций.
    let folds = 3;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for fold in 0..folds {
        // Сохраняем рассчитанное значение `validation` для следующих операций.
        let validation: Vec<_> = rows
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Копируем значения из ссылок, чтобы получить самостоятельные элементы.
            .copied()
            // Оставляем только элементы, прошедшие указанную проверку.
            .filter(|&row| row % folds == fold)
            // Собираем элементы итератора в итоговую коллекцию.
            .collect();
        // Сохраняем рассчитанное значение `train` для следующих операций.
        let train: Vec<_> = rows
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Копируем значения из ссылок, чтобы получить самостоятельные элементы.
            .copied()
            // Оставляем только элементы, прошедшие указанную проверку.
            .filter(|&row| row % folds != fold)
            // Собираем элементы итератора в итоговую коллекцию.
            .collect();
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("fold={fold}: train={train:?}, validation={validation:?}");
    }
}
