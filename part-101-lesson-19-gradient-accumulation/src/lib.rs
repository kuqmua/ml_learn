//! Вычисления и примеры урока part-101-lesson-19-gradient-accumulation.

// Урок 19.3. Накопление градиентов.
//
// Что изучаем: Накопление градиентов.
// Зачем это нужно: Если один узел участвует в нескольких путях, градиенты этих путей складываются.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Сохраняем рассчитанное значение `x` для следующих операций.
    let x = 3.0;
    // f(x)=x*x: вход x участвует как левый и правый множитель.
    let left_path_gradient = x;
    // Сохраняем рассчитанное значение `right_path_gradient` для следующих операций.
    let right_path_gradient = x;
    // Комбинируем исходные величины и сохраняем результат в `total_gradient`.
    let total_gradient = left_path_gradient + right_path_gradient;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        "градиент слева={left_path_gradient}, справа={right_path_gradient}, всего={total_gradient}"
    );
}
