//! Вычисления и примеры урока part-181-lesson-34-postrelease-quality.

// Урок 34.2. Качество после релиза.
//
// Что изучаем: Качество после релиза.
// Зачем это нужно: Когда появляются истинные метки, пересчитываем метрику на новых данных отдельно от
// учебной оценки.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Создаём набор значений `truth` для следующего шага примера.
    let truth = [true, false, true];
    // Создаём набор значений `predicted` для следующего шага примера.
    let predicted = [true, true, true];
    assert_eq!(
        truth.len(),
        predicted.len(),
        "число прогнозов должно совпадать с числом ответов"
    );
    assert!(
        !truth.is_empty(),
        "для accuracy нужна хотя бы одна пара значений"
    );
    // Считаем количество элементов и сохраняем его в `correct`.
    let correct = (0..truth.len())
        // Оставляем только элементы, прошедшие указанную проверку.
        .filter(|&index| truth[index] == predicted[index])
        // Подсчитываем число элементов после отбора.
        .count();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        "accuracy новых данных={:.2}",
        // Делим значения, получая нормированную величину или среднее.
        correct as f64 / truth.len() as f64
    );
}
