//! Вычисления и примеры урока part-034-lesson-06-bootstrap.

// Урок 06.6. Bootstrap.
//
// Что изучаем: Bootstrap.
// Зачем это нужно: Повторная выборка с возвращением показывает, как меняется оценка при перестановке
// наблюдений.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Создаём набор значений `values` для следующего шага примера.
    let values = [2.0, 4.0, 6.0];
    // Создаём набор значений `resamples` для следующего шага примера.
    let resamples = [[0, 1, 2], [0, 0, 2], [1, 2, 2], [0, 1, 1]];
    assert!(!values.is_empty(), "исходная выборка не должна быть пустой");
    // Повторяем следующий блок для каждой повторной выборки.
    for indices in resamples {
        assert!(
            !indices.is_empty(),
            "повторная выборка не должна быть пустой"
        );
        assert!(
            indices.iter().all(|&index| index < values.len()),
            "индекс выходит за границы исходной выборки"
        );
        // Инициализируем изменяемый накопитель `sum` начальным состоянием.
        let mut sum = 0.0;
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for index in indices {
            // Прибавляем очередной вклад к ранее накопленному результату.
            sum += values[index];
        }
        // Считаем количество элементов и сохраняем его в `mean`.
        let mean = sum / indices.len() as f64;
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("индексы {indices:?} -> среднее {mean:.2}");
    }
}
