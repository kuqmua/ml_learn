// Урок 32.4. Обратная совместимость формата.
//
// Что изучаем: Обратная совместимость формата.
// Зачем это нужно: Загрузчик может отдельно обрабатывать прежнюю и новую версию, явно отвергая незнакомые
// данные.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `serialized` для следующих операций.
    let serialized = "model_v1\n2.0\n1.0\n";
    // Сохраняем рассчитанное значение `version` для следующих операций.
    let version = serialized.lines().next().unwrap();
    // Сохраняем рассчитанное значение `explanation` для следующих операций.
    let explanation = match version {
        // Для этого варианта применяем соответствующее правило вычисления.
        "model_v1" => "старый формат: вес и смещение",
        // Для этого варианта применяем соответствующее правило вычисления.
        "model_v2" => "новый формат: параметры и метаданные",
        // Для этого варианта применяем соответствующее правило вычисления.
        _ => "формат не поддерживается",
    };
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("{explanation}");
}
