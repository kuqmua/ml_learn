// Сводная практика 13. Наивный Байес.
//
// Что повторяем вместе: условная независимость, априорные вероятности, сглаживание Лапласа.
// Зачем это нужно: Наивный Байес сравнивает вероятности слов в классах; логарифмы превращают результат умножения
//   малых чисел в сумму.
// Что показывает программа: Составляем маленький размеченный корпус положительных и отрицательных текстов.
//   Считаем логарифмические оценки классов для известных слов. Отдельно проверяем, что неизвестное слово не
//   ломает классификатор.
// Что проверить при изменении примера: Проверь неизвестные слова и класс с редкими токенами; считай
//   вероятности в log-пространстве.
// Дополнительная практика: Обучи мультиномиальный классификатор коротких текстов по счётчикам слов.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Шаг: Составляем маленький размеченный корпус положительных и отрицательных текстов.
    let training_examples = [
        // Составляем результат из вычисленных значений в указанном порядке.
        ("хороший фильм", true),
        // Составляем результат из вычисленных значений в указанном порядке.
        ("отличный фильм", true),
        // Составляем результат из вычисленных значений в указанном порядке.
        ("плохой фильм", false),
        // Составляем результат из вычисленных значений в указанном порядке.
        ("ужасный фильм", false),
    ];

    // Учебные реализации математических операций для этого урока.

    /// ln(x) через ряд 2 * (t + t³/3 + t⁵/5 + ...), t=(x-1)/(x+1).
    fn approximate_natural_logarithm_with_series(value: f64) -> f64 {
        // Проверяем обязательное условие до дальнейшего вычисления.
        assert!(
            // Передаём очередное значение в составе результата или вызова.
            value > 0.0,
            // Подставляем результаты в этот шаблон вывода или текстового значения.
            "логарифм определён только для положительных чисел"
        );
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if value == f64::INFINITY {
            // Завершаем текущий расчёт и возвращаем найденное значение.
            return f64::INFINITY;
        }
        // Создаём изменяемое значение `scaled` для следующих операций.
        let mut scaled = value;
        // Инициализируем изменяемый накопитель `power_of_two` начальным состоянием.
        let mut power_of_two = 0i32;
        // Повторяем вычисление, пока выполняется указанное условие.
        while scaled >= 2.0 {
            // Масштабируем текущую величину делением.
            scaled /= 2.0;
            // Прибавляем очередной вклад к ранее накопленному результату.
            power_of_two += 1;
        }
        // Повторяем вычисление, пока выполняется указанное условие.
        while scaled < 1.0 {
            // Умножаем накопленное значение на очередной множитель.
            scaled *= 2.0;
            // Вычитаем очередной вклад из текущего значения параметра.
            power_of_two -= 1;
        }
        // Объявляем повторно используемое вычисление `sum_logarithm_series_terms`; параметры ниже задают его входы.
        fn sum_logarithm_series_terms(value: f64) -> f64 {
            // Нормируем или усредняем величину делением и сохраняем её в `ratio`.
            let ratio = (value - 1.0) / (value + 1.0);
            // Умножаем значения и сохраняем результат в `ratio_squared`.
            let ratio_squared = ratio * ratio;
            // Создаём изменяемое значение `term` для следующих операций.
            let mut term = ratio;
            // Инициализируем изменяемый накопитель `result` начальным состоянием.
            let mut result = 0.0;
            // Повторяем следующий блок для каждого элемента указанной последовательности.
            for term_index in 0..40 {
                // Прибавляем очередной вклад к ранее накопленному результату.
                result += term / (2 * term_index + 1) as f64;
                // Умножаем накопленное значение на очередной множитель.
                term *= ratio_squared;
            }
            // Умножаем величины согласно используемой формуле.
            2.0 * result
        }
        // Сохраняем рассчитанное значение `logarithm_of_two` для следующих операций.
        let logarithm_of_two = sum_logarithm_series_terms(2.0);
        // Умножаем величины согласно используемой формуле.
        sum_logarithm_series_terms(scaled) + power_of_two as f64 * logarithm_of_two
    }

    // Суммируем логарифмы априорной вероятности и вероятностей токенов.
    fn classify_text_with_multinomial_naive_bayes(
        // Получаем размеченные обучающие примеры по ссылке без копирования.
        training_examples: &[(&str, bool)],
        // `text` задаёт соответствующее входное значение или поле структуры.
        text: &str,
    ) -> (bool, [f64; 2]) {
        // Словарь задаёт все слова, встреченные во время обучения.
        let vocabulary: std::collections::HashSet<_> = training_examples
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Разделяем текст по пробельным символам на отдельные слова.
            .flat_map(|(document_text, _)| document_text.split_whitespace())
            // Собираем элементы итератора в итоговую коллекцию.
            .collect();
        // Создаём набор значений `scores` для следующего шага примера.
        let mut scores = [0.; 2];
        // Для каждого класса собираем частоты слов отдельно.
        for (class, score) in scores.iter_mut().enumerate() {
            // Сохраняем рассчитанное значение `class_documents` для следующих операций.
            let class_documents: Vec<_> = training_examples
                // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                .iter()
                // Оставляем только элементы, прошедшие указанную проверку.
                .filter(|(_, label)| *label == (class == 1))
                // Собираем элементы итератора в итоговую коллекцию.
                .collect();
            // Инициализируем изменяемый накопитель `token_counts` начальным состоянием.
            let mut token_counts = std::collections::HashMap::new();
            // Инициализируем изменяемый накопитель `total_tokens` начальным состоянием.
            let mut total_tokens = 0;
            // Повторяем следующий блок для каждого элемента указанной последовательности.
            for (document_text, _) in &class_documents {
                // Повторяем следующий блок для каждого элемента указанной последовательности.
                for token in document_text.split_whitespace() {
                    // Прибавляем очередной вклад к ранее накопленному результату.
                    *token_counts.entry(token).or_insert(0usize) += 1;
                    // Прибавляем очередной вклад к ранее накопленному результату.
                    total_tokens += 1;
                }
            }
            // Начинаем с априорной вероятности класса и добавляем логарифмы вероятностей слов.
            *score = approximate_natural_logarithm_with_series(
                // Составляем результат из вычисленных значений в указанном порядке.
                (class_documents.len() as f64 + 1.) / (training_examples.len() as f64 + 2.),
            );
            // Повторяем следующий блок для каждого элемента указанной последовательности.
            for token in text.split_whitespace() {
                // Проверяем условие и выбираем соответствующую ветку алгоритма.
                if vocabulary.contains(token) {
                    // Прибавляем очередной вклад к ранее накопленному результату.
                    *score += approximate_natural_logarithm_with_series(
                        // Составляем результат из вычисленных значений в указанном порядке.
                        (*token_counts.get(token).unwrap_or(&0) as f64 + 1.)
                            // Делим значения, получая нормированную величину или среднее.
                            / (total_tokens + vocabulary.len()) as f64,
                    );
                }
            }
        }
        // Составляем результат из вычисленных значений в указанном порядке.
        (scores[1] > scores[0], scores)
    }

    // Шаг: Считаем логарифмические оценки классов для известных слов.
    println!(
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "{:?}",
        // Вызываем нужное вычисление с подготовленными аргументами.
        classify_text_with_multinomial_naive_bayes(&training_examples, "хороший отличный")
    );
    // Шаг: Отдельно проверяем, что неизвестное слово не ломает классификатор.
    println!(
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "unknown: {:?}",
        // Вызываем нужное вычисление с подготовленными аргументами.
        classify_text_with_multinomial_naive_bayes(&training_examples, "неизвестное")
    );
}
