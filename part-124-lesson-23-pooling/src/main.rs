// Урок 23.4. Max pooling.
//
// Что изучаем: Max pooling.
// Зачем это нужно: Pooling оставляет наиболее сильный отклик в локальном окне и уменьшает пространственный
// размер.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `feature_map` для следующего шага примера.
    let feature_map = [[1.0, 4.0], [3.0, 2.0]];
    // Создаём изменяемое значение `maximum` для следующих операций.
    // Для выбора максимума карта должна содержать хотя бы одно значение.
    assert!(
        !feature_map.is_empty() && !feature_map[0].is_empty(),
        "карта признаков не должна быть пустой"
    );
    let mut maximum = feature_map[0][0];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for row in feature_map {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for value in row {
            // Проверяем условие и выбираем соответствующую ветку алгоритма.
            if value > maximum {
                // Присваиваем вычисленное значение соответствующей переменной или полю.
                maximum = value;
            }
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("max pooling = {maximum}");
    // Сравниваем величины, вычисленные в примере.
    let chart = lesson_visualization::bars(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Max pooling",
        "значение",
        &[
            ("1", feature_map[0][0]),
            ("2", feature_map[0][1]),
            ("3", feature_map[1][0]),
            ("4", feature_map[1][1]),
            ("максимум", maximum),
        ],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
