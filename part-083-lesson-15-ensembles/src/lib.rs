//! Вычисления и примеры урока part-083-lesson-15-ensembles.

// Сводная практика 15. Ансамбли.
//
// Что повторяем вместе: bagging, bootstrap, majority vote, bias/variance.
// Зачем это нужно: Ансамбль объединяет несколько простых моделей, обученных на разных выборках, чтобы
//   снизить зависимость от одной модели.
// Что показывает программа: Берём обучающие точки для нескольких базовых моделей. Каждый stump обучаем на
//   своей bootstrap-выборке. Объединяем прогнозы моделей голосованием большинства.
// Что проверить при изменении примера: Сравни одно дерево с ансамблем на одинаковом split; фиксируй seed
//   каждого дерева.
// Дополнительная практика: Собери несколько деревьев на bootstrap-выборках и усредни прогнозы.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Шаг: Берём обучающие точки для нескольких базовых моделей.
    let data = [
        // Учебный объект: признак 0., метка класса false.
        (0., false),
        // Учебный объект: признак 1., метка класса false.
        (1., false),
        // Учебный объект: признак 2., метка класса true.
        (2., true),
        // Учебный объект: признак 3., метка класса true.
        (3., true),
        // Учебный объект: признак 4., метка класса false.
        (4., false),
        // Учебный объект: признак 5., метка класса true.
        (5., true),
    ];

    // Шаг: Каждый stump обучаем на своей bootstrap-выборке.
    let models: Vec<_> = (1..=9)
        // Преобразуем каждый элемент последовательности.
        .map(|seed| {
            // Составляем результат из вычисленных значений в указанном порядке.
            (|| -> (f64, bool) {
                /* Перебираем пороги и направления, выбирая пень с минимальным числом ошибок. */
                let data: &[(f64, bool)] = &(|| -> Vec<(f64, bool)> {
                    /* Создаём выборку той же длины с возвращением и фиксированным seed. */
                    let data: &[(f64, bool)] = &data;
                    // Сохраняем рассчитанное значение `seed` для следующих операций.
                    let seed: u64 = seed;
                    // Создаём изменяемое значение `generator_state` для следующих операций.
                    let mut generator_state = seed;
                    // Составляем результат из вычисленных значений в указанном порядке.
                    (0..data.len())
                        // Преобразуем каждый элемент последовательности.
                        .map(|_| {
                            // Обновляем `generator_state` результатом текущего шага.
                            generator_state = generator_state
                                // Используем арифметику с переполнением для воспроизводимого генератора.
                                .wrapping_mul(6364136223846793005)
                                // Используем арифметику с переполнением для воспроизводимого генератора.
                                .wrapping_add(1);
                            // Передаём ранее рассчитанное значение в текущую операцию.
                            data[(generator_state as usize) % data.len()]
                        })
                        // Собираем элементы итератора в итоговую коллекцию.
                        .collect()
                })();
                // Создаём изменяемое значение `best` для следующих операций.
                let mut best = (f64::INFINITY, 0., false);
                // Повторяем следующий блок для каждого элемента указанной последовательности.
                for &(candidate_threshold, _) in data {
                    // Повторяем следующий блок для каждого элемента указанной последовательности.
                    for reverse in [false, true] {
                        // Сохраняем рассчитанное значение `errors` для следующих операций.
                        let errors = data
                            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                            .iter()
                            // Оставляем только элементы, прошедшие указанную проверку.
                            .filter(|&&(feature_value, label)| {
                                // Составляем результат из вычисленных значений в указанном порядке.
                                ((feature_value >= candidate_threshold) ^ reverse) != label
                            })
                            // Подсчитываем число элементов после отбора.
                            .count() as f64;
                        // Проверяем условие и выбираем соответствующую ветку алгоритма.
                        if errors < best.0 {
                            // Обновляем `best` результатом текущего шага.
                            best = (errors, candidate_threshold, reverse);
                        }
                    }
                }
                // Составляем результат из вычисленных значений в указанном порядке.
                (best.1, best.2)
            })()
        })
        // Собираем элементы итератора в итоговую коллекцию.
        .collect();

    // Шаг: Объединяем прогнозы моделей голосованием большинства.
    assert!(
        !models.is_empty(),
        "для сравнения нужна хотя бы одна модель"
    );
    for feature_value in [0.5, 2.5, 4.5] {
        // Показываем ответ одного и того же базового дерева рядом с ответом ансамбля.
        let first_model = (feature_value >= models[0].0) ^ models[0].1;
        // Сохраняем рассчитанное значение `votes` для следующих операций.
        let votes = models
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Оставляем только элементы, прошедшие указанную проверку.
            .filter(|&&model| {
                // Составляем результат из вычисленных значений в указанном порядке.
                (|| -> bool {
                    /* Сравниваем признак с порогом и учитываем направление пня. */
                    let model: (f64, bool) = model;
                    // Сохраняем рассчитанное значение `feature_value` для следующих операций.
                    let feature_value: f64 = feature_value;
                    // Составляем результат из вычисленных значений в указанном порядке.
                    (feature_value >= model.0) ^ model.1
                })()
            })
            // Подсчитываем число элементов после отбора.
            .count();
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!(
            // Задаём шаблон строки: плейсхолдеры ниже заменятся рассчитанными значениями.
            "x={feature_value}: первое дерево={first_model}, {votes}/{} positive -> ансамбль={}",
            // Передаём очередное значение в составе результата или вызова.
            models.len(),
            // Умножаем величины согласно используемой формуле.
            votes * 2 > models.len()
        );
    }
}
