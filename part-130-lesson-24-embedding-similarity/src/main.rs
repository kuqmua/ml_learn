// Урок 24.4. Сходство эмбеддингов.
//
// Что изучаем: Сходство эмбеддингов.
// Зачем это нужно: Результат умножения пар координат и сложения двух нормированных представлений измеряет близость их
// направлений.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `first` для следующего шага примера.
    let first = [0.8, 0.2];
    // Создаём набор значений `second` для следующего шага примера.
    let second = [0.7, 0.3];
    // Умножаем значения и сохраняем результат в `sum_after_multiplying_coordinates`.
    let sum_after_multiplying_coordinates = first[0] * second[0] + first[1] * second[1];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        "сумма после попарного умножения координат представлений = {sum_after_multiplying_coordinates}"
    );
}
