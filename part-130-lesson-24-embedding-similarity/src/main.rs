// Урок 24.4. Сходство эмбеддингов.
//
// Что изучаем: Сходство эмбеддингов.
// Зачем это нужно: Результат умножения пар координат и сложения двух представлений измеряет близость их
// направлений.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `first` для следующего шага примера.
    let first = [0.8, 0.2];
    // Создаём набор значений `second` для следующего шага примера.
    let second = [0.7, 0.3];
    // Умножаем значения и сохраняем результат в `sum_after_multiplying_coordinates`.
    let sum_after_multiplying_coordinates =
        lesson_001::multiply_matching_coordinates_then_add(&first, &second)
            .expect("представления имеют одинаковую размерность");
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        "сумма после попарного умножения координат представлений = {sum_after_multiplying_coordinates}"
    );
    // Значения из этого урока на графике.
    let chart_points_0: Vec<(f64, f64)> = vec![(first[0], first[1])];
    let chart_points_1: Vec<(f64, f64)> = vec![(second[0], second[1])];
    let chart = lesson_visualization::scatter_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Похожие эмбеддинги",
        "первая координата",
        "вторая координата",
        &[
            lesson_visualization::Series {
                name: "первый",
                points: &chart_points_0,
            },
            lesson_visualization::Series {
                name: "второй",
                points: &chart_points_1,
            },
        ],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
