// Урок 169. Смешивать векторы значений по заданным весам.
// Получаем общий контекст, в который каждая позиция вносит свою долю.

fn main() {
    let values: [[f64; 2]; 2] = [[1.0, 0.0], [0.0, 2.0]];
    let weights: [f64; 2] = [0.25, 0.75];
    let output: [f64; 2] = [
        weights[0] * values[0][0] + weights[1] * values[1][0],
        weights[0] * values[0][1] + weights[1] * values[1][1],
    ];

    // Выполняем вычисления из примера.
    let _ = output;

    println!("Значения={values:?}; доли={weights:?}; смесь={output:?}");
    assert_eq!(output, [0.25, 1.5]);
    let only_first = [1.0 * values[0][0], 1.0 * values[0][1]];
    println!("Если дать первому весь вес: {only_first:?}");
    assert_ne!(output, only_first);
}

