// Урок 31.1. Преобразование координат позиции в вектор запроса для поиска подходящего контекста.
// Связь с принятой терминологией: Вектор запроса Q для позиции механизма внимания.
// Зачем здесь эта тема: Поиск по словам не учитывает контекст; внимание позволяет каждой позиции
//   запросить сведения у других.
// Почему код устроен так: Строим вектор Q из состояния одной позиции и отделяем его от того, что
//   хранится в других позициях.
// Представь: Позиция со словом «он» может запросить сведения о более раннем слове «кот».
//
// Что изучаем: Вектор запроса Q.
// Зачем это нужно: Query задаёт, какую информацию текущая позиция ищет в других позициях
// последовательности.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Создаём набор значений `text_unit` для следующего шага примера.
    // Единицу текста, которую модель обрабатывает как одно целое, называют token.
    let text_unit: [f64; 2] = [1.0, 2.0];
    lesson_trace::trace_step!(text_unit);
    // Создаём набор значений `query_weights` для следующего шага примера.
    let query_weights: [[f64; 2]; 2] = [[1.0, 0.0], [0.0, 0.5]];
    lesson_trace::trace_step!(query_weights);
    // Создаём набор значений `query` для следующего шага примера.
    let query: [f64; 2] = [
        // Умножаем величины согласно используемой формуле.
        query_weights[0][0] * text_unit[0] + query_weights[0][1] * text_unit[1],
        // Умножаем величины согласно используемой формуле.
        query_weights[1][0] * text_unit[0] + query_weights[1][1] * text_unit[1],
    ];
    lesson_trace::trace_step!(query);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("Q = {query:?}");

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    plot_coordinates_after_multiplying_by_query_weights(query);
}

// Строим график по результатам урока.
fn plot_coordinates_after_multiplying_by_query_weights(query: [f64; 2]) {
    // Сравнение величин из этого урока.
    let chart: std::path::PathBuf = lesson_visualization::bar_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок диаграммы.
        "Проекция в Q",
        // Указываем подпись вертикальной оси.
        "компонента",
        // Передаём ряды или значения для отрисовки графика.
        &[("Q₀", query[0]), ("Q₁", query[1])],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
