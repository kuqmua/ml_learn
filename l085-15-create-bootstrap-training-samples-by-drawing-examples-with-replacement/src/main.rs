// Урок 085. Составлять обучающую выборку по индексам, которые могут повторяться.
// Заданный список индексов показывает выбор с возвращением: один объект можно взять дважды, другой
// пропустить.

fn main() {
    let data = ["A", "B", "C", "D"];
    let indices = [0, 2, 2, 3];
    let sample = indices.map(|i| data[i]);
    println!("Исходная выборка={data:?}; индексы={indices:?}; повторная={sample:?}");
    assert_eq!(sample.iter().filter(|&&v| v == "C").count(), 2);
    assert!(!sample.contains(&"B"));
    println!("Выбор с возвращением сохраняет размер выборки, но допускает повторы и пропуски.");
}

