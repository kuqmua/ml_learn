//! Вычисления и примеры урока part-019-lesson-04-learning-rate.

// Урок 04.1. Скорость обучения.
//
// Что изучаем: Скорость обучения.
// Зачем это нужно: Один и тот же градиент даёт разные шаги при разных learning rate. Слишком большой шаг
// может перескочить минимум.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Инициализируем значение `parameter` начальным состоянием.
    let parameter = 0.0;
    // Умножаем значения и сохраняем результат в `gradient`.
    let gradient = 2.0 * (parameter - 3.0);
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for rate in [0.1, 1.0, 2.0] {
        // Делаем ровно одно обновление, чтобы изолировать влияние скорости.
        let updated = parameter - rate * gradient;
        // Умножаем значения и сохраняем результат в `error`.
        let error = (updated - 3.0) * (updated - 3.0);
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("rate={rate}: параметр={updated}, ошибка={error}");
    }
}
