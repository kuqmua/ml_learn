// Сводная практика 01. Векторы и геометрия.
//
// Что повторяем вместе: сумма после попарного умножения координат, нормы L1/L2, расстояние, косинусное сходство.
// Зачем это нужно: Длина и угол между векторами позволяют измерять сходство объектов, представленных
//   числами.
// Что показывает программа: Задаём два двумерных вектора, чтобы проверить геометрию вручную. Вычисляем
//   евклидово расстояние из покоординатных разностей. Выводим сумму после попарного умножения координат, нормы и косинусное
//   сходство.
// Что проверить при изменении примера: Сравни ортогональные, одинаковые и противоположные векторы; проверь
//   симметрию расстояния.
// Дополнительная практика: Реализуй Vec<f64>: sum_after_multiplying_coordinates, norm, distance,
//   cosine; опиши ошибки длины и нулевого вектора.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Шаг: Задаём два двумерных вектора, чтобы проверить геометрию вручную.
    let first_vector = [3.0, 4.0];
    // Создаём набор значений `second_vector` для следующего шага примера.
    let second_vector = [-4.0, 3.0];
    /// Корень через итерацию Ньютона: x_(n+1) = (x_n + value / x_n) / 2.
    fn approximate_square_root_with_newton_method(value: f64) -> f64 {
        // Проверяем обязательное условие до дальнейшего вычисления.
        assert!(value >= 0.0, "корень из отрицательного числа");
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if value == 0.0 {
            // Завершаем текущий расчёт и возвращаем найденное значение.
            return 0.0;
        }
        // Создаём изменяемое значение `estimate` для следующих операций.
        let mut estimate = if value > 1.0 { value } else { 1.0 };
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for _ in 0..80 {
            // Обновляем `estimate` результатом текущего шага.
            estimate = (estimate + value / estimate) / 2.0;
        }
        // Используем ранее рассчитанное значение `estimate` в текущем выражении.
        estimate
    }

    // Шаг: Вычисляем евклидово расстояние из покоординатных разностей.
    let distance = (|| -> f64 {
        /* Суммируем квадраты разностей координат и извлекаем корень. */
        let first_vector: &[f64] = &first_vector;
        // Сохраняем рассчитанное значение `second_vector` для следующих операций.
        let second_vector: &[f64] = &second_vector;
        // Проверяем, что сравниваемые размерности или значения действительно совпадают.
        assert_eq!(first_vector.len(), second_vector.len());
        // Инициализируем изменяемый накопитель `squared_difference_sum` начальным состоянием.
        let mut squared_difference_sum = 0.0;
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for index in 0..first_vector.len() {
            // Комбинируем исходные величины и сохраняем результат в `difference`.
            let difference = first_vector[index] - second_vector[index];
            // Прибавляем очередной вклад к ранее накопленному результату.
            squared_difference_sum += difference * difference;
        }
        // Вызываем нужное вычисление с подготовленными аргументами.
        approximate_square_root_with_newton_method(squared_difference_sum)
    })();

    // Умножаем соответствующие координаты и складываем результаты; размерности должны совпадать.
    fn multiply_matching_coordinates_then_add(
        // `first_vector` задаёт соответствующее входное значение или поле структуры.
        first_vector: &[f64],
        // `second_vector` задаёт соответствующее входное значение или поле структуры.
        second_vector: &[f64],
    ) -> Result<f64, &'static str> {
        // Сопоставлять координаты можно только у векторов одинаковой длины.
        if first_vector.len() != second_vector.len() {
            // Прерываем расчёт и явно сообщаем причину некорректного входа.
            return Err("разные размерности");
        }
        // Инициализируем изменяемый накопитель `sum_after_multiplication` начальным состоянием.
        let mut sum_after_multiplication = 0.0;
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for index in 0..first_vector.len() {
            // Прибавляем очередной вклад к ранее накопленному результату.
            sum_after_multiplication += first_vector[index] * second_vector[index];
        }
        // Возвращаем успешное значение в типе `Result`.
        Ok(sum_after_multiplication)
    }

    // Объявляем повторно используемое вычисление `calculate_vector_length_from_coordinates`; параметры ниже задают его входы.
    fn calculate_vector_length_from_coordinates(first_vector: &[f64]) -> f64 {
        // Вызываем нужное вычисление с подготовленными аргументами.
        approximate_square_root_with_newton_method(
            // Извлекаем результат после проверки условий демонстрационного примера.
            multiply_matching_coordinates_then_add(first_vector, first_vector).unwrap(),
        )
    }

    // Шаг: Выводим сумму после попарного умножения координат, нормы и косинусное сходство.
    println!(
        // Задаём шаблон строки: плейсхолдеры ниже заменятся рассчитанными значениями.
        "сумма после попарного умножения координат={}, L1={}, L2={}, distance={distance:.3}, cosine={:.3}",
        // Извлекаем результат после проверки условий демонстрационного примера.
        multiply_matching_coordinates_then_add(&first_vector, &second_vector).unwrap(),
        // Составляем результат из вычисленных значений в указанном порядке.
        (|| -> f64 {
            /* Складываем модули всех координат вектора. */
            let vector: &[f64] = &first_vector;
            // Инициализируем изменяемый накопитель `absolute_sum` начальным состоянием.
            let mut absolute_sum = 0.0;
            // Повторяем следующий блок для каждого элемента указанной последовательности.
            for &component in vector {
                // Прибавляем очередной вклад к ранее накопленному результату.
                absolute_sum += (|| -> f64 {
                    /* Модуль числа по определению: меняем знак только у отрицательного числа. */
                    let value: f64 = component;
                    // Проверяем условие и выбираем соответствующую ветку алгоритма.
                    if value < 0.0 { -value } else { value }
                })();
            }
            // Используем ранее рассчитанное значение `absolute_sum` в текущем выражении.
            absolute_sum
        })(),
        // Вызываем нужное вычисление с подготовленными аргументами.
        calculate_vector_length_from_coordinates(&first_vector),
        // Составляем результат из вычисленных значений в указанном порядке.
        (|| -> Result<f64, &'static str> {
            /* Делим сумму после попарного умножения координат на результат умножения длин векторов. */
            let first_vector: &[f64] = &first_vector;
            // Сохраняем рассчитанное значение `second_vector` для следующих операций.
            let second_vector: &[f64] = &second_vector;
            // Косинус равен сумме после попарного умножения координат, делённой на результат умножения длин.
            let multiplied_lengths = calculate_vector_length_from_coordinates(first_vector)
                // Добавляем этот член в составное арифметическое выражение.
                * calculate_vector_length_from_coordinates(second_vector);
            // Проверяем условие и выбираем соответствующую ветку алгоритма.
            if multiplied_lengths == 0.0 {
                // Прерываем расчёт и явно сообщаем причину некорректного входа.
                return Err("нулевой вектор");
            }
            // Возвращаем успешное значение в типе `Result`.
            Ok(
                // Вызываем нужное вычисление с подготовленными аргументами.
                multiply_matching_coordinates_then_add(first_vector, second_vector)?
                    // Делим значения, получая нормированную величину или среднее.
                    / multiplied_lengths,
            )
        })()
        // Извлекаем значение: выше в примере обеспечено отсутствие ошибки.
        .unwrap()
    );
}
