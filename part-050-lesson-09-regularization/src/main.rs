// Урок 09.4. Регуляризация коэффициентов.
//
// Что изучаем: Регуляризация коэффициентов.
// Зачем это нужно: Штраф за большой вес добавляется к ошибке обучения и побуждает модель выбирать более
// простое решение.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `prediction_error` для следующих операций.
    let prediction_error = 1.0;
    // Сохраняем рассчитанное значение `weight` для следующих операций.
    let weight = 3.0;
    // Инициализируем значение `penalty_strength` начальным состоянием.
    let penalty_strength = 0.2;
    // Умножаем значения и сохраняем результат в `squared_weight`.
    let squared_weight = weight * weight;
    // Умножаем значения и сохраняем результат в `objective`.
    let objective = prediction_error + penalty_strength * squared_weight;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        "ошибка={prediction_error}, штраф={}, итог={objective}",
        // Умножаем величины согласно используемой формуле.
        penalty_strength * squared_weight
    );
    // График величин и зависимостей, изученных в этом уроке.
    let chart_points_0: Vec<(f64, f64)> = (-30..=30).map(|i| (i as f64 / 10.0, 1.0)).collect();
    let chart_points_1: Vec<(f64, f64)> = (-30..=30)
        .map(|i| {
            let w = i as f64 / 10.0;
            (w, 1.0 + w * w)
        })
        .collect();
    let chart = lesson_visualization::line_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Штраф за большой вес",
        "вес",
        "целевая функция",
        &[
            lesson_visualization::Series {
                name: "без регуляризации",
                points: &chart_points_0,
            },
            lesson_visualization::Series {
                name: "со штрафом",
                points: &chart_points_1,
            },
        ],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
