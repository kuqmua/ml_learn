// Урок 19.1. Прямой проход графа.
//
// Что изучаем: Прямой проход графа.
// Зачем это нужно: Каждый узел вычисляет значение из уже готовых входов; здесь f(x)=tanh(2x²) заменяем
// простой составной функцией 2x² для изоляции прямого прохода.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `x` для следующих операций.
    let x = 2.0;
    // Умножаем значения и сохраняем результат в `square`.
    let square = x * x;
    // Комбинируем исходные величины и сохраняем результат в `doubled_square`.
    let doubled_square = square + square;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("x={x}, x²={square}, 2x²={doubled_square}");
    // График величин и зависимостей, изученных в этом уроке.
    let chart_points_0: Vec<(f64, f64)> = (-30..=30)
        // Преобразуем каждый элемент в новое значение.
        .map(|i| {
            // Сохраняем результат этого шага в `x`.
            let x = i as f64 / 10.0;
            // Добавляем пару значений для сравнения или построения графика.
            (x, x * x)
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Собираем значения для `chart_points_1` в коллекцию.
    let chart_points_1: Vec<(f64, f64)> = (-30..=30)
        // Преобразуем каждый элемент в новое значение.
        .map(|i| {
            // Сохраняем результат этого шага в `x`.
            let x = i as f64 / 10.0;
            // Добавляем пару значений для сравнения или построения графика.
            (x, 2.0 * x * x)
        })
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Прямой проход вычислительного графа",
        // Указываем подпись горизонтальной оси.
        "x",
        // Указываем подпись вертикальной оси.
        "значение",
        // Передаём ряды или значения для отрисовки графика.
        &[
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "x²",
                // Передаём рассчитанные координаты точек.
                points: &chart_points_0,
            },
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "2x²",
                // Передаём рассчитанные координаты точек.
                points: &chart_points_1,
            },
        ],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
