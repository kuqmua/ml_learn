// Урок 21.6. Ранняя остановка.
//
// Что изучаем: Ранняя остановка.
// Зачем это нужно: Останавливаем обучение, если качество validation долго не улучшается, даже если число
// эпох ещё не исчерпано.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `validation_losses` для следующего шага примера.
    let validation_losses = [0.8, 0.6, 0.5, 0.52, 0.55, 0.58];
    // Сохраняем рассчитанное значение `patience` для следующих операций.
    let patience = 2;
    // Создаём изменяемое значение `best` для следующих операций.
    let mut best = f64::INFINITY;
    // Инициализируем изменяемый накопитель `bad_epochs` начальным состоянием.
    let mut bad_epochs = 0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for (epoch, loss) in validation_losses.into_iter().enumerate() {
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if loss < best {
            // Присваиваем вычисленное значение соответствующей переменной или полю.
            best = loss;
            // Присваиваем вычисленное значение соответствующей переменной или полю.
            bad_epochs = 0;
        } else {
            // Прибавляем очередной вклад к ранее накопленному результату.
            bad_epochs += 1;
        }
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if bad_epochs >= patience {
            // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
            println!("остановка на эпохе {epoch}, лучший loss={best}");
            // Останавливаем цикл после достижения условия завершения.
            break;
        }
    }
}
