// Урок 41.3. Награда за переход агента между состояниями.
// Зачем здесь эта тема: Агенту нужна оценка последствий перехода, чтобы различать полезные
//   действия.
// Почему код устроен так: Назначаем награду переходу и отдельно показываем новое состояние.
// Представь: Шаг к цели приносит награду; тот же шаг в другой ситуации может не принести её.
//
// Что изучаем: Награда.
// Зачем это нужно: Награда сообщает агенту, насколько полезным оказался переход, и формирует цель
// обучения.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Сохраняем рассчитанное значение `next_state` для следующих операций.
    let next_state: i32 = 4;
    lesson_trace::trace_step!(next_state);
    // Сохраняем рассчитанное значение `goal` для следующих операций.
    let goal: i32 = 4;
    lesson_trace::trace_step!(goal);
    // Комбинируем исходные величины и сохраняем результат в `reward`.
    let reward: f64 = if next_state == goal { 1.0 } else { -0.01 };
    lesson_trace::trace_step!(reward);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("после перехода награда={reward}");
}
