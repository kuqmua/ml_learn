//! Вычисления и примеры урока part-158-lesson-29-rag.

// Сводная практика 29. Retrieval augmented generation.
//
// Что повторяем вместе: контекст, ограничения длины, цитирование, проверка источника.
// Зачем это нужно: RAG связывает ответ с найденным источником и должен воздерживаться от ответа без
//   подходящей опоры.
// Что показывает программа: Ищем опору в локальных фрагментах и добавляем ссылку на выбранный источник. Для
//   неподтверждённого вопроса выводим отказ от ответа.
// Что проверить при изменении примера: Ответ содержит ссылки на использованные локальные фрагменты; при
//   отсутствии опоры сообщает об этом.
// Дополнительная практика: Собери прототип: retrieval из урока 28 плюс формирование ответа по найденным
//   фрагментам; генератор можно заменить шаблоном.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Фиксируем демонстрационные данные на время выполнения программы.
    const DOCUMENTS: [(&str, &str); 3] = [
        // Составляем результат из вычисленных значений в указанном порядке.
        (
            // Подставляем результаты в этот шаблон вывода или текстового значения.
            "rust.md",
            // Подставляем результаты в этот шаблон вывода или текстового значения.
            "Rust использует владение для управления памятью.",
        ),
        // Составляем результат из вычисленных значений в указанном порядке.
        (
            // Подставляем результаты в этот шаблон вывода или текстового значения.
            "ml.md",
            // Подставляем результаты в этот шаблон вывода или текстового значения.
            "Модель обучают на примерах и проверяют на отложенных данных.",
        ),
        // Составляем результат из вычисленных значений в указанном порядке.
        ("math.md", "Градиент указывает направление роста функции."),
    ];
    // Ответ формируется только по найденному локальному фрагменту с указанием источника.
    fn answer_from_matching_document_or_abstain(question: &str) -> String {
        // Убираем пунктуацию и слишком короткие слова вопроса.
        let query_terms: Vec<_> = question
            // Приводим текст к нижнему регистру для одинакового сравнения слов.
            .to_lowercase()
            // Разделяем текст по пробельным символам на отдельные слова.
            .split_whitespace()
            // Преобразуем каждый элемент последовательности.
            .map(|raw_word| {
                // Используем ранее рассчитанное значение `raw_word` в текущем выражении.
                raw_word
                    // Убираем знаки пунктуации по краям слова.
                    .trim_matches(|character: char| !character.is_alphabetic())
                    // Создаём собственную строку для хранения результата.
                    .to_string()
            })
            // Оставляем только элементы, прошедшие указанную проверку.
            .filter(|raw_word| raw_word.len() > 3)
            // Собираем элементы итератора в итоговую коллекцию.
            .collect();
        // Выбираем фрагмент с наибольшим числом совпавших слов.
        let best_match = DOCUMENTS
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Преобразуем каждый элемент последовательности.
            .map(|&(source_id, document)| {
                // Сохраняем рассчитанное значение `lower` для следующих операций.
                let lower = document.to_lowercase();
                // Сохраняем рассчитанное значение `score` для следующих операций.
                let score = query_terms
                    // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                    .iter()
                    // Оставляем только элементы, прошедшие указанную проверку.
                    .filter(|term| lower.contains(term.as_str()))
                    // Подсчитываем число элементов после отбора.
                    .count();
                // Составляем результат из вычисленных значений в указанном порядке.
                (score, source_id, document)
            })
            // Выбираем элемент с наибольшим значением указанного ключа.
            .max_by_key(|candidate| candidate.0)
            // Извлекаем значение: выше в примере обеспечено отсутствие ошибки.
            .unwrap();
        // Без совпадений нельзя ссылаться на источник как на подтверждение.
        if best_match.0 == 0 {
            // Подставляем результаты в этот шаблон вывода или текстового значения.
            "Нет подтверждения в локальных документах.".into()
        } else {
            // Формируем строковое представление значений по указанному шаблону.
            format!("{} [источник: {}]", best_match.2, best_match.1)
        }
    }

    // Шаг: Ищем опору в локальных фрагментах и добавляем ссылку на выбранный источник.
    println!(
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "{}",
        // Вызываем нужное вычисление с подготовленными аргументами.
        answer_from_matching_document_or_abstain("Как проверяют модель на данных?")
    );
    // Шаг: Для неподтверждённого вопроса выводим отказ от ответа.
    println!(
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "{}",
        // Вызываем нужное вычисление с подготовленными аргументами.
        answer_from_matching_document_or_abstain("Где рецепт пирога?")
    );
}
