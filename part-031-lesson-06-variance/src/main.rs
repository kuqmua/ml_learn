// Урок 06.3. Выборочная дисперсия.
//
// Что изучаем: Выборочная дисперсия.
// Зачем это нужно: Дисперсия усредняет квадраты отклонений от среднего. Для выборочной оценки делим на
// n−1.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `values` для следующего шага примера.
    let values = [2.0, 4.0, 6.0];
    assert!(
        values.len() >= 2,
        "для выборочной дисперсии нужны хотя бы два значения"
    );
    // Преобразуем входные данные и сохраняем полученную коллекцию в `mean`.
    let mean = values.iter().sum::<f64>() / values.len() as f64;
    // Инициализируем изменяемый накопитель `squared_deviation_sum` начальным состоянием.
    let mut squared_deviation_sum = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for value in values {
        // Комбинируем исходные величины и сохраняем результат в `deviation`.
        let deviation = value - mean;
        // Прибавляем очередной вклад к ранее накопленному результату.
        squared_deviation_sum += deviation * deviation;
    }
    // Считаем количество элементов и сохраняем его в `sample_variance`.
    let sample_variance = squared_deviation_sum / (values.len() - 1) as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("выборочная дисперсия = {sample_variance}");
}
