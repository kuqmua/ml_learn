// Урок 01.3. Евклидова норма L2.
//
// Что изучаем: Евклидова норма L2.
// Зачем это нужно: Изучаем длину вектора как корень из суммы квадратов координат. Корень считаем
// итерациями Ньютона: новое приближение равно среднему между текущим приближением и отношением числа к
// нему. Для [3, 4] ответ равен 5 по теореме Пифагора.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `vector` для следующего шага примера.
    let vector = [3.0, 4.0];
    // Инициализируем изменяемый накопитель `squared_length` начальным состоянием.
    let mut squared_length = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for coordinate in vector {
        // Возведение в квадрат делает оба вклада неотрицательными.
        squared_length += coordinate * coordinate;
    }
    // Положительное начальное значение защищает от деления на ноль.
    let mut estimate = if squared_length == 0.0 {
        // Используем фиксированное значение для этого варианта примера.
        0.0
    } else {
        // Используем ранее рассчитанное значение `squared_length` в текущем выражении.
        squared_length
    };
    // Проверяем условие и выбираем соответствующую ветку алгоритма.
    if squared_length > 0.0 {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for _ in 0..80 {
            // Итерация Ньютона приближает корень из суммы квадратов.
            estimate = (estimate + squared_length / estimate) / 2.0;
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("норма L2 = {estimate}");
}
