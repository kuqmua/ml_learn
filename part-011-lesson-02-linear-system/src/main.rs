// Урок 02.5. Система двух линейных уравнений.
//
// Что изучаем: Система двух линейных уравнений.
// Зачем это нужно: Решение Ax=b ищем по определителю матрицы 2×2. Нулевой определитель означает, что
// формула не даёт единственного решения.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Система: 2x + y = 5; x − y = 1.
    let (a, b, c, d) = (2.0, 1.0, 1.0, -1.0);
    // Сохраняем рассчитанное значение `(first_rhs, second_rhs)` для следующих операций.
    let (first_rhs, second_rhs) = (5.0, 1.0);
    // Умножаем значения и сохраняем результат в `determinant`.
    let determinant = a * d - b * c;
    // Проверяем обязательное условие до дальнейшего вычисления.
    assert!(determinant != 0.0, "нет единственного решения");
    // Формулы Крамера заменяют один столбец коэффициентов правой частью.
    let x = (first_rhs * d - b * second_rhs) / determinant;
    // Нормируем или усредняем величину делением и сохраняем её в `y`.
    let y = (a * second_rhs - first_rhs * c) / determinant;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("решение: x={x}, y={y}");
}
