// Урок 101. Сравнивать начальные центры по сумме квадратов расстояний до ближайшего центра.
// Выбор центров из разных скоплений здесь даёт меньшую начальную ошибку, чем выбор двух соседних
// точек.

fn main() {
    let points: [[f64; 2]; 4] = [[0.0, 0.0], [0.1, 0.0], [5.0, 5.0], [5.1, 5.0]];
    let start1: [[f64; 2]; 2] = [points[0], points[2]];
    let start2: [[f64; 2]; 2] = [points[0], points[1]];

    // Выполняем вычисления из примера.
    let _ = (&points, &start1, &start2);

    let error = |centers: [[f64; 2]; 2]| {
        points
            .iter()
            .map(|p| {
                centers
                    .iter()
                    .map(|c| (p[0] - c[0]).powi(2) + (p[1] - c[1]).powi(2))
                    .fold(f64::INFINITY, f64::min)
            })
            .sum::<f64>()
    };
    println!(
        "Центры из разных скоплений={start1:?}: начальная ошибка={}",
        error(start1)
    );
    println!(
        "Оба центра рядом={start2:?}: начальная ошибка={}",
        error(start2)
    );
    assert!(error(start1) < error(start2));
}

