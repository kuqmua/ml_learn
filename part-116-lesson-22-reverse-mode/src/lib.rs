//! Вычисления и примеры урока part-116-lesson-22-reverse-mode.

// Урок 22.1. Обратный режим дифференцирования.
//
// Что изучаем: Обратный режим дифференцирования.
// Зачем это нужно: Один обратный проход вычисляет градиенты скалярного результата по многим входам.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // f(x,y)=x*y+x.
    let (x, y) = (2.0, 3.0);
    // Умножаем значения и сохраняем результат в `multiplied_xy`.
    let multiplied_xy = x * y;
    // Комбинируем исходные величины и сохраняем результат в `output`.
    let output = multiplied_xy + x;
    // Комбинируем исходные величины и сохраняем результат в `derivative_by_x`.
    let derivative_by_x = y + 1.0;
    // Сохраняем рассчитанное значение `derivative_by_y` для следующих операций.
    let derivative_by_y = x;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("f={output}, df/dx={derivative_by_x}, df/dy={derivative_by_y}");
}
