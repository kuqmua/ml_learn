// Урок 10.2. Логарифмическая ошибка.
//
// Что изучаем: Логарифмическая ошибка.
// Зачем это нужно: Log-loss сильно штрафует уверенный неверный прогноз. Логарифм вероятности вычисляем
// через сходящийся ряд.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `target` для следующих операций.
    let target = 1.0;
    // Инициализируем значение `probability` начальным состоянием.
    let probability = 0.8;
    // Сохраняем рассчитанное значение `chosen_probability` для следующих операций.
    let chosen_probability = if target == 1.0 {
        // Используем ранее рассчитанное значение `probability` в текущем выражении.
        probability
    } else {
        // Складываем или вычитаем величины согласно используемой формуле.
        1.0 - probability
    };
    // Нормируем или усредняем величину делением и сохраняем её в `ratio`.
    let ratio = (chosen_probability - 1.0) / (chosen_probability + 1.0);
    // Создаём изменяемое значение `term` для следующих операций.
    let mut term = ratio;
    // Инициализируем изменяемый накопитель `logarithm` начальным состоянием.
    let mut logarithm = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for odd in (1..=99).step_by(2) {
        // Прибавляем очередной вклад к ранее накопленному результату.
        logarithm += term / odd as f64;
        // Умножаем накопленное значение на очередной множитель.
        term *= ratio * ratio;
    }
    // Умножаем накопленное значение на очередной множитель.
    logarithm *= 2.0;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("log-loss = {}", -logarithm);
}
