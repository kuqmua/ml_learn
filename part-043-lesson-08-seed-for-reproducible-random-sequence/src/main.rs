// Урок 08.1. Начальное число для воспроизводимой псевдослучайной последовательности.
// Почему этот урок сейчас: Случайное разбиение или обучение нельзя сравнить повторно без воспроизводимого источника случайности.
// Почему пример устроен так: Одинаковый seed должен давать одинаковую последовательность, а другой seed — другую.
//
// Что изучаем: Случайный seed.
// Зачем это нужно: Начальное состояние генератора делает псевдослучайную последовательность
// воспроизводимой.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Сохраняем рассчитанное значение `seed` для следующих операций.
    let seed: u64 = 42_u64;
    lesson_trace::trace_step!(seed);
    // Создаём изменяемое значение `state` для следующих операций.
    let mut state: u64 = seed;
    lesson_trace::trace_step!(state);
    // Печатаем три последовательных состояния, чтобы показать повторяемость при одном seed.
    for _ in 0..3 {
        // Это линейный конгруэнтный генератор: state ← 6364136223846793005·state + 1 (mod 2⁶⁴).
        // Фиксированные множитель и прибавка дают одну и ту же последовательность для одного seed.
        state = state.wrapping_mul(6364136223846793005).wrapping_add(1);
        lesson_trace::trace_step!(state);
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("состояние = {state}");
    }
}
