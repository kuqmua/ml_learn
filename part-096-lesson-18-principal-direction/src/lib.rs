//! Вычисления и примеры урока part-096-lesson-18-principal-direction.

// Урок 18.3. Главное направление PCA.
//
// Что изучаем: Главное направление PCA.
// Зачем это нужно: Собственное направление с наибольшей дисперсией служит первой осью PCA. На точках вдоль
// x эта ось совпадает с x.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Создаём набор значений `centered_points` для следующего шага примера.
    let centered_points = [[-2.0, 0.0], [-1.0, 0.0], [1.0, 0.0], [2.0, 0.0]];
    // Создаём набор значений `principal_axis` для следующего шага примера.
    let principal_axis = [1.0, 0.0];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for point in centered_points {
        // Умножаем значения и сохраняем результат в `projection`.
        let projection =
            lesson_001::multiply_matching_coordinates_then_add(&point, &principal_axis).unwrap();
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("точка={point:?}, координата на главной оси={projection}");
    }
}
