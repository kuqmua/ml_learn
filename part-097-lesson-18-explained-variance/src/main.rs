// Урок 18.4. Объяснённая дисперсия.
//
// Что изучаем: Объяснённая дисперсия.
// Зачем это нужно: Доля дисперсии главной оси показывает, сколько изменчивости сохраняет проекция на
// меньшее число измерений.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `eigenvalues` для следующего шага примера.
    let eigenvalues = [9.0, 1.0];
    // Комбинируем исходные величины и сохраняем результат в `total_variance`.
    let total_variance = eigenvalues[0] + eigenvalues[1];
    // Нормируем или усредняем величину делением и сохраняем её в `explained_fraction`.
    // При нулевой общей дисперсии доля первой оси не определена.
    assert!(
        total_variance > 0.0,
        "общая дисперсия должна быть положительной"
    );
    let explained_fraction = eigenvalues[0] / total_variance;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "первая ось сохраняет {:.1}% дисперсии",
        // Умножаем величины согласно используемой формуле.
        explained_fraction * 100.0
    );
}
