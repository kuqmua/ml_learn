// Урок 06.4. Квантили.
//
// Что изучаем: Квантили.
// Зачем это нужно: Квантиль указывает значение на выбранной доле упорядоченной выборки. Здесь используем
// ближайший порядковый элемент.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `values` для следующего шага примера.
    let mut values = [9, 1, 7, 3, 5];
    // Выполняем очередное действие, после которого продолжаем следующий шаг.
    values.sort();
    // Инициализируем значение `fraction` начальным состоянием.
    let fraction = 0.75;
    // Считаем количество элементов и сохраняем его в `index`.
    let index = ((values.len() - 1) as f64 * fraction) as usize;
    // Сохраняем рассчитанное значение `quantile` для следующих операций.
    let quantile = values[index];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("квантиль 0.75 = {quantile}, набор: {values:?}");
}
