// Урок 13.1. Условная независимость признаков.
//
// Что изучаем: Условная независимость признаков.
// Зачем это нужно: Наивный Байес предполагает независимость признаков при известном классе и перемножает
// их условные вероятности.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Инициализируем значение `prior_positive` начальным состоянием.
    let prior_positive = 0.5;
    // Инициализируем значение `word_one_given_positive` начальным состоянием.
    let word_one_given_positive = 0.8;
    // Инициализируем значение `word_two_given_positive` начальным состоянием.
    let word_two_given_positive = 0.6;
    // Умножаем значения и сохраняем результат в `joint_score`.
    let joint_score = prior_positive * word_one_given_positive * word_two_given_positive;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("оценка положительного класса = {joint_score}");
    // Сравниваем величины, вычисленные в примере.
    let chart = lesson_visualization::bars(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Условно независимые признаки",
        "вероятность",
        &[
            ("prior", prior_positive),
            ("слово 1", word_one_given_positive),
            ("слово 2", word_two_given_positive),
            ("совместно", joint_score),
        ],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
