// Урок 05.1. Условная вероятность.
//
// Что изучаем: Условная вероятность.
// Зачем это нужно: P(A|B) — доля случаев A среди тех, где уже произошло B. Знаменатель содержит только
// случаи B.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Среди 20 положительных тестов 8 действительно больных.
    let positive_tests = 20.0;
    // Сохраняем рассчитанное значение `sick_and_positive` для следующих операций.
    let sick_and_positive = 8.0;
    // Нормируем или усредняем величину делением и сохраняем её в `probability`.
    let probability = sick_and_positive / positive_tests;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("P(болен | тест положительный) = {probability}");
}
