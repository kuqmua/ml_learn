// Урок 175. Прибавлять результат преобразования к исходному входу по координатам.
// Так сохраняется прямой путь для исходной информации, а преобразование задаёт добавочную
// поправку.

fn main() {
    let input: [f64; 2] = [1.0, 2.0];
    let transformed: [f64; 2] = [0.2, -0.5];
    let output: [f64; 2] = [input[0] + transformed[0], input[1] + transformed[1]];

    // Выполняем вычисления из примера.
    let _ = (&input, &output);

    println!("Вход={input:?}; поправка={transformed:?}; сумма={output:?}");
    assert_eq!(output, [1.2, 1.5]);
    let zero_transform = [0.0, 0.0];
    assert_eq!(
        [input[0] + zero_transform[0], input[1] + zero_transform[1]],
        input
    );
    println!("При нулевой поправке вход проходит без изменения.");
}

