// Урок 43.2. Версия формата модели.
//
// Загрузчик различает поддерживаемый формат, другую версию и отсутствие строки версии.

fn main() {
    // Повторяем расчёт для каждого элемента последовательности.
    for (description, saved_model_text, expected) in [
        // Добавляем пару значений для сравнения или построения графика.
        ("поддерживаемый формат", "model_v1\n2.0\n1.0\n", "model_v1"),
        (
            // Передаём подпись или текстовое значение для следующего шага.
            "другая версия",
            // Передаём подпись или текстовое значение для следующего шага.
            "model_v2\n2.0\n1.0\n",
            // Передаём подпись или текстовое значение для следующего шага.
            "неизвестный формат",
        ),
        // Добавляем пару значений для сравнения или построения графика.
        ("пустой файл", "", "нет версии"),
    ] {
        // Сохраняем результат этого шага в `status`.
        let status = match saved_model_text.lines().next() {
            // Возвращаем присутствующее значение.
            Some("model_v1") => "model_v1",
            // Возвращаем присутствующее значение.
            Some(_) => "неизвестный формат",
            // Отмечаем отсутствие подходящего значения.
            None => "нет версии",
        };
        // Проверяем ожидаемое свойство учебного примера.
        assert_eq!(status, expected);
        // Печатаем рассчитанные значения для проверки примера.
        println!("{description}: {status}");
    }
}
