// Урок 110. Разбивать вычисление на промежуточные операции и выполнять их по порядку.
// Сохраняем квадрат входа и используем его дважды: такие зависимости нужны для дальнейшего
// вычисления производных.

fn main() {
    let x: f64 = 2.0;
    let square = x * x;
    let output = square + square;
    println!("Вход={x}; шаг 1: x*x={square}; шаг 2: квадрат+квадрат={output}");
    assert_eq!(output, 8.0);
    let changed_x = 3.0;
    let changed_square = changed_x * changed_x;
    let changed_output = changed_square + changed_square;
    println!(
        "Изменили вход на {changed_x}: нужно пересчитать и квадрат={changed_square}, и выход={changed_output}"
    );
    assert_eq!(changed_output, 18.0);
}

