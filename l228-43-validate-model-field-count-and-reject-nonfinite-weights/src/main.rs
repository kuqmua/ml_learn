// Урок 43.3. Проверка числа полей модели и отклонение бесконечных и неопределённых весов.
// Зачем здесь эта тема: Даже файл правильной версии может быть повреждён или содержать NaN.
// Почему код устроен так: Проверяем число полей и конечность весов до создания модели.
// Представь: Строку с недостающим весом или NaN нельзя молча превращать в готовую модель.
//
// Перед использованием проверяем число полей, числовой формат и конечность значений.
// Ошибочные строки показываем отдельно, не выдавая их за допустимую модель.

fn main() {
    for (_description, saved_model_text, should_be_valid) in [
        ("допустимая модель", "2.0\n1.0\n", true),
        ("не хватает поля", "2.0\n", false),
        ("лишнее поле", "2.0\n1.0\n3.0\n", false),
        ("вес не является числом", "abc\n1.0\n", false),
        ("бесконечный вес", "inf\n1.0\n", false),
    ] {
        let values: Vec<&str> = saved_model_text.lines().collect();
        let parsed_model_weights: Result<(f64, f64), &str> = if values.len() != 2 {
            Err("нужно ровно два параметра")
        } else {
            match (values[0].parse::<f64>(), values[1].parse::<f64>()) {
                (Ok(weight), Ok(constant_input_weight))
                    if weight.is_finite() && constant_input_weight.is_finite() =>
                {
                    Ok((weight, constant_input_weight))
                }

                _ => Err("параметры должны быть конечными числами"),
            }
        };
        assert_eq!(parsed_model_weights.is_ok(), should_be_valid);
    }
}

