// Урок 31.3. Вектор значения V для позиции механизма внимания.
// Почему этот урок сейчас: Высокая оценка совпадения указывает куда смотреть, но ещё не содержит передаваемой информации.
// Почему пример устроен так: Храним отдельный V, который попадёт во взвешенную сумму после расчёта весов.
//
// Что изучаем: Вектор значения V.
// Зачем это нужно: Value содержит информацию, которая будет перенесена в выход внимания после взвешивания.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Создаём набор значений `values` для следующего шага примера.
    let values: [[f64; 2]; 2] = [[1.0, 0.0], [0.0, 2.0]];
    lesson_trace::trace_step!(values);
    // Создаём набор значений `weights` для следующего шага примера.
    let weights: [f64; 2] = [0.25, 0.75];
    lesson_trace::trace_step!(weights);
    // Создаём набор значений `output` для следующего шага примера.
    let output: [f64; 2] = [
        // Умножаем величины согласно используемой формуле.
        weights[0] * values[0][0] + weights[1] * values[1][0],
        // Умножаем величины согласно используемой формуле.
        weights[0] * values[0][1] + weights[1] * values[1][1],
    ];
    lesson_trace::trace_step!(output);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("взвешенное значение = {output:?}");

    // Построение графика вынесено из основного кода урока.
    lesson_trace::disable();
    visualize_value_vector_for_attention_position(output);
}

// Строим график по результатам урока.
fn visualize_value_vector_for_attention_position(output: [f64; 2]) {
    // Сравнение величин из этого урока.
    let chart: std::path::PathBuf = lesson_visualization::bar_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок диаграммы.
        "Взвешенная сумма V",
        // Указываем подпись вертикальной оси.
        "компонента",
        // Передаём ряды или значения для отрисовки графика.
        &[("выход 0", output[0]), ("выход 1", output[1])],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
