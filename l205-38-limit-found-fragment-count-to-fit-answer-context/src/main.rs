// Урок 205. Сначала упорядочивать фрагменты по оценке, затем выбирать ограниченное число лучших.
// Проверяем нулевой и положительный лимиты; это ограничение числа фрагментов, не числа токенов.

fn main() {
    let mut passages = [
        ("слабый фрагмент", 0.1_f64),
        ("важный фрагмент", 0.9),
        ("дополнительный", 0.5),
    ];
    passages.sort_by(|a, b| b.1.total_cmp(&a.1));
    for capacity in [0, 1, 2] {
        let selected: Vec<_> = passages.iter().take(capacity).map(|p| p.0).collect();
        println!("Лимит фрагментов={capacity}: {selected:?}");
        assert_eq!(selected.len(), capacity);
        if capacity > 0 {
            assert_eq!(selected[0], "важный фрагмент");
        }
    }
}

