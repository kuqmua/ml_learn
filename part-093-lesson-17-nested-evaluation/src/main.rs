// Урок 17.3. Вложенная оценка.
//
// Что изучаем: Вложенная оценка.
// Зачем это нужно: Внутреннее разбиение выбирает гиперпараметр, а внешнее измеряет качество выбранной
// процедуры на новых данных.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `inner_scores` для следующего шага примера.
    let inner_scores: [(usize, f64); 3] = [(1, 0.70), (3, 0.85), (5, 0.80)];
    // Проверяем ожидаемое свойство учебного примера.
    assert!(
        // Используем подготовленное значение в следующем шаге примера.
        !inner_scores.is_empty(),
        // Передаём подпись или текстовое значение для следующего шага.
        "для выбора k нужна хотя бы одна оценка"
    );
    // Сохраняем рассчитанное значение `best` для следующих операций.
    let best = inner_scores
        // Перебираем элементы по ссылке, не копируя исходную коллекцию.
        .iter()
        // Выбираем k с максимальной оценкой на внутренней проверке.
        .max_by(|a, b| a.1.total_cmp(&b.1))
        // Извлекаем значение: выше в примере обеспечено отсутствие ошибки.
        .unwrap();
    // Внешние метки не участвовали в выборе k: они нужны только для итоговой оценки.
    let outer_truth = [true, false, true, false];
    // Создаём набор значений `outer_predictions` для следующего шага примера.
    let outer_predictions = [true, false, false, false];
    // Проверяем ожидаемое свойство учебного примера.
    assert_eq!(
        // Используем подготовленное значение в следующем шаге примера.
        outer_truth.len(),
        // Используем подготовленное значение в следующем шаге примера.
        outer_predictions.len(),
        // Передаём подпись или текстовое значение для следующего шага.
        "число прогнозов должно совпадать с числом ответов"
    );
    // Проверяем ожидаемое свойство учебного примера.
    assert!(
        // Используем подготовленное значение в следующем шаге примера.
        !outer_truth.is_empty(),
        // Передаём подпись или текстовое значение для следующего шага.
        "для внешней оценки нужен хотя бы один пример"
    );
    // Считаем количество элементов и сохраняем его в `outer_correct`.
    let outer_correct = (0..outer_truth.len())
        // Оставляем только элементы, прошедшие указанную проверку.
        .filter(|&index| outer_truth[index] == outer_predictions[index])
        // Подсчитываем число элементов после отбора.
        .count();
    // Считаем количество элементов и сохраняем его в `outer_test_accuracy`.
    let outer_test_accuracy = outer_correct as f64 / outer_truth.len() as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        "внутри выбрано k={}, внешняя оценка={outer_test_accuracy}",
        // Печатаем выбранное число соседей рядом с внешней оценкой.
        best.0
    );

    // Построение графика вынесено из основного кода урока.
    visualize(inner_scores);
}

// Строим график по результатам урока.
fn visualize(inner_scores: [(usize, f64); 3]) {
    // Значения из этого урока на графике.
    let chart_points_0: Vec<(f64, f64)> = inner_scores
        // Просматриваем элементы коллекции по ссылке.
        .iter()
        // Преобразуем каждый элемент в новое значение.
        .map(|&(k, score)| (k as f64, score))
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Выбор k внутри вложенной оценки",
        // Указываем подпись горизонтальной оси.
        "k",
        // Указываем подпись вертикальной оси.
        "внутренняя оценка",
        // Передаём ряды или значения для отрисовки графика.
        &[lesson_visualization::Series {
            // Указываем подпись этого ряда в легенде.
            name: "validation",
            // Передаём рассчитанные координаты точек.
            points: &chart_points_0,
        }],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
