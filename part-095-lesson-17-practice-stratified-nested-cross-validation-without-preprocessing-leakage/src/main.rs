// Сводная практика 17. Стратифицированная вложенная кросс-валидация без утечки.
//
// Что повторяем вместе: k-fold, стратификация, nested evaluation, утечка в preprocessing.
// Зачем это нужно: Кросс-валидация использует несколько разбиений для выбора параметра, сохраняя test для
//   итоговой оценки.
// Что показывает программа: Задаём данные для выбора числа соседей. Сравниваем значения гиперпараметра на
//   кросс-валидации. После выбора параметра один раз оцениваем качество на test.
// Что проверить при изменении примера: Каждый объект ровно один раз попадает в validation; test
//   используется один раз после выбора модели.
// Дополнительная практика: Реализуй k-fold подбор одного гиперпараметра для модели из предыдущих уроков.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Шаг: Задаём данные для выбора числа соседей.
    let training_examples: [(f64, bool); 9] = [
        // Учебный объект: признак 0., метка класса false.
        (0., false),
        // Учебный объект: признак 1., метка класса false.
        (1., false),
        // Учебный объект: признак 2., метка класса false.
        (2., false),
        // Учебный объект: признак 3., метка класса true.
        (3., true),
        // Учебный объект: признак 4., метка класса true.
        (4., true),
        // Учебный объект: признак 5., метка класса true.
        (5., true),
        // Учебный объект: признак 6., метка класса true.
        (6., true),
        // Учебный объект: признак 7., метка класса false.
        (7., false),
        // Учебный объект: признак 8., метка класса false.
        (8., false),
    ];

    // Учебные реализации математических операций для этого урока.

    // Объявляем повторно используемое вычисление `classify_feature_using_nearest_neighbors`; параметры ниже задают его входы.
    fn classify_feature_using_nearest_neighbors(
        // Получаем размеченные обучающие примеры по ссылке без копирования.
        training_examples: &[(f64, bool)],
        // `feature_value` задаёт соответствующее входное значение или поле структуры.
        feature_value: f64,
        // `neighbor_count` задаёт соответствующее входное значение или поле структуры.
        neighbor_count: usize,
        // Указываем тип возвращаемого значения.
    ) -> bool {
        // Проверяем ожидаемое свойство учебного примера.
        assert!(
            // Обновляем значение результатом текущего вычисления.
            neighbor_count > 0 && neighbor_count <= training_examples.len(),
            // Передаём подпись или текстовое значение для следующего шага.
            "число соседей должно быть от 1 до числа обучающих примеров"
        );
        // Создаём изменяемое значение `sorted_neighbors` для следующих операций.
        let mut sorted_neighbors: Vec<(f64, bool)> = training_examples
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Преобразуем каждый элемент последовательности.
            .map(|&(training_feature, label)| {
                // Составляем результат из вычисленных значений в указанном порядке.
                (
                    // Составляем результат из вычисленных значений в указанном порядке.
                    (|| -> f64 {
                        // Используем подготовленное значение в следующем шаге примера.
                        /* Модуль числа по определению: меняем знак только у отрицательного числа. */
                        // Сохраняем результат этого шага в `value`.
                        let value: f64 = training_feature - feature_value;
                        // Проверяем условие и выбираем соответствующую ветку алгоритма.
                        if value < 0.0 { -value } else { value }
                    })(),
                    // Используем ранее рассчитанное значение `label` в текущем выражении.
                    label,
                )
            })
            // Собираем элементы итератора в итоговую коллекцию.
            .collect();
        // Используем ранее рассчитанное значение `sorted_neighbors` в текущем выражении.
        sorted_neighbors
            // Упорядочиваем данные для следующего шага алгоритма.
            .sort_by(|left_result, right_result| left_result.0.total_cmp(&right_result.0));
        // Используем ранее рассчитанное значение `sorted_neighbors` в текущем выражении.
        sorted_neighbors
            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
            .iter()
            // Оставляем только заданное число лучших элементов.
            .take(neighbor_count)
            // Оставляем только элементы, прошедшие указанную проверку.
            .filter(|(_, label)| *label)
            // Подсчитываем число элементов после отбора.
            .count()
            // Добавляем этот член в составное арифметическое выражение.
            * 2
            // Сравниваем значения, чтобы получить булев результат.
            > neighbor_count
    }

    // Шаг: Сравниваем значения гиперпараметра на кросс-валидации.
    let best: (usize, f64) = [1, 3, 5]
        // Передаём владение элементами итератору для дальнейшей обработки.
        .into_iter()
        // Преобразуем каждый элемент последовательности.
        .map(|neighbor_count| {
            // Составляем результат из вычисленных значений в указанном порядке.
            (
                // Используем ранее рассчитанное значение `neighbor_count` в текущем выражении.
                neighbor_count,
                // Составляем результат из вычисленных значений в указанном порядке.
                (|| -> f64 {
                    // Используем подготовленное значение в следующем шаге примера.
                    /* Каждый объект один раз становится проверочным, остальные участвуют в обучении. */
                    // Сохраняем результат этого шага в `data`.
                    let data: &[(f64, bool)] = &training_examples;
                    // Сохраняем рассчитанное значение `neighbor_count` для следующих операций.
                    let neighbor_count: usize = neighbor_count;
                    // Сохраняем рассчитанное значение `fold_count` для следующих операций.
                    let fold_count: usize = 3;
                    // Проверяем ожидаемое свойство учебного примера.
                    assert!(data.len() >= fold_count, "для каждого блока нужен хотя бы один пример");
                    // Инициализируем изменяемый накопитель `correct_predictions` начальным состоянием.
                    let mut correct_predictions: usize = 0;
                    // Повторяем следующий блок для каждого элемента указанной последовательности.
                    for fold in 0..fold_count {
                        // Сохраняем рассчитанное значение `training_examples` для следующих операций.
                        let training_examples: Vec<(f64, bool)> = data
                            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                            .iter()
                            // Добавляем порядковый индекс к каждому элементу обхода.
                            .enumerate()
                            // Оставляем только элементы, прошедшие указанную проверку.
                            .filter(|(sample_index, _)| sample_index % fold_count != fold)
                            // Преобразуем каждый элемент последовательности.
                            .map(|(_, record)| *record)
                            // Собираем элементы итератора в итоговую коллекцию.
                            .collect();
                        // Повторяем следующий блок для каждого элемента указанной последовательности.
                        for (_, record) in data
                            // Перебираем элементы по ссылке, не копируя исходную коллекцию.
                            .iter()
                            // Добавляем порядковый индекс к каждому элементу обхода.
                            .enumerate()
                            // Оставляем только элементы, прошедшие указанную проверку.
                            .filter(|(sample_index, _)| sample_index % fold_count == fold)
                        {
                            // Прибавляем очередной вклад к ранее накопленному результату.
                            correct_predictions += usize::from(
                                // Вызываем нужное вычисление с подготовленными аргументами.
                                classify_feature_using_nearest_neighbors(
                                    // Передаём данные по ссылке или разыменовываем их для следующей операции.
                                    &training_examples,
                                    // Передаём очередное значение в составе результата или вызова.
                                    record.0,
                                    // Используем ранее рассчитанное значение `neighbor_count` в текущем выражении.
                                    neighbor_count,
                                // Обновляем значение результатом текущего вычисления.
                                ) == record.1,
                            );
                        }
                    }
                    // Делим значения, получая нормированную величину или среднее.
                    correct_predictions as f64 / data.len() as f64
                })(),
            )
        })
        // Сравниваем кандидатов и оставляем наибольший результат.
        .max_by(|left_result, right_result| left_result.1.total_cmp(&right_result.1))
        // Извлекаем значение: выше в примере обеспечено отсутствие ошибки.
        .unwrap();
    // Шаг: После выбора параметра один раз оцениваем качество на test.
    let test: [(f64, bool); 2] = [(2.5, false), (5.5, true)];
    // Сохраняем рассчитанное значение `accuracy` для следующих операций.
    let accuracy: f64 = test
        // Перебираем элементы по ссылке, не копируя исходную коллекцию.
        .iter()
        // Оставляем только элементы, прошедшие указанную проверку.
        .filter(|&&(feature_value, label)| {
            // Вызываем нужное вычисление с подготовленными аргументами.
            classify_feature_using_nearest_neighbors(&training_examples, feature_value, best.0)
                // Проверяем логическое условие для текущих элементов.
                == label
        })
        // Подсчитываем число элементов после отбора.
        .count() as f64
        // Делим значения, получая нормированную величину или среднее.
        / test.len() as f64;
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Задаём шаблон строки: плейсхолдеры ниже заменятся рассчитанными значениями.
        "selected k={}, CV={:.2}, test={accuracy:.2}",
        // Возвращаем найденные гиперпараметр и оценку его качества.
        best.0,
        // Передаём найденную оценку качества выбранного числа соседей.
        best.1
    );

    // Построение графика вынесено из основного кода урока.
    visualize_practice_stratified_nested_cross_validation_without_preprocessing_leakage(
        best, accuracy,
    );
}

