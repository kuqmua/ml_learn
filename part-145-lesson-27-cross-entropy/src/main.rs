// Урок 27.2. Cross-entropy языковой модели.
//
// Что изучаем: Cross-entropy языковой модели.
// Зачем это нужно: Средняя отрицательная логарифмическая вероятность измеряет, насколько модель уверена в
// правильных токенах.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `correct_token_probabilities` для следующего шага примера.
    let correct_token_probabilities = [0.8, 0.5];
    assert!(
        !correct_token_probabilities.is_empty(),
        "нужна хотя бы одна вероятность"
    );
    assert!(
        correct_token_probabilities
            .iter()
            .all(|&p| p > 0.0 && p <= 1.0),
        "вероятности должны быть больше 0 и не больше 1"
    );
    // Инициализируем изменяемый накопитель `negative_log_sum` начальным состоянием.
    let mut negative_log_sum = 0.0;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for probability in correct_token_probabilities {
        // Нормируем или усредняем величину делением и сохраняем её в `ratio`.
        let ratio = (probability - 1.0) / (probability + 1.0);
        // Создаём изменяемое значение `term` для следующих операций.
        let mut term = ratio;
        // Инициализируем изменяемый накопитель `logarithm` начальным состоянием.
        let mut logarithm = 0.0;
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for odd in (1..=99).step_by(2) {
            // Прибавляем очередной вклад к ранее накопленному результату.
            logarithm += term / odd as f64;
            // Умножаем накопленное значение на очередной множитель.
            term *= ratio * ratio;
        }
        // Вычитаем очередной вклад из текущего значения параметра.
        negative_log_sum -= 2.0 * logarithm;
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        "cross-entropy={:.3}",
        // Делим значения, получая нормированную величину или среднее.
        negative_log_sum / correct_token_probabilities.len() as f64
    );
}
