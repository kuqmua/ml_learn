// Урок 26.4. Feed-forward слой.
//
// Что изучаем: Feed-forward слой.
// Зачем это нужно: После внимания каждый токен отдельно проходит через линейное преобразование и
// нелинейную активацию.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `token` для следующего шага примера.
    let token = [1.0, 2.0];
    // Создаём набор значений `linear` для следующего шага примера.
    let linear = [
        // Умножаем величины согласно используемой формуле.
        0.5 * token[0] - 0.2 * token[1],
        // Умножаем величины согласно используемой формуле.
        0.3 * token[0] + 0.4 * token[1],
    ];
    // Создаём набор значений `activated` для следующего шага примера.
    let activated = [
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if linear[0] > 0.0 { linear[0] } else { 0.0 },
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if linear[1] > 0.0 { linear[1] } else { 0.0 },
    ];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("после feed-forward = {activated:?}");
    // Сравнение величин из этого урока.
    let chart = lesson_visualization::bars(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Feed-forward",
        "активация",
        &[("нейрон 0", activated[0]), ("нейрон 1", activated[1])],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
