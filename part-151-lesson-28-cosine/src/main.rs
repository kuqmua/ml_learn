// Урок 28.3. Косинусное сходство документов.
//
// Что изучаем: Косинусное сходство документов.
// Зачем это нужно: Нормировка суммы после попарного умножения координат позволяет сравнивать направления векторов слов, а не
// длину документов.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `query` для следующего шага примера.
    let query = [1.0, 0.0];
    // Создаём набор значений `document` для следующего шага примера.
    let document = [2.0, 0.0];
    // Умножаем значения и сохраняем результат в `sum_after_multiplying_coordinates`.
    let sum_after_multiplying_coordinates = query[0] * document[0] + query[1] * document[1];
    // Умножаем значения и сохраняем результат в `query_squared`.
    let query_squared = query[0] * query[0] + query[1] * query[1];
    // Умножаем значения и сохраняем результат в `document_squared`.
    let document_squared = document[0] * document[0] + document[1] * document[1];
    // Умножаем значения и сохраняем результат в `squared_scale`.
    let squared_scale = query_squared * document_squared;
    // Проверяем обязательное условие до дальнейшего вычисления.
    assert!(squared_scale > 0.0, "нулевой вектор не имеет направления");
    // Создаём изменяемое значение `scale` для следующих операций.
    let mut scale = squared_scale;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for _ in 0..80 {
        // Присваиваем вычисленное значение соответствующей переменной или полю.
        scale = (scale + squared_scale / scale) / 2.0;
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!(
        "косинусное сходство={}",
        sum_after_multiplying_coordinates / scale
    );
}
