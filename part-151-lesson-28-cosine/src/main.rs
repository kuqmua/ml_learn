// Урок 28.3. Косинусное сходство документов.
//
// Что изучаем: Косинусное сходство документов.
// Зачем это нужно: Нормировка суммы после попарного умножения координат позволяет сравнивать направления векторов слов, а не
// длину документов.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `query` для следующего шага примера.
    let query = [1.0, 0.0];
    // Создаём набор значений `document` для следующего шага примера.
    let document = [2.0, 0.0];
    // Тот же косинус из урока 01.5 теперь сравнивает векторы слов документов.
    let similarity = lesson_005::cosine_similarity(&query, &document)
        .expect("ненулевые векторы слов одинаковой размерности");
    println!("косинусное сходство={similarity}");
    let points: Vec<(f64, f64)> = (0..=180)
        .step_by(5)
        .map(|degrees| {
            let angle = (degrees as f64).to_radians();
            let rotated_document = [angle.cos(), angle.sin()];
            (
                degrees as f64,
                lesson_005::cosine_similarity(&query, &rotated_document).unwrap(),
            )
        })
        .collect();
    let chart = lesson_visualization::line_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Сходство документов при изменении направления",
        "угол, градусы",
        "косинус",
        &[lesson_visualization::Series {
            name: "сходство",
            points: &points,
        }],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
