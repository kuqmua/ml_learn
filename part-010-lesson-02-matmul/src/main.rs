// Урок 02.4. Умножение матриц.
//
// Что изучаем: Умножение матриц.
// Зачем это нужно: Для каждой ячейки ответа умножаем элементы строки и столбца попарно и складываем результаты.
// Внутренние размеры должны совпадать.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `left` для следующего шага примера.
    let left = [[1, 2], [3, 4]];
    // Создаём набор значений `right` для следующего шага примера.
    let right = [[5, 6], [7, 8]];
    // Создаём набор значений `result` для следующего шага примера.
    let mut result = [[0; 2]; 2];
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for row in 0..2 {
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for column in 0..2 {
            // Повторяем следующий блок для каждого элемента указанной последовательности.
            for shared in 0..2 {
                // Общий индекс соединяет строку левой матрицы со столбцом правой.
                result[row][column] += left[row][shared] * right[shared][column];
            }
        }
    }
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("A·B = {result:?}");
}
