// Урок 44.3. Сообщение об ошибочных входных данных с номером строки.
// Связь с принятой терминологией: Сообщение ошибок ввода инференса с номером строки.
// Зачем здесь эта тема: При плохой строке пользователю нужно знать, где исправлять файл.
// Почему код устроен так: Добавляем номер строки к ошибке разбора и не теряем исходный контекст.
// Представь: Ошибка «не число» полезнее, когда указано: «строка 7: не число».
//
// Что изучаем: Ошибки входных данных.
// Зачем это нужно: Некорректную строку сообщаем явно вместе с её номером, не выдавая ошибочный прогноз.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
use lesson_trace::{enable, trace_note, trace_step};

fn main() {
    enable();
    trace_note!("Создаём набор значений `rows` для следующего шага примера.");
    let rows: [&str; 3] = ["1.0", "oops", "3.0"];
    trace_step!(rows);
    trace_note!("Повторяем следующий блок для каждого элемента указанной последовательности.");
    for (index, row) in rows.into_iter().enumerate() {
        trace_step!(index);
        trace_step!(row);
        trace_note!("Разбираем каждый возможный вариант значения отдельно.");
        trace_note!("Возвращаем успешное значение в типе `Result`.");
        trace_note!("Возвращаем описание ошибки в типе `Result`.");
        match row.parse::<f64>() {
            Ok(value) => println!("строка {}: {value}", index + 1),

            Err(_) => println!("строка {}: не число", index + 1),
        }
    }
}
