// Урок 233. Обрабатывать ошибки разбора, сохраняя номер и исходное содержимое строки.
// Показываем корректные числа и понятное сообщение о неверной строке вместо молчаливого пропуска.

fn main() {
    let rows = ["1.0", "oops", "3.0"];
    let mut errors = Vec::new();
    for (index, row) in rows.into_iter().enumerate() {
        match row.parse::<f64>() {
            Ok(value) => println!("Строка {}: число={value}", index + 1),
            Err(_) => {
                let message = format!("строка {}: не число: {row}", index + 1);
                eprintln!("{message}");
                errors.push(message);
            }
        }
    }
    assert_eq!(errors, vec!["строка 2: не число: oops"]);
}

