//! Вычисления и примеры урока part-020-lesson-04-convergence.

// Урок 04.2. Сходимость градиентного спуска.
//
// Что изучаем: Сходимость градиентного спуска.
// Зачем это нужно: Последовательность шагов должна приближаться к минимуму. Останавливаемся по малому
// градиенту, а не только по числу эпох.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
pub fn run() {
    // Инициализируем изменяемый накопитель `parameter` начальным состоянием.
    let mut parameter = 0.0;
    // Инициализируем значение `rate` начальным состоянием.
    let rate = 0.2;
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for epoch in 0..100 {
        // Умножаем значения и сохраняем результат в `gradient`.
        let gradient = 2.0 * (parameter - 3.0);
        // Проверяем условие и выбираем соответствующую ветку алгоритма.
        if gradient > -0.000001 && gradient < 0.000001 {
            // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
            println!("сошлись за {epoch} шагов: параметр={parameter}");
            // Останавливаем цикл после достижения условия завершения.
            break;
        }
        // Вычитаем очередной вклад из текущего значения параметра.
        parameter -= rate * gradient;
    }
}
