// Что изучаем: Стратифицированное разбиение.
// Зачем это нужно: Сохраняем примерно одинаковую долю классов в каждой части, особенно когда положительный
// класс редок.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `positive` для следующего шага примера.
    let positive = [1, 3, 5, 7];
    // Создаём набор значений `negative` для следующего шага примера.
    let negative = [0, 2, 4, 6];
    // Создаём набор значений `first_fold` для следующего шага примера.
    let first_fold = [positive[0], positive[1], negative[0], negative[1]];
    // Создаём набор значений `second_fold` для следующего шага примера.
    let second_fold = [positive[2], positive[3], negative[2], negative[3]];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("fold 1={first_fold:?}, fold 2={second_fold:?}");
}
