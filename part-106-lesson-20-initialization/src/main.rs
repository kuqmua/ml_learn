// Урок 20.4. Инициализация весов.
//
// Что изучаем: Инициализация весов.
// Зачем это нужно: Начальные веса задают разные ответы нейронов до обучения; одинаковые веса затрудняют
// разделение их ролей.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `first_neuron` для следующего шага примера.
    let first_neuron = [0.2, -0.3];
    // Создаём набор значений `second_neuron` для следующего шага примера.
    let second_neuron = [-0.1, 0.4];
    // Создаём набор значений `input` для следующего шага примера.
    let input = [1.0, 2.0];
    // Умножаем значения и сохраняем результат в `first_output`.
    let first_output = first_neuron[0] * input[0] + first_neuron[1] * input[1];
    // Умножаем значения и сохраняем результат в `second_output`.
    let second_output = second_neuron[0] * input[0] + second_neuron[1] * input[1];
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("разные начальные ответы: {first_output}, {second_output}");
}
