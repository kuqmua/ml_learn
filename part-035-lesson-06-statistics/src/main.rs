// Сводная практика 06. Выборочная статистика.
//
// Что повторяем вместе: среднее, медиана, дисперсия, квантили, доверительный интервал, bootstrap.
// Зачем это нужно: Среднее, медиана и дисперсия описывают данные разными способами; пустые и неверные
//   строки требуют отдельной обработки.
// Что показывает программа: Читаем числовую колонку и пропускаем пустую строку. Сортируем значения, чтобы
//   вычислить медиану. Показываем среднее, медиану и выборочную дисперсию.
// Что проверить при изменении примера: Проверь на малом наборе вручную; сравни интервалы bootstrap при
//   разных размерах выборки.
// Дополнительная практика: Напиши статистический отчёт по CSV-столбцу; отдельно обработай пропуски и
//   нечисловые значения.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Фиксируем демонстрационные данные на время выполнения программы.
    const SAMPLE_CSV: &str = "value\n2\n4\n\n6\n8\n";

    // Шаг: Читаем числовую колонку и пропускаем пустую строку.
    let mut values = (|| -> Result<Vec<f64>, String> {
        /* Читаем числовые значения из строк CSV, пропуская пустые строки. */
        let csv_content: &str = SAMPLE_CSV;
        // Используем ранее рассчитанное значение `csv_content` в текущем выражении.
        csv_content
            // Разбиваем текст на строки для последовательной обработки.
            .lines()
            // Пропускаем первые элементы, которые не входят в полезные данные.
            .skip(1)
            // Оставляем только элементы, прошедшие указанную проверку.
            .filter(|value_text| !value_text.trim().is_empty())
            // Добавляем порядковый индекс к каждому элементу обхода.
            .enumerate()
            // Преобразуем каждый элемент последовательности.
            .map(|(row_index, value_text)| {
                // Используем ранее рассчитанное значение `value_text` в текущем выражении.
                value_text
                    // Преобразуем текстовое поле CSV в число с плавающей точкой.
                    .parse::<f64>()
                    // Складываем или вычитаем величины согласно используемой формуле.
                    .map_err(|_| format!("строка {}: не число", row_index + 2))
            })
            // Собираем элементы итератора в итоговую коллекцию.
            .collect()
    })()
    // Извлекаем значение: выше в примере обеспечено отсутствие ошибки.
    .unwrap();
    // Шаг: Сортируем значения, чтобы вычислить медиану.
    values.sort_by(f64::total_cmp);

    // Учебные реализации математических операций для этого урока.

    // Объявляем повторно используемое вычисление `calculate_arithmetic_mean`; параметры ниже задают его входы.
    fn calculate_arithmetic_mean(values: &[f64]) -> f64 {
        // Инициализируем изменяемый накопитель `total` начальным состоянием.
        let mut total = 0.0;
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for &value in values {
            // Прибавляем очередной вклад к ранее накопленному результату.
            total += value;
        }
        // Делим значения, получая нормированную величину или среднее.
        total / values.len() as f64
    }

    // Шаг: Показываем среднее, медиану и выборочную дисперсию.
    println!(
        // Задаём шаблон строки: плейсхолдеры ниже заменятся рассчитанными значениями.
        "n={}, mean={}, median={}, sample variance={:.3}",
        // Передаём очередное значение в составе результата или вызова.
        values.len(),
        // Вызываем нужное вычисление с подготовленными аргументами.
        calculate_arithmetic_mean(&values),
        // Составляем результат из вычисленных значений в указанном порядке.
        (values[1] + values[2]) / 2.0,
        // Составляем результат из вычисленных значений в указанном порядке.
        (|| -> f64 {
            /* Деление на n−1 даёт несмещённую оценку дисперсии по выборке. */
            let values: &[f64] = &values;
            // Сохраняем рассчитанное значение `average` для следующих операций.
            let average = calculate_arithmetic_mean(values);
            // Инициализируем изменяемый накопитель `squared_deviation_sum` начальным состоянием.
            let mut squared_deviation_sum = 0.0;
            // Повторяем следующий блок для каждого элемента указанной последовательности.
            for &value in values {
                // Прибавляем очередной вклад к ранее накопленному результату.
                squared_deviation_sum += (|| -> f64 {
                    /* Возводим число в квадрат обычным умножением. */
                    let value: f64 = value - average;
                    // Умножаем величины согласно используемой формуле.
                    value * value
                })();
            }
            // Делим значения, получая нормированную величину или среднее.
            squared_deviation_sum / (values.len() - 1) as f64
        })()
    );
}
