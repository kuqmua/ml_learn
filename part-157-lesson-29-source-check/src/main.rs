// Что изучаем: Проверка источника.
// Зачем это нужно: Если подходящего подтверждения нет, система должна явно воздержаться от ответа.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Инициализируем значение `retrieval_score` начальным состоянием.
    let retrieval_score = 0.1;
    // Инициализируем значение `minimum_reliable_score` начальным состоянием.
    let minimum_reliable_score = 0.5;
    // Сохраняем рассчитанное значение `answer` для следующих операций.
    let answer = if retrieval_score >= minimum_reliable_score {
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "подтверждённый ответ"
    } else {
        // Подставляем результаты в этот шаблон вывода или текстового значения.
        "нет надёжного источника"
    };
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("{answer}");
}
