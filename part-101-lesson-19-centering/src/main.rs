// Урок 19.1. Центрирование признаков.
//
// Что изучаем: Центрирование признаков.
// Зачем это нужно: Вычитаем среднее из каждой координаты, чтобы PCA искал направления изменчивости
// относительно центра данных.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Создаём набор значений `values` для следующего шага примера.
    let values = [1.0, 2.0, 3.0];
    // Проверяем ожидаемое свойство учебного примера.
    assert!(
        // Используем подготовленное значение в следующем шаге примера.
        !values.is_empty(),
        // Передаём подпись или текстовое значение для следующего шага.
        "для центрирования нужно хотя бы одно значение"
    );
    // Преобразуем входные данные и сохраняем полученную коллекцию в `mean`.
    let mean = lesson_029::mean(&values).unwrap();
    // Преобразуем входные данные и сохраняем полученную коллекцию в `centered`.
    let centered: Vec<_> = values.iter().map(|&value| value - mean).collect();
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("среднее={mean}, центрированные значения={centered:?}");

    // Построение графика вынесено из основного кода урока.
    visualize(values, centered);
}

// Строим график по результатам урока.
fn visualize(values: [f64; 3], centered: std::vec::Vec<f64>) {
    // График величин и зависимостей, изученных в этом уроке.
    let chart_points_0: Vec<(f64, f64)> = values
        // Просматриваем элементы коллекции по ссылке.
        .iter()
        // Добавляем порядковый номер к каждому элементу.
        .enumerate()
        // Преобразуем каждый элемент в новое значение.
        .map(|(i, &v)| (i as f64, v))
        // Собираем результаты в коллекцию.
        .collect();
    // Собираем значения для `chart_points_1` в коллекцию.
    let chart_points_1: Vec<(f64, f64)> = centered
        // Просматриваем элементы коллекции по ссылке.
        .iter()
        // Добавляем порядковый номер к каждому элементу.
        .enumerate()
        // Преобразуем каждый элемент в новое значение.
        .map(|(i, &v)| (i as f64, v))
        // Собираем результаты в коллекцию.
        .collect();
    // Строим график по рассчитанным значениям и сохраняем его как SVG.
    let chart = lesson_visualization::line_chart(
        // Передаём путь к каталогу текущего урока.
        env!("CARGO_MANIFEST_DIR"),
        // Указываем имя SVG-файла.
        "lesson-chart",
        // Указываем заголовок графика.
        "Центрирование признака",
        // Указываем подпись горизонтальной оси.
        "номер наблюдения",
        // Указываем подпись вертикальной оси.
        "значение",
        // Передаём ряды или значения для отрисовки графика.
        &[
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "исходные",
                // Передаём рассчитанные координаты точек.
                points: &chart_points_0,
            },
            // Добавляем ряд данных с подписью к графику.
            lesson_visualization::Series {
                // Указываем подпись этого ряда в легенде.
                name: "центрированные",
                // Передаём рассчитанные координаты точек.
                points: &chart_points_1,
            },
        ],
    )
    // Прерываем пример с понятной ошибкой, если SVG не удалось записать.
    .expect("не удалось сохранить график");
    // Печатаем путь к созданному SVG, чтобы его можно было открыть.
    println!("график: {}", chart.display());
}
