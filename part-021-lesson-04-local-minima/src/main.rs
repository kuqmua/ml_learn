// Урок 04.3. Локальные минимумы.
//
// Что изучаем: Локальные минимумы.
// Зачем это нужно: У невыпуклой функции разные начальные точки могут привести к разным минимумам.
// Исследуем f(x)=x⁴−2x².
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Повторяем следующий блок для каждого элемента указанной последовательности.
    for start in [-0.5, 0.5] {
        // Создаём изменяемое значение `x` для следующих операций.
        let mut x = start;
        // Повторяем следующий блок для каждого элемента указанной последовательности.
        for _ in 0..100 {
            // Производная равна 4x³−4x; шагаем против её знака.
            let gradient = 4.0 * x * x * x - 4.0 * x;
            // Вычитаем очередной вклад из текущего значения параметра.
            x -= 0.1 * gradient;
        }
        // Умножаем значения и сохраняем результат в `loss`.
        let loss = x * x * x * x - 2.0 * x * x;
        // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
        println!("старт={start}, найдено x={x:.3}, f(x)={loss:.3}");
    }
    // Наглядное представление величин из этого урока.
    let chart_points_0: Vec<(f64, f64)> = (-150..=150)
        .map(|i| {
            let x = i as f64 / 100.0;
            (x, x * x * x * x - 2.0 * x * x)
        })
        .collect();
    let chart = lesson_visualization::line_chart(
        env!("CARGO_MANIFEST_DIR"),
        "lesson-chart",
        "Два локальных минимума",
        "x",
        "f(x)",
        &[lesson_visualization::Series {
            name: "x⁴−2x²",
            points: &chart_points_0,
        }],
    )
    .expect("не удалось сохранить график");
    println!("график: {}", chart.display());
}
