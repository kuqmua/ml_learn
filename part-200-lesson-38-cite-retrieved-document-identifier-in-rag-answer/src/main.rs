// Урок 38.3. Указание идентификатора найденного документа в ответе RAG.
//
// Что изучаем: Цитирование источника.
// Зачем это нужно: Ответ сопровождаем идентификатором найденного документа, чтобы пользователь мог
// проверить основание.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    lesson_trace::enable();
    // Сохраняем рассчитанное значение `source_identifier` для следующих операций.
    let source_identifier: &str = "docs/rust/cargo";
    lesson_trace::trace_step!(source_identifier);
    // Сохраняем рассчитанное значение `fact` для следующих операций.
    let fact: &str = "Cargo собирает проект";
    lesson_trace::trace_step!(fact);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("{fact} [источник: {source_identifier}]");
}
