// Урок 059. Превращать вероятность в выбор класса сравнением с порогом.
// Меняя порог, можно менять решения, не меняя сами вероятности модели.

fn main() {
    let probabilities = [0.2, 0.55, 0.8];
    let low = probabilities.map(|p| p >= 0.5);
    let high = probabilities.map(|p| p >= 0.7);
    println!("Вероятности={probabilities:?}; порог 0.5: {low:?}; порог 0.7: {high:?}");
    assert_eq!(low, [false, true, true]);
    assert_eq!(high, [false, false, true]);
    println!("Прогноз 0.55 сменил класс, хотя сама модель не менялась.");
}

