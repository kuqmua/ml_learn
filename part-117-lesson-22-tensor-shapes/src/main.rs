// Урок 22.2. Формы тензоров.
//
// Что изучаем: Формы тензоров.
// Зачем это нужно: Форма определяет число осей и размер каждой оси; несовместимые размеры нельзя умножать
// как матрицы.
// Что делает пример: на небольших проверяемых данных вычисляет результат этой темы и печатает его.
// Как проверить понимание: предскажи вывод до запуска, затем измени одно входное значение и объясни
// изменение результата.

// Точка входа: все определения и шаги примера выполняются внутри этой функции.
fn main() {
    // Сохраняем рассчитанное значение `left_shape` для следующих операций.
    let left_shape = (2, 3);
    // Сохраняем рассчитанное значение `right_shape` для следующих операций.
    let right_shape = (3, 4);
    // Проверяем, что сравниваемые размерности или значения действительно совпадают.
    assert_eq!(left_shape.1, right_shape.0);
    // Сохраняем рассчитанное значение `result_shape` для следующих операций.
    let result_shape = (left_shape.0, right_shape.1);
    // Выводим рассчитанные значения, чтобы сравнить их с ожидаемым поведением.
    println!("{left_shape:?} × {right_shape:?} -> {result_shape:?}");
}
